"""Контракт хранилища тредов: файлы — реализация, а не устройство ядра.

Зачем. Встраивающий должен уметь положить историю треда в базу, а не в
``data_*.jsonl``, и передать своё хранилище агенту при создании. Сегодня путь к
диску зашит: ``ThreadSession`` ходит в модульные функции ``thread_store``, а
ядро вдобавок зовёт их напрямую в четырёх местах.

Форма — ``Protocol``, а не наследуемый ABC, и это не вкусовщина. Свой урок:
``FsBackend`` сделан ABC с **31 абстрактным методом**, его реализуют снаружи, и
чем это кончилось — записано в докстроке ``backends/async_protocol``: «Добавить
туда async-двойники всех методов значило бы сломать каждую такую реализацию».
Пришлось заводить отдельный ``AsyncExecPort`` — уже ``Protocol``. Толстый ABC,
который реализуют ЧУЖИЕ, развивать нельзя: любой новый метод ломает всех.

Второй урок — из ``TaskStore`` в TUI. Там протокол объявлен, но не держится: в
нём 4 метода против 12 публичных у ``FileTaskStore``, а само слово ``TaskStore``
встречается во всём TUI ровно один раз — в файле, где объявлено. Все четыре
потребителя импортируют конкретный класс. Вторая реализация удовлетворит
протокол и всё равно не заработает.

Поэтому здесь три правила, и они важнее самого контракта:

1. **Контракт покрывает всё, чем пользуются.** Методы ниже выведены из
   фактических обращений (AST-обход ядра: 11 прямых вызовов + собственный
   ввод-вывод ``ThreadSession``), а не придуманы «на вырост».
2. **Потребители типизируются протоколом, фабрика одна.** Не
   ``FileThreadStore(...)`` в четырёх местах, а ``ctx.thread_store``.
3. **Есть гейт, который краснеет при отступлении** — прогон агента на
   in-memory реализации, не создавший ни одного файла. Именно его отсутствие и
   сгноило ``TaskStore``.

Границы. Здесь ТОЛЬКО то, что нужно ядру: один тред, чтение и запись. Листинг
всех тредов и хвостовое чтение по курсору — нужды UI, у агента их нет: он
работает с одним тредом и читает историю один раз на старте. Их место — в
более широком контракте ``TaskStore``, который расширяет этот и реализуется тем
же бэкендом.

Почему сигнатур мало и они дополнены гейтом
-------------------------------------------

``@runtime_checkable`` проверяет ТОЛЬКО наличие атрибутов — ни сигнатур, ни
корутинности, ни форм. Проверено запуском: у класса, где все одиннадцать
методов объявлены ``async def``, ``isinstance(store, ThreadStore)`` истинно, и
структурный тест зелёный, а восемь поведенческих — красные. Ошибка при этом
симметрична: законное прокси-хранилище на ``__getattr__`` ``isinstance`` НЕ
пройдёт, потому что в 3.12 проверка ходит через ``getattr_static``.

Отсюда правило: ``isinstance`` — не гейт. Гейт — исполняемый конформанс-набор
``gc_testkit.thread_store_conformance.assert_conforms``, и его чужая реализация
запускает у себя одной строкой. Типы ниже — спецификация для человека и вход
для этого набора; статического типчекера в репозитории нет, и притворяться, что
аннотации что-то гарантируют сами по себе, не следует.

Что здесь закреплено вторым заходом
-----------------------------------

Первая редакция контракта описывала методы, но не свойства — и две наши
собственные реализации успели разойтись в четырёх местах, оставаясь зелёными на
всём наборе. Все четыре теперь записаны явно и проверяются:

* третий элемент ``load_thread_state`` — НОМЕР последнего выданного ``seq``, а
  не количество записей (расходятся после ``discard_message``);
* ``known_keys`` мутируется НА МЕСТЕ и пополняется только фактически
  записанными ключами;
* реализация обязана гарантировать ``id`` у сообщения на чтении;
* запись трассы субагента содержит все шесть полей, включая ``ts`` и ``seq``.
"""
from __future__ import annotations

from typing import (
    Any,
    Dict,
    List,
    Literal,
    NamedTuple,
    Optional,
    Protocol,
    Sequence,
    Set,
    TypedDict,
    runtime_checkable,
)

#: Ключ идемпотентности одного сообщения. Формат задаёт
#: :func:`gc_core.thread_store.make_message_key` и ТОЛЬКО она: ``"id:<id>"``,
#: если у сообщения непустой строковый ``id``, иначе ``"payload:"`` плюс
#: ``json.dumps(message, ensure_ascii=False, sort_keys=True)``.
#:
#: Своим форматом ключи не изобретаются: ветка ``payload:`` нестабильна к
#: любому изменению словаря, поэтому реализация обязана давать сообщениям ``id``
#: (см. ``load_thread_state``), а не полагаться на неё.
MessageKey = str

#: Вид записи в трассе субагента. Множество замкнутое — эти шесть значений
#: приходят из ``processing_responses`` и ``tools/subagents/runner``.
TraceKind = Literal[
    "call", "user", "intermediate_reply", "child_summary", "error", "finished",
]


class ThreadState(NamedTuple):
    """История треда вместе со служебным — то, что ядру нужно на старте.

    Именованный кортеж, а не голая тройка, ровно по одной причине: третий
    элемент — ``int``, и перепутать «сколько записей» с «номер последнего
    seq» не поймает ни одна проверка типов. Одно это значение уже носит в
    ядре четыре имени на трёх строках (``max_seq`` при распаковке →
    параметр ``persisted_messages_count`` → ``meta["messages_count"]``), и
    две наши реализации успели разойтись в его смысле.

    Распаковка сохраняется — ``messages, keys, seq = store.load_thread_state(...)``
    работает как прежде, потому что ``NamedTuple`` остаётся кортежем.
    """

    #: История в порядке записи. У каждого сообщения гарантирован ``id``.
    messages: List[Dict[str, Any]]
    #: Ключи идемпотентности всех сохранённых сообщений.
    known_keys: Set[MessageKey]
    #: НОМЕР последнего выданного ``seq``, НЕ количество записей.
    max_seq: int


class SubagentTraceRecord(TypedDict):
    """Запись в sidecar-трассе субагента. Ровно шесть полей, все обязательные.

    Замкнутая форма, в отличие от meta: её пишет и читает только ядро, никакой
    третьей стороны у неё нет. Именно здесь наши реализации и разошлись —
    файловая писала шесть полей, in-memory четыре (без ``ts`` и ``seq``), а
    конформанс смотрел только на ``kind`` и оставался зелёным.
    """

    #: Момент записи, ISO-8601 UTC с таймзоной.
    ts: str
    #: Порядковый номер записи внутри трассы треда, с единицы.
    seq: int
    #: ``call_id`` родительского вызова тула-субагента.
    parent_call_id: str
    #: ``run_id`` дочернего прогона.
    child_run_id: str
    kind: TraceKind
    payload: Dict[str, Any]


#: Имена одиннадцати методов контракта. Ведётся явным списком, а не выводится
#: из ``ThreadStore``: набор проверок должен краснеть и в том случае, если метод
#: пропал из протокола по недосмотру, а не только когда он пропал у реализации.
CONTRACT_METHODS_HINT = (
    "load_messages",
    "load_thread_state",
    "load_meta",
    "append_messages",
    "save_meta",
    "patch_runtime_flag",
    "update_runtime_meta",
    "discard_message",
    "reset",
    "append_subagent_trace",
    "read_subagent_trace",
)


@runtime_checkable
class ThreadStore(Protocol):
    """Что ядру нужно от хранилища одного треда.

    Реализуется структурно: наследовать ничего не нужно, достаточно совпасть по
    именам и сигнатурам. Проверять себя следует не ``isinstance``, а
    ``gc_testkit.thread_store_conformance.assert_conforms`` — см. докстроку
    модуля о том, почему первое ничего не значит.

    Все методы СИНХРОННЫЕ. Асинхронную реализацию ядро вызвать не может:
    двенадцать из шестнадцати обращений лежат в обычных ``def``, и корутина там
    молча отбрасывается — без ошибки, без лога, с потерей записи. Если у вас
    асинхронный клиент (``redis.asyncio``, ``asyncpg``), реализуйте
    :class:`gc_core.thread_store_async.AsyncThreadStore` — ядро ждёт его
    нативно; синхронный контракт оно поддерживает через адаптер.
    """

    # --- чтение ------------------------------------------------------------

    def load_messages(self, system_id: str, thread_id: str) -> List[Dict[str, Any]]:
        """История треда в порядке записи. Нет треда — пустой список, не ошибка."""
        ...

    def load_thread_state(self, system_id: str, thread_id: str) -> ThreadState:
        """История ВМЕСТЕ со служебным — см. :class:`ThreadState`.

        Отдельно от ``load_messages``, потому что ядру нужно и то и другое:
        ключи — для идемпотентного дописывания, номер — чтобы продолжить
        нумерацию. Я сперва спрятал их как «деталь хранилища», и это оказалось
        неверно: ``agent_executor`` снимает с них снимок перед батчем (для
        user_ask при компакции).

        ТРЕТИЙ ЭЛЕМЕНТ — НОМЕР ПОСЛЕДНЕГО ВЫДАННОГО ``seq``, а не количество
        записей. Первая редакция этой докстроки утверждала обратное («сколько
        уже сохранено… у базы это будет число строк»), и утверждение было
        неверным: ``append_messages`` выдаёт ``start_seq + 1``, поэтому после
        любого ``discard_message`` количество и номер расходятся, а номер
        переиспользуется. Проверено: три сообщения, удалить третье (seq=3) →
        отдаётся 2 → следующая запись снова получает seq=3.

        Инвариант, который держат на самом деле, — НЕУБЫВАНИЕ, а не
        уникальность. Он не косметический: ``seq`` — это ordering key
        хвостового читателя TUI, и на записи с меньшим номером тот отдаёт
        ``stream_reset`` и перестраивает живой трейс.

        ОБЯЗАННОСТЬ НА ЧТЕНИИ: каждому сообщению нужно проставить ``id``, если
        его нет (файловая реализация зовёт ``ensure_message_id``). Без этого
        ключи уедут в ветку ``payload:<json>``, нестабильную к любому
        изменению словаря, и идемпотентность развалится на первом же
        изменении формы сообщения.
        """
        ...

    def load_meta(self, system_id: str, thread_id: str) -> Dict[str, Any]:
        """Метаданные треда. Нет треда — пустой словарь.

        Форма ОТКРЫТАЯ и замыканию не подлежит. Ядро пишет ``runtime``,
        ``token_usage``, ``messages_count``, ``previous_response_id``,
        ``backend_api_mode``, объёмы ``live_*`` и метки компакции
        (``last_summarized_at``, ``last_summary_archive_suffix``). Секцией
        ``tui`` владеет ДРУГОЙ процесс, а сервер отдаёт meta наружу дословно.
        Реализация обязана сохранять и возвращать незнакомые ей ключи как есть.
        """
        ...

    # --- запись ------------------------------------------------------------

    def append_messages(
        self,
        system_id: str,
        thread_id: str,
        messages: Sequence[Dict[str, Any]],
        *,
        known_keys: Optional[Set[MessageKey]] = None,
        start_seq: int = 0,
    ) -> int:
        """Дописать сообщения, пропустив уже записанные.

        ``start_seq`` — НОМЕР последнего выданного ``seq`` (то же, что третий
        элемент :class:`ThreadState`). Каждой фактически записанной строке
        достаётся ``start_seq + 1``, ``+ 2`` и так далее.

        ``known_keys`` МУТИРУЕТСЯ НА МЕСТЕ, и это часть контракта, а не деталь
        файловой реализации. Вызывающий (``ThreadSession.known_message_keys``)
        держит тот же самый объект и рассчитывает увидеть в нём пополнение;
        защитная копия — совершенно естественное решение реализатора — молча
        задваивает историю на следующем батче. Проверено: реализация, которая
        копирует набор, даёт два сообщения там, где мутирующая даёт одно.

        Пополнять набор следует ТОЛЬКО фактически записанными ключами.
        Досыпать туда заодно всё, что уже лежит в хранилище, нельзя: вызывающий
        снимает снимок набора ДО вызова и по разнице решает, что добавить в
        свою ``history_messages``.

        Ключи не передали — реализация читает их сама.

        Идемпотентность обязательна: батч персистится дважды — сразу после
        исполнения тулов и ещё раз на выходе цикла, — и повтор не должен
        задваивать записи. Ключ сообщения даёт ``make_message_key``.

        Возвращает число фактически записанных.
        """
        ...

    def save_meta(self, system_id: str, thread_id: str, meta: Dict[str, Any]) -> None:
        """Записать метаданные целиком.

        Незнакомые секции сохраняются как есть — см. ``load_meta``.

        ПРИ ЗАПИСИ хранилище обязано проставить три поля, если их нет:

        * ``state_schema_version`` — иначе следующий прогон ОТКАЖЕТСЯ читать
          тред: ``validate_thread_meta_for_load`` поднимает ``StateSchemaError``
          на meta, где есть состояние агента, но нет версии схемы;
        * ``created_at`` — момент рождения треда, НЕ сбрасывается никогда, в том
          числе компакцией;
        * ``updated_at`` — момент этой записи.

        Готовые значения: ``ThreadMetaMapper.ensure_v2_meta(meta)`` проставляет
        версию схемы.

        Требование появилось пятым заходом и было НЕСУЩИМ: файловый слой делал
        это в ``save_thread_meta``, in-memory не делала ничего, и расхождение
        проявлялось только на ВТОРОМ прогоне того же треда — первый проходил
        нормально. Ни один тест первого прогона такое не ловит.
        """
        ...

    def patch_runtime_flag(
        self,
        system_id: str,
        thread_id: str,
        flag: str,
        *,
        active: bool,
        session_meta: Optional[Dict[str, Any]] = None,
    ) -> None:
        """Взвести или снять один флаг в ``meta.runtime``.

        Отдельно от ``save_meta`` намеренно: сюда пишут флаги вроде
        ``summarizing`` ВО ВРЕМЯ работы, и read-modify-write целого meta затирал
        бы то, что параллельно записал сам прогон. ``session_meta`` — снимок,
        который вызывающий уже держит в руках, чтобы не потерять его секции
        (в файловой реализации это защита от clobber'а ``meta.tui``).

        Имя флага нормализуется через ``resolve_runtime_flag_name``: набор
        замкнут, и опечатка должна падать, а не тихо заводить новый флаг.

        Снятие последнего флага убирает секцию ``runtime`` ЦЕЛИКОМ — «нет
        флагов» и «пустой словарь» должны читаться одинаково. Свойство не
        косметическое: расхождение здесь означало бы, что переезд на другое
        хранилище меняет форму meta, а её читают и TUI, и сервер.
        """
        ...

    def update_runtime_meta(
        self, system_id: str, thread_id: str, patch: Dict[str, Any]
    ) -> None:
        """Слить ``patch`` в ``meta.runtime``, не трогая остальное.

        Отличается от ``patch_runtime_flag`` тем, что кладёт произвольные
        значения, а не взводит булев флаг из фиксированного списка: сюда пишут,
        например, накопленный список ``trace_ids`` и снимок ``mcp_tools``.

        В контракте появилось вторым заходом. Первую редакцию я вывел из
        обращений ``ThreadSession`` — и пропустил четыре вызова, идущие мимо
        неё, прямо из ``agent_executor``. Правило «контракт покрывает всё, чем
        пользуются» сработало ровно так, как задумано: недостачу нашли, когда
        начали переводить эти вызовы.
        """
        ...

    def discard_message(self, system_id: str, thread_id: str, message_id: str) -> bool:
        """Убрать сообщение из истории. ``False``, если такого нет.

        Номера ``seq`` при этом НЕ перевыдаются — см. ``load_thread_state``.
        """
        ...

    def reset(self, system_id: str, thread_id: str) -> List[str]:
        """Очистить тред. Возвращает описания удалённого.

        Строки СВОБОДНОЙ формы и разбору не подлежат. Файловая реализация
        отдаёт абсолютные пути удалённых файлов, in-memory — метки сущностей;
        это не расхождение, а следствие того, что общей формы здесь быть не
        может. Потребителя у возврата нет ни одного: единственный вызов в ядре
        его отбрасывает. Если он появится и начнёт разбирать пути — контракт
        окажется прибит гвоздями к файлам, чего этот слой и избегает.
        """
        ...

