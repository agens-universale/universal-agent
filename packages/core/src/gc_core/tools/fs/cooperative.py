"""Кооперативная уступка loop внутри длинных обходов файловой системы.

Файловые тулы исполняются ИНЛАЙН, на loop вызывающего, и docs/async.md
обосновывает это микросекундами: у чтения и записи нативной асинхронной формы
нет, а поход в пул стоит дороже самой операции.

Для чтения и записи это правда. Для рекурсивного ОБХОДА — нет. Обход
ограничен числом записей, а не временем: потолок ``max_visited`` по умолчанию
полмиллиона, и уже 24 тысячи записей замораживают loop примерно на 150 мс —
ровно бюджет приёмки, целиком, одной операцией. На потолке это секунды.
Внутри циклов обхода не было ни одной точки уступки, а на develop они
целиком уходили в ``to_thread``.

Уступаем не по счётчику записей, а по ВРЕМЕНИ: дерево из мелких каталогов и
дерево из огромных ведут себя по-разному, и «каждые N записей» на одном будет
уступать вхолостую, а на другом слишком поздно. ``asyncio.sleep(0)`` — самая
дешёвая уступка, какая есть: один прогон готовых колбэков без таймера.

Стоимость самой проверки — ``perf_counter()`` на запись, десятки наносекунд;
на фоне ``stat()`` каждой записи это шум.
"""

from __future__ import annotations

import asyncio
import time

#: Как часто отдавать управление loop. Меньше — чаще дёргаем планировщик
#: впустую; больше — заметный разрыв пульса. 20 мс на порядок ниже бюджета
#: приёмки (150 мс) и на порядок выше стоимости самого прогона колбэков.
_YIELD_EVERY_SEC = 0.02


class LoopYielder:
    """Счётчик времени с уступкой: ``await y.tick()`` в теле цикла обхода.

    Использование::

        yielder = LoopYielder()
        for entry in walk_iter:
            await yielder.tick()
            ...
    """

    __slots__ = ("_next_at",)

    def __init__(self) -> None:
        self._next_at = time.perf_counter() + _YIELD_EVERY_SEC

    async def tick(self) -> None:
        now = time.perf_counter()
        if now < self._next_at:
            return
        self._next_at = now + _YIELD_EVERY_SEC
        await asyncio.sleep(0)


__all__ = ["LoopYielder"]
