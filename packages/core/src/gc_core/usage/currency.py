"""Валюта фактической стоимости, которую сообщает провайдер.

Поле ``usage.cost`` в ответе валюту не называет, а провайдеры считают в разном:

- OpenRouter (``openrouter.ai``) биллит в долларах;
- routerai.ru — в рублях (проверено живым замером: прайс сошёлся с долларовыми
  ставками тех же моделей по курсу ~107.9 на двух моделях и обеих ставках).

Правило поэтому выводится из адреса эндпоинта: домен ``.ru`` — рубли, всё
остальное — доллары. Настройки нет намеренно: смысл фичи в том, что цена
показывается сама, без похода пользователя в конфиг. Реестра известных хостов
тоже нет — оба проверенных случая покрываются правилом, а список из записей,
дублирующих правило, пришлось бы поддерживать без всякой пользы. Заводить
исключение имеет смысл, только когда найдётся провайдер, который правилу
противоречит.

ЛОВУШКА НА БУДУЩЕЕ. LiteLLM живёт на ``.ru``-хостах (корпоративный прокси), но
биллит в долларах. Сегодня это безопасно: ``usage/normalize.py`` читает цену
только из ``usage.cost``, а LiteLLM кладёт её в ``response_cost`` и в заголовок
``x-litellm-response-cost`` — факта попросту не возникает, работает тариф. Если
кто-то расширит разбор на эти источники, правило ниже начнёт врать: такие вызовы
получат рубли вместо долларов.
"""

from __future__ import annotations

from urllib.parse import urlsplit

DEFAULT_PROVIDER_CURRENCY = "$"
RU_PROVIDER_CURRENCY = "₽"


def provider_currency_for_url(url: str | None) -> str:
    """Валюта фактической цены для эндпоинта ``url``.

    Никогда не бросает: пустой, битый или отсутствующий адрес даёт валюту
    по умолчанию. Цена этого — необнаруженная опечатка в ``completions_url``
    покажет доллары вместо рублей; падать в рендере футера хуже.
    """
    if not isinstance(url, str) or not url.strip():
        return DEFAULT_PROVIDER_CURRENCY
    raw = url.strip()
    try:
        # Схема может отсутствовать («routerai.ru/api/v1»): без «//» urlsplit
        # разберёт такую строку как путь, и хоста не будет.
        host = urlsplit(raw if "://" in raw else "//" + raw).hostname
    except Exception:
        return DEFAULT_PROVIDER_CURRENCY
    if not host:
        return DEFAULT_PROVIDER_CURRENCY
    # ``hostname`` уже понижает регистр, отрезает порт, ``user:pass@`` и скобки
    # IPv6; остаётся снять точку FQDN («routerai.ru.»).
    if host.rstrip(".").endswith(".ru"):
        return RU_PROVIDER_CURRENCY
    return DEFAULT_PROVIDER_CURRENCY
