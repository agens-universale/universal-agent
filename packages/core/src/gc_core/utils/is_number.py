def is_number(text: str) -> bool:
    """Строка — ровно то, что разберёт `int()`.

    `str.isdigit()` шире `int()`: надстрочная `²` (и прочие цифры вне категории
    Nd) его проходит, а `int("²")` падает голым `ValueError`. Пара «isdigit +
    int» поэтому роняет любого, кто ей поверил: мастер терял ответы человека на
    трейсбеке, диалог массового удаления рушился на КАЖДОЙ отрисовке (`_n()`
    зовётся из `_refresh`), `! clear ²` уносил разбор строки ввода.

    Дом общий у мастера (`onboarding_wizard`) и TUI (`tui/screens/mass_delete`,
    `tui/services/bang_shell`) намеренно: приватная копия в одном из них уже
    оставила два места незакрытыми — правило про ввод человека одно, и жить
    оно обязано там, где его видно всем троим.
    """
    return text.isdecimal()
