"""Чтение текстового файла ЧЕЛОВЕКА: два класса отказа, один ответ.

Файл на месте, но не читается — это ДВА разных исключения, и второе притворяется
первым только по случайности наследования. `OSError` — нет прав, каталог на месте
файла, отвалившийся сетевой диск. `UnicodeDecodeError` — файл сохранён «блокнотом»
Windows в UTF-16; он подкласс `ValueError`, а НЕ `OSError`, поэтому любой
`except OSError:` вокруг чтения его ПРОПУСКАЕТ, и приложение падает трейсбеком —
чаще всего ровно на том экране, куда человек пришёл этот файл чинить.

Цена ошибки здесь несимметрична: перехватить лишнее — потерять деградацию на один
файл; не перехватить — уронить процесс. Класс закрывали четырьмя коммитами подряд
по СПИСКУ мест, и каждый раз следующую щель владелец находил живьём. Поэтому
правило переезжает сюда, в одну функцию: пятой редакции одного и того же
`try/except` по файлам быть не должно.

Отказ называет ФАЙЛ. Голое «'utf-8' codec can't decode byte 0xff» человеку
бесполезно — оно не говорит, какой из конфигов, профилей или промптов виноват.
Формат «<путь>: не удалось прочитать: <причина>» — тот же, по которому
`onboarding.explain_broken_config` опознаёт виноватый файл, и тот же, каким уже
отвечают чтение слоёв (`config_modules.layers`), профиль
(`config_modules.profiles`) и запись реестра (`config_modules.registry_write`).

Класс отказа — `ValueError`: его уже ловят все точки входа (`cli._run_init`,
`tui.main`, лестница починки конфига), и заводить ради этого новый тип значит
обойти их все. Кому нужна ТИХАЯ деградация, а не отказ, — `read_user_text_or_none`.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any


def unreadable_reason(path: Any, exc: BaseException) -> str:
    """Текст отказа «файл на месте, но не читается» — единственная его редакция."""
    return f"{path}: не удалось прочитать: {exc}"


def read_user_text(path: Any) -> str:
    """Текст файла человека либо `ValueError` с ИМЕНЕМ файла и причиной.

    Для тех, кто обязан отказать: запись в конфиг, синхронизация по шаблону,
    загрузка промпта, на который показал сам человек."""
    try:
        return Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise ValueError(unreadable_reason(path, exc)) from exc


def read_user_text_or_none(path: Any) -> str | None:
    """Текст файла человека либо None — для тех, кто обязан деградировать.

    Витрины, снимки и кэши прохода отрисовки читают файлы, которые в этом запуске
    могут даже не действовать (неактивный профиль, чужой слой): отказ там значил бы
    «упасть вместо того, чтобы показать остальное»."""
    try:
        return Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
