"""Быстро пишущая команда не имеет права морозить event loop.

Труба сама заставляла читателя уступать: `stream.read()` — настоящая точка
переключения, поэтому разрыв loop держался на сотых долях секунды. У файла её
нет: `os.read` отдаёт данные немедленно, пока писатель быстрее читателя, и цикл
дренажа не отдаёт управление столько, сколько длится поток.

Само «дочитывать до конца» — обязанность ТРУБНОЙ эпохи: не читаешь трубу, и
потомок встаёт на `write` на 64 КиБ. У файла этой обязанности нет вовсе, никто
не блокируется. Поэтому правильное свойство — не «читатель успевает за
писателем», а «читатель за ним НЕ гонится».

Замороженный loop бьёт не только по соседям (другие агенты, keep-alive
MCP-сессий, у сервера — все запросы). На нём стоят и собственные предохранители
exec: дедлайн процесса, лимит на дожатие дренажа, обработка отмены. Отдельных
тестов на них здесь НЕТ намеренно: чтобы увидеть их красными, нужен залив в
несколько гигабайт (при 200 МиБ заморозка всего ~0,1 с и до дедлайна не
дотягивает), то есть пришлось бы платить гигабайтами диска за ноль
дополнительной обнаруживающей способности. Как только читатель отдаёт
управление, таймеры тикают и оба свойства восстанавливаются сами.

Существующие тесты exec этот режим обходят по построению: у них либо крошечный
вывод (`echo`), либо намеренно МЕДЛЕННЫЙ писатель (`test_async_exec.py`,
300 КиБ за 6 с) — ровно тот случай, где дефекта не видно.
"""
import sys

from gc_core.backends.local import LocalFsBackend

#: Объём залива. 200 МиБ хватает, чтобы дефект проявился (замерено: разрыв loop
#: ~0,1 с при потолке 0,05), и не хватает, чтобы тест стал долгим или заметным
#: для диска. Больше брать нельзя: у файла захвата нет потолка, и тест сам
#: становится той болезнью, которую стережёт.
_FLOOD_MIB = 200

#: Шаг пульса и потолок разрыва СВЕРХ шага: сам шаг — не залипание.
_TICK_SEC = 0.01
_MAX_GAP_SEC = 0.05


def _flood_argv(mib: int) -> list:
    """Писатель на заданный объём: пишет так быстро, как получается."""
    code = (
        "import sys\n"
        "block = b'x' * 65536\n"
        f"for _ in range({mib} * 16):\n"
        "    sys.stdout.buffer.write(block)\n"
        "sys.stdout.buffer.flush()\n"
    )
    return [sys.executable, "-c", code]


async def test_a_fast_writer_does_not_freeze_the_loop():
    """Соседняя корутина продолжает получать управление во время залива."""
    from gc_testkit import LoopPulse, quiet_gc_for_loop_timing

    backend = LocalFsBackend()
    # Сборщик глушится на окне замера: пауза поколения 2 на куче полного набора
    # (180–220 мс) кратно больше потолка, и тест судил бы её, а не дренаж.
    #
    # Пульс прогретый и общий. Собственный ставился в очередь прямо перед
    # `await aexec_argv` и брал первую отметку уже после того, как запуск
    # дошёл до первой уступки: 0,2 с сна в начале `aexec_argv` тест не видел —
    # проверено подменой.
    with quiet_gc_for_loop_timing():
        async with LoopPulse(step=_TICK_SEC) as pulse:
            res = await backend.aexec_argv(_flood_argv(_FLOOD_MIB), timeout=60)

    assert res.return_code == 0, res.return_code
    worst = pulse.worst() - _TICK_SEC
    assert worst < _MAX_GAP_SEC, (
        f"loop стоял {worst:.2f} с при потолке {_MAX_GAP_SEC} с — пока команда "
        f"писала, соседние задачи управления не получали"
    )
