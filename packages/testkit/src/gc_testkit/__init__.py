"""Общая тестовая инфраструктура пакетов ``gc-*``.

Пакет ставится только в dev-окружение и в колёса дистрибутивов не попадает.
Держит то, что нужно наборам сразу нескольких пакетов: раскладку исходников
(:mod:`gc_testkit.paths`), фикстуры и хелперы, а также pytest-плагин, который
подключается автоматически через entry point ``pytest11``.
"""


def as_coro(fn):
    """Обернуть синхронную заглушку в корутинную функцию.

    Тест-side адаптер, не производственный. Нужен там, где шов ядра стал
    асинхронным (``await self._build_child_state(...)``), а заглушка теста —
    обычная ``lambda``: без обёртки получится
    ``TypeError: object ... can't be used in 'await' expression``.

    Именно адаптер, а не «терпимый» хелпер в ядре: тождество
    «шов ждёт → заглушка корутинная» должно оставаться жёстким в проде, иначе
    ошибка проводки снова начнёт маскироваться под легальный результат
    (так и вышло с ``_maybe_await``: он прятал 11 тестов, ничего не
    проверявших).
    """
    import functools

    @functools.wraps(fn)
    async def _wrapped(*args, **kwargs):
        return fn(*args, **kwargs)

    return _wrapped


def _p95(ordered):
    """95-й процентиль уже отсортированной выборки — для отчёта, не для суда."""
    return ordered[min(len(ordered) - 1, int(len(ordered) * 0.95))]


class LoopPulse:
    """Прогретый пульс на loop: тикает каждые ``step`` и копит разрывы.

    Разрыв — время, на которое loop НЕ вернулся к пульсу. Судить по ним —
    :func:`assert_loop_was_free` или своим правилом теста; окно замера —
    под :func:`quiet_gc_for_loop_timing`.

    Прогрев — главное, ради чего пульс общий. ``async with`` отдаёт управление
    только после ПЕРВОГО тика. Без этого задача пульса лишь поставлена в
    очередь, и всё, что измеряемая работа делает на loop до своей первой
    уступки, пульс не видит: при ``create_task(пульс)`` и сразу
    ``await AsyncAgent.create(...)`` синхронные 0,35 с в начале сборки
    проходили незамеченными — проверено подменой. Отсюда правило: работа,
    которую меряем, начинается ВНУТРИ ``async with``.

    Последний разрыв снимается после выхода работы из окна: ``__aexit__``
    дожидается очередного тика, так что хвост работы тоже в замере.

    Оба свойства сторожит контроль измерителя
    ``test_the_pulse_actually_sees_a_frozen_loop`` в
    ``test_acceptance_summary_async``: заморозка стоит до первой уступки, в
    середине окна и перед самым выходом. Без прогрева краснеет случай
    ``head``, без ожидания последнего тика — ``tail``.
    """

    STEP = 0.01

    def __init__(self, step=STEP):
        self.step = step
        self.gaps = []
        self._stop = None
        self._task = None

    async def __aenter__(self):
        import asyncio

        self._stop = asyncio.Event()
        self._task = asyncio.create_task(self._beat())
        while not self.gaps:
            await asyncio.sleep(self.step / 2)
        self.gaps.clear()
        return self

    async def __aexit__(self, *_exc):
        self._stop.set()
        await self._task

    async def _beat(self):
        import asyncio
        import time

        # perf_counter, а не monotonic: на Windows под 3.12 monotonic — это
        # GetTickCount64 с шагом 15,6 мс, и разрыв квантовался бы на полтора
        # шага пульса. На macOS и Linux это одни и те же часы. Половина
        # собственных пульсов, переведённых сюда, мерила именно perf_counter.
        prev = time.perf_counter()
        while not self._stop.is_set():
            await asyncio.sleep(self.step)
            now = time.perf_counter()
            self.gaps.append(now - prev)
            prev = now

    def worst(self):
        assert self.gaps, "пульс не тикал вовсе"
        return max(self.gaps)

    def p95(self):
        """Диагностика для сообщения, НЕ критерий.

        Здоровый хвост рядом с разъехавшимся максимумом — это и есть картина
        «цикл отняли один раз надолго». Судить по процентилю нельзя: на
        десятках тиков p95 вырождается во «второй по величине разрыв», а
        настоящая поломка даёт ОДИН длинный — вставленный в компакцию
        ``time.sleep(0.4)`` поднимал максимум до 516 мс при p95 в 46 мс.
        """
        assert self.gaps, "пульс не тикал вовсе"
        return _p95(sorted(self.gaps))

    def report(self):
        import statistics

        return (
            f"p95 {self.p95() * 1000:.0f} мс, "
            f"медиана {statistics.median(self.gaps) * 1000:.0f} мс, "
            f"максимум {self.worst() * 1000:.0f} мс, тиков {len(self.gaps)}"
        )


def assert_loop_was_free(gaps, *, tick, allowed_stalls=1, label=""):
    """Критерий «loop свободен» по РАСПРЕДЕЛЕНИЮ, а не по худшему интервалу.

    ``gaps`` — разрывы прогретого :class:`LoopPulse`, снятые под
    :func:`quiet_gc_for_loop_timing`. Без глушителя критерий меряет сборщик:
    на куче полного набора одна сборка поколения 2 стоит 180–220 мс, и в
    момент падения было ``p50=11.1мс p95=11.2мс max=203.9мс`` на 28 тиков —
    loop свободен, а тест красный.

    Три проверки, каждая ловит свой отказ:

    * ``p50 < tick * 1.5`` — loop занят ПОСТОЯННО (медиана уехала от шага);
    * не больше ``allowed_stalls`` пропусков, по умолчанию ОДНОГО, — loop
      залипает ПОВТОРНО, пусть и ненадолго. Синхронное хранилище тредов с RTT
      5 мс даёт два разрыва, около 85 и 100 мс: оба ниже потолка, и ловит его
      только это правило. Прежде здесь стояла доля ``max(1, int(N * 0.01))`` с
      обещанием «меньше 1%», но на окнах в десятки тиков она всегда была
      единицей, а один пропуск на полсотни тиков — это 2%. Теперь правило
      названо тем, чем и было. Больше одного пропуска вызывающий разрешает
      сам и только с замером: так делает ``test_acceptance_non_blocking``, у
      хода которого два куска без уступки по дизайну;
    * ``max < 150 мс`` — одна НАСТОЯЩАЯ блокировка, которая по правилу
      пропусков проходила бы. Потолок 300 мс стоял, пока в окно попадали паузы
      сборщика (до 204 мс), и при нём блокирующие 0,2 с в пути тула проходили
      молча. Под глушителем сборщика этих пауз в окне нет.

    Пропуском считается ``tick + 10 мс``, а не ``2 * tick`` (как в образце
    ``parallel_agents._report``, где шаг 20 мс). При шаге 5 мс удвоение попадает
    ВНУТРЬ обычного джиттера: измерено p95 = 9.4 мс. Абсолютный пол делает
    определение одинаковым для любого шага.

    p95 в сообщении — диагностика, не критерий (см. :meth:`LoopPulse.p95`).
    """
    import statistics

    assert gaps, f"{label}пульс не тикнул ни разу — loop был занят целиком"
    ordered = sorted(gaps)
    p50 = statistics.median(ordered)
    stalls = [g for g in gaps if g >= tick + 0.010]
    detail = (f"{label}p50={p50 * 1000:.1f}мс p95={_p95(ordered) * 1000:.1f}мс "
              f"max={ordered[-1] * 1000:.1f}мс "
              f"пропусков={len(stalls)} из {len(gaps)}, "
              f"допустимо {allowed_stalls}")
    assert p50 < tick * 1.5, f"loop занят ПОСТОЯННО: {detail}"
    # Потолок ПЕРЕД правилом пропусков: одна настоящая блокировка даёт и
    # выброс, и один-два пропуска, и без этого порядка она диагностировалась
    # бы как «повторно».
    assert ordered[-1] < 0.150, f"loop БЛОКИРОВАН целиком: {detail}"
    assert len(stalls) <= allowed_stalls, f"loop залипал ПОВТОРНО: {detail}"


def quiet_gc_for_loop_timing():
    """Заглушить автосборку на время замера отзывчивости цикла.

    Замерено зондом на полном наборе ядра: **57 319 пауз сборщика, суммарно
    278,6 с при длительности прогона 703 с** — сорок процентов времени процесс
    стоит в сборке. К моменту приёмочных тестов куча дорастает до 440 тысяч
    объектов, и одна сборка поколения 2 занимает 180–220 мс.

    Почему это НЕ смягчение критерия. Тест утверждает «ядро не держит цикл
    встраивающего». Пауза CPython — не ядро: она stop-the-world в том же потоке,
    и во время неё не крутится ни цикл, ни что-либо ещё. Замер в окнах падавших
    тестов: у ``test_two_agents_run_concurrently`` 15 пауз на 872 мс при
    собственной работе 0,39 с — тест мерил сборщик, а не ядро.

    Куча — артефакт набора, а не приложения: в изоляции те же тесты зелёные,
    потому что собирать нечего. Поэтому глушим сборку на окне замера, а не
    двигаем пороги.

    Зубы остаются: настоящий блокирующий вызов внутри окна даёт разрыв, который
    ловят прежние проверки. Проверено подменой.

    ``collect`` и ``freeze`` — ДО начала окна: первый убирает мусор, накопленный
    предыдущими тестами, второй уводит пережившее в постоянное поколение, чтобы
    отложенная сборка не пришлась на замер сразу после ``enable``.
    """
    import contextlib
    import gc

    @contextlib.contextmanager
    def _quiet():
        was_enabled = gc.isenabled()
        gc.collect()
        gc.freeze()
        gc.disable()
        try:
            yield
        finally:
            gc.unfreeze()
            if was_enabled:
                gc.enable()

    return _quiet()


def run_coro(coro):
    """Выполнить корутину из синхронного теста.

    Тест-side адаптер к тому же шву, что и :func:`as_coro`: часть внутренних
    функций ядра стала корутинами (``SubagentRunner._build_child_ctx``,
    ``_arequest_backend_canonical_once``), а приехавшие с develop тесты зовут
    их напрямую. Своим ``asyncio.run``: у такого теста своего loop нет.

    Живёт здесь, а не копией в каждом файле: копий было две и они уже начали
    расходиться комментариями.
    """
    import asyncio

    return asyncio.run(coro)
