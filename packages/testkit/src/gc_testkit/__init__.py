"""Общая тестовая инфраструктура пакетов ``gc-*``.

Пакет ставится только в dev-окружение и в колёса дистрибутивов не попадает.
Держит то, что нужно наборам сразу нескольких пакетов: раскладку исходников
(:mod:`gc_testkit.paths`), фикстуры и хелперы, а также pytest-плагин, который
подключается автоматически через entry point ``pytest11``.
"""


def as_coro(fn):
    """Обернуть синхронную заглушку в корутинную функцию.

    Тест-side адаптер, не производственный. Нужен там, где шов ядра стал
    асинхронным (``await self._build_child_state(...)``), а заглушка теста —
    обычная ``lambda``: без обёртки получится
    ``TypeError: object ... can't be used in 'await' expression``.

    Именно адаптер, а не «терпимый» хелпер в ядре: тождество
    «шов ждёт → заглушка корутинная» должно оставаться жёстким в проде, иначе
    ошибка проводки снова начнёт маскироваться под легальный результат
    (так и вышло с ``_maybe_await``: он прятал 11 тестов, ничего не
    проверявших).
    """
    import functools

    @functools.wraps(fn)
    async def _wrapped(*args, **kwargs):
        return fn(*args, **kwargs)

    return _wrapped


def assert_loop_was_free(gaps, *, tick, label=""):
    """Критерий «loop свободен» по РАСПРЕДЕЛЕНИЮ, а не по худшему интервалу.

    Все три числа ниже — из замеров, а не из вкуса.

    ``max(gaps) < 0.15`` врёт: одна пауза сборщика на куче, накопленной тысячами
    предыдущих тестов того же процесса, даёт единичный выброс при медиане ровно
    у шага пульса. Замерено в момент падения: ``p50=11.1мс p95=11.2мс
    max=203.9мс`` на 28 тиков — двадцать семь интервалов из двадцати восьми по
    11 мс. Loop свободен, а тест краснел.

    Три проверки, каждая ловит свой отказ:

    * ``p50 < tick * 1.5`` — loop занят ПОСТОЯННО (медиана уехала от шага);
    * доля пропусков < 1% — залипает УСТОЙЧИВО, пусть и ненадолго;
    * ``max < 300 мс`` — одна НАСТОЯЩАЯ блокировка. Без неё критерий терял зубы:
      блокирующий ``time.sleep(0.5)`` даёт ровно один пропуск и проходил бы по
      доле. Замерено: настоящая блокировка — 515 мс, шум и GC — до 204 мс;
      порог посередине, с запасом в обе стороны.

    Пропуском считается ``tick + 10 мс``, а не ``2 * tick`` (как в образце
    ``parallel_agents._report``, где шаг 20 мс). При шаге 5 мс удвоение попадает
    ВНУТРЬ обычного джиттера: измерено p95 = 9.4 мс. Абсолютный пол делает
    определение одинаковым для любого шага.
    """
    import statistics

    assert gaps, f"{label}пульс не тикнул ни разу — loop был занят целиком"
    ordered = sorted(gaps)
    p50 = statistics.median(ordered)
    p95 = ordered[min(len(ordered) - 1, int(len(ordered) * 0.95))]
    stalls = [g for g in gaps if g >= tick + 0.010]
    detail = (f"{label}p50={p50 * 1000:.1f}мс p95={p95 * 1000:.1f}мс "
              f"max={ordered[-1] * 1000:.1f}мс "
              f"пропусков={len(stalls)} из {len(gaps)}")
    assert p50 < tick * 1.5, f"loop занят ПОСТОЯННО: {detail}"
    # Потолок ПЕРЕД долей: одна настоящая блокировка даёт и выброс, и один-два
    # пропуска, и без этого порядка она диагностировалась бы как «устойчиво».
    assert ordered[-1] < 0.300, f"loop БЛОКИРОВАН целиком: {detail}"
    assert len(stalls) <= max(1, int(len(gaps) * 0.01)), (
        f"loop залипал УСТОЙЧИВО: {detail}")


def quiet_gc_for_loop_timing():
    """Заглушить автосборку на время замера отзывчивости цикла.

    Замерено зондом на полном наборе ядра: **57 319 пауз сборщика, суммарно
    278,6 с при длительности прогона 703 с** — сорок процентов времени процесс
    стоит в сборке. К моменту приёмочных тестов куча дорастает до 440 тысяч
    объектов, и одна сборка поколения 2 занимает 180–220 мс.

    Почему это НЕ смягчение критерия. Тест утверждает «ядро не держит цикл
    встраивающего». Пауза CPython — не ядро: она stop-the-world в том же потоке,
    и во время неё не крутится ни цикл, ни что-либо ещё. Замер в окнах падавших
    тестов: у ``test_two_agents_run_concurrently`` 15 пауз на 872 мс при
    собственной работе 0,39 с — тест мерил сборщик, а не ядро.

    Куча — артефакт набора, а не приложения: в изоляции те же тесты зелёные,
    потому что собирать нечего. Поэтому глушим сборку на окне замера, а не
    двигаем пороги.

    Зубы остаются: настоящий блокирующий вызов внутри окна даёт разрыв, который
    ловят прежние проверки. Проверено подменой.

    ``collect`` и ``freeze`` — ДО начала окна: первый убирает мусор, накопленный
    предыдущими тестами, второй уводит пережившее в постоянное поколение, чтобы
    отложенная сборка не пришлась на замер сразу после ``enable``.
    """
    import contextlib
    import gc

    @contextlib.contextmanager
    def _quiet():
        was_enabled = gc.isenabled()
        gc.collect()
        gc.freeze()
        gc.disable()
        try:
            yield
        finally:
            gc.unfreeze()
            if was_enabled:
                gc.enable()

    return _quiet()


def run_coro(coro):
    """Выполнить корутину из синхронного теста.

    Тест-side адаптер к тому же шву, что и :func:`as_coro`: часть внутренних
    функций ядра стала корутинами (``SubagentRunner._build_child_ctx``,
    ``_arequest_backend_canonical_once``), а приехавшие с develop тесты зовут
    их напрямую. Своим ``asyncio.run``: у такого теста своего loop нет.

    Живёт здесь, а не копией в каждом файле: копий было две и они уже начали
    расходиться комментариями.
    """
    import asyncio

    return asyncio.run(coro)
