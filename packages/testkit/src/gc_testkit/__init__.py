"""Общая тестовая инфраструктура пакетов ``gc-*``.

Пакет ставится только в dev-окружение и в колёса дистрибутивов не попадает.
Держит то, что нужно наборам сразу нескольких пакетов: раскладку исходников
(:mod:`gc_testkit.paths`), фикстуры и хелперы, а также pytest-плагин, который
подключается автоматически через entry point ``pytest11``.
"""


def as_coro(fn):
    """Обернуть синхронную заглушку в корутинную функцию.

    Тест-side адаптер, не производственный. Нужен там, где шов ядра стал
    асинхронным (``await self._build_child_state(...)``), а заглушка теста —
    обычная ``lambda``: без обёртки получится
    ``TypeError: object ... can't be used in 'await' expression``.

    Именно адаптер, а не «терпимый» хелпер в ядре: тождество
    «шов ждёт → заглушка корутинная» должно оставаться жёстким в проде, иначе
    ошибка проводки снова начнёт маскироваться под легальный результат
    (так и вышло с ``_maybe_await``: он прятал 11 тестов, ничего не
    проверявших).
    """
    import functools

    @functools.wraps(fn)
    async def _wrapped(*args, **kwargs):
        return fn(*args, **kwargs)

    return _wrapped


def run_coro(coro):
    """Выполнить корутину из синхронного теста.

    Тест-side адаптер к тому же шву, что и :func:`as_coro`: часть внутренних
    функций ядра стала корутинами (``SubagentRunner._build_child_ctx``,
    ``_arequest_backend_canonical_once``), а приехавшие с develop тесты зовут
    их напрямую. Своим ``asyncio.run``: у такого теста своего loop нет.

    Живёт здесь, а не копией в каждом файле: копий было две и они уже начали
    расходиться комментариями.
    """
    import asyncio

    return asyncio.run(coro)
