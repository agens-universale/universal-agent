"""Раскладка экранов-карточек (`/settings`, мастер, пост-апдейт): что видно в рамке.

Канон визуального контракта: **футер есть всегда**, какой бы экран ни был по высоте;
**рамка цельная** (её граница видна целиком); а что не влезло — **скроллится внутри
рамки**. Второе и третье обеспечивает CSS: рамку рисует сам скроллящий контейнер
(`#set-scroll` / `#onb-scroll` / `#pu-scroll`), поэтому граница остаётся на месте, а
едет только содержимое. Первое — `cap_frame_height`.

Потолок считается в коде, тем же приёмом, что `TraceScreen._sync_trace_max_height` на
главном экране: экран минус хром. Ставится именно потолок, а не высота, — короткая
секция по-прежнему обнимает свой контент, и хром следует за его концом.

Почему не CSS (замерено, а не предположено):

* `max-height: 100%` меряется по ВСЕЙ высоте `#root`, куда шапка и футер входят, —
  ровно с этого начался дефект: скролл дорастал до высоты экрана и выдавливал футер;
* `max-height: 1fr` ведёт себя так же — резолвится в полную высоту контейнера, а не в
  остаток (замер: на окне 14 рамка выходит 12 строк, футер уезжает на `y=16`);
* обёртка `#set-mid { height: 1fr }` вокруг скролла РАБОТАЕТ и держит весь набор
  стражей, включая живой ресайз (проверено, 5 прогонов подряд). Геометрия самой рамки
  при ней совпадает с здешней побайтово. Но `1fr` у обёртки прибивает футер к низу
  экрана: там, где контент влезает, футер перестаёт следовать за рамкой (замер на
  окне 40: меню — `footer_y` 22 здесь против 38 при обёртке). Это визуальный язык
  всех коротких секций и всех шагов мастера разом, и меняться он должен решением, а
  не побочным эффектом рефакторинга. Перейти — три строки CSS и обёртка в `compose`,
  если такое решение будет принято.

Обратная сторона того же канона — `reveal_focus`: раз у рамки теперь есть настоящий
вьюпорт, в него обязано попадать то, ради чего кадр нарисован, — висящий вопрос или
строка под курсором. Пока вьюпорта не было, подводить было НЕКУДА: элемент «виден» в
координатах скролла и невидим на экране.
"""
from __future__ import annotations

from textual.css.query import NoMatches

#: Коробка скролл-контейнера в НОРМАЛЬНОМ (некомпактном) режиме: `border: round`
#: (1 строка сверху + 1 снизу) + `padding: 1 2` (1 сверху + 1 снизу) — см.
#: `#set-scroll`/`#onb-scroll`/`#pu-scroll` в styles.tcss. Константа, а не замер
#: `scroll.styles` на месте: этот же вызов переключает класс `.frame-compact`, и
#: замер ПОСЛЕ переключения увидел бы уже урезанную коробку — решение мигало бы
#: между режимами на одной и той же высоте (компакт → коробка 0 → «места хватает»
#: → некомпакт → коробка 4 → «снова тесно» → компакт…).
_NORMAL_FRAME_BOX = 4


def cap_frame_height(screen, scroll_id: str) -> None:
    """Ограничить рамку `scroll_id` остатком экрана под шапкой и футером.

    Вызывается на старте экрана и на каждый ресайз: значение зависит только от высоты
    окна и хрома, не от содержимого, — пересчитывать на каждый кадр секции незачем.
    Хром меряется по регионам соседей: пока layout не прошёл, они нулевые — такой
    замер отбрасываем (следующий вызов придёт с готовыми регионами).

    На тесных окнах собственная коробка рамки (граница + вертикальные отступы,
    `_NORMAL_FRAME_BOX`) съедала весь остаток раньше, чем до неё добиралось
    содержимое: рамка рисовалась пустой ещё при остатке в 4-5 строк. Класс
    `.frame-compact` (styles.tcss) снимает границу и вертикальный паддинг, отдавая
    остаток целиком содержимому, — и снимается обратно, как только места снова
    хватает. Потолок высоты выставляется ВСЕГДА, даже в 0: молчаливый пропуск
    оставлял прежний (протухший) потолок после уменьшения окна, и скролл
    разрастался на всю высоту содержимого, становясь непрокручиваемым."""
    try:
        root = screen.query_one("#root")
        scroll = screen.query_one(scroll_id)
    except NoMatches:
        return
    chrome = sum(child.region.height for child in root.children if child is not scroll)
    if chrome <= 0:
        return
    margin = scroll.styles.margin
    available = screen.size.height - chrome - margin.top - margin.bottom
    scroll.set_class(available <= _NORMAL_FRAME_BOX + 1, "frame-compact")
    scroll.styles.max_height = max(available, 0)


#: Маркер «этот элемент — ВОПРОС: держи его на экране, пока висит». Класс без
#: оформления, его несут инлайн-вопросы (баннеры подтверждения, поле ввода имени)
#: НАРЯДУ со своим стилевым классом. Так подводка не знает имён отдельных баннеров:
#: новый вопрос попадает под канон, просто унаследовав маркер, — а не правкой списка
#: селекторов внутри подводки.
#:
#: Плашкам ИТОГА (`#set-notice`, `#set-flash`) маркер не положен, хотя подвести их при
#: появлении тоже надо: они сообщение, а не вопрос, и ответа не ждут. `#set-notice`
#: живёт до следующей пересборки тела — с приоритетом вопроса он навсегда перебивал бы
#: курсор, и стрелки переставали бы двигать кадр. Им — разовый `reveal`.
KEEP_IN_VIEW = "keep-in-view"

#: Зеркальный родовой маркер: СООБЩЕНИЕ-итог действия (плашка успеха, строка
#: отказа), ответа не ждёт — и гаснет на следующем осознанном действии
#: пользователя (правило В1, ревизия владельца 2026-08-14: единое время жизни
#: для успеха и отказа; различается подача, не срок). Гасит преамбула клавиш
#: экрана — по маркеру, а не по перечню id: новое сообщение получает правило,
#: просто надев маркер. Вопросы (`KEEP_IN_VIEW`) под правило не попадают.
EPHEMERAL = "ephemeral"

#: Третий род той же семьи: ОТЧЁТ — результат операции, который надо прочитать и
#: по которому надо что-то сделать («задайте заново: …», «бэкап: …»). Ответа не
#: ждёт (это не вопрос), но и гаснуть на следующем действии не имеет права: за
#: одно нажатие его не прочитать. Живёт до ЯВНОГО закрытия (Esc — своя ступень
#: лестницы) либо до смены секции. Различается ПРИРОДА, а не длина: граница
#: «длиннее N строк» была бы произвольной и непредсказуемой для читателя.
KEEP_UNTIL_DISMISSED = "keep-until-dismissed"


def reveal_focus(host) -> None:
    """Подвести то, что в текущем кадре и есть предмет разговора.

    Приоритет: помеченный `KEEP_IN_VIEW` → строка под курсором (`.selected`). Вопрос
    важнее курсора: если экран просит Enter, показывать надо вопрос, а не строку, с
    которой его задали. Оба яруса — родовые маркеры, а не перечень конкретных
    баннеров и списков.

    Единственная точка подводки на экране — и потому единственная, кто решает, ЧТО
    подводить. Раньше курсор и баннер подводили себя сами, двумя независимыми
    отложенными заказами, и порядок их исполнения решал, что человек увидит: заказ
    курсора, поставленный предыдущей клавишей, приезжал ПОСЛЕ баннера и утаскивал
    кадр обратно на строку. Здесь приоритет считается в момент исполнения, поэтому
    порядок заказов больше ничего не значит.

    Отложено ЦЕЛИКОМ, вместе с поиском цели: сразу после пересборки тела в дереве
    висят два комплекта строк — новый и ещё не отсоединённый старый (`display` у
    обречённого прежний), и поиск «здесь и сейчас» подводил бы строку уходящего
    кадра. Заказ адресуем ПРИЛОЖЕНИЮ: `mount` асинхронен, и у только что
    смонтированного виджета насос сообщений ещё не запущен."""
    _schedule(host, 0)


#: Минимум кадров, которые подводка повторяет себя БЕЗУСЛОВНО. Textual применяет
#: прокрутку тоже отложенно, и заказ, поставленный ПРЕДЫДУЩИМ кадром (курсор),
#: приземляется уже после нашего — кадр уезжал бы обратно на строку, а вопрос
#: оставался за краем. Повтор всегда безопасен: цель выбирается заново по тому же
#: приоритету, поэтому он либо подтверждает верное положение, либо чинит сбитое.
_SETTLE_FRAMES = 3
#: Потолок повторов, пока цель ТАК И НЕ попала в кадр. Фиксированного бюджета мало:
#: под нагрузкой раскладка успевает устояться позже, и подводка, отработав свои три
#: кадра вхолостую, замолкала навсегда — сторож `#set-envconfirm` краснел через раз.
#: Считаем не кадры, а результат; потолок — только чтобы не крутиться вечно на цели,
#: которая во вьюпорт не влезает в принципе.
_MAX_FRAMES = 15


def reveal(widget) -> None:
    """Подвести КОНКРЕТНЫЙ элемент — без права держать кадр дальше.

    Для плашек итога: показать, когда появились, и отпустить. Ярус приоритета им не
    нужен и вреден (см. `KEEP_IN_VIEW`), а подводка нужна — плашка садится в конец
    тела, ниже вьюпорта."""
    _step(widget.app, _reveal_widget, widget, 0)


def _step(app, fn, arg, frame: int) -> None:
    app.call_after_refresh(fn, arg, frame)


def _again(frame: int, target) -> bool:
    """Повторять ли подводку на следующем кадре: пока не отстоялось — да, дальше —
    только если цель всё ещё вне кадра (и не бесконечно)."""
    if frame + 1 < _SETTLE_FRAMES:
        return True
    if frame + 1 >= _MAX_FRAMES:
        return False
    try:
        return not target.screen.region.contains_region(target.region)
    except Exception:
        return False


def _reveal_widget(widget, frame: int) -> None:
    """Один кадр подводки конкретного элемента.

    Не смонтирован — не сдаёмся, а ждём следующего кадра: `mount` асинхронен, и на
    первом отложенном такте `is_mounted` у только что созданной плашки ещё False.
    Ровно на этом сторож `#set-envconfirm` и краснел через раз — подводка молча
    уходила навсегда, если её такт опередил применение mount'а."""
    if widget.is_mounted:
        widget.scroll_visible(animate=False)
    if not widget.is_mounted or _again(frame, widget):
        if frame + 1 < _MAX_FRAMES:
            _step(widget.app, _reveal_widget, widget, frame + 1)


def _schedule(host, frame: int) -> None:
    _step(host.app, _reveal_focus_now, host, frame)


def _reveal_focus_now(host, frame: int) -> None:
    # Ищем по всему экрану, а не в поддереве заказчика: приоритет сквозной — вопрос
    # экрана обязан перебивать курсор редактора, кто бы из них ни заказал подводку.
    try:
        scope = host.screen
    except Exception:
        return                     # экран уже сменился — подводить нечего
    target = None
    for selector in (f".{KEEP_IN_VIEW}", ".selected"):
        found = [w for w in scope.query(selector) if w.display]
        if found:
            target = found[-1]
            target.scroll_visible(animate=False)
            break
    if target is not None and _again(frame, target):
        _schedule(host, frame + 1)
