"""Глифы ленты (дизайн-код TUI, таблица глифов ленты).

Статус вызова — круги, исход несёт цвет. Итог хода и следствие «скилл не
найден» — `✕`. Прочие экраны (настройки, онбординг, MCP, формы) держат
свой `✗`."""

#: Вызов исполнен или идёт: успех, ошибка, идёт (цветом исхода).
CALL_GLYPH = "●"
#: Вызов не исполнен до конца: отказ, стоп, лимит, сбой проверки.
CALL_UNDONE_GLYPH = "○"
#: Вызов ещё не начат.
CALL_WAITING_GLYPH = "•"
#: Ошибка вне строки вызова: итог хода «✕ Ошибка», `└ ✕ скилл … не найден`.
ERROR_GLYPH = "✕"
#: Приглашение поля ввода — главного и фильтров (`/sessions`, `/skills`,
#: `/config`) — и метка реплики пользователя в ленте: один знак везде.
PROMPT = "› "

#: Ритм мигания живого глифа в кадрах 0.1с-тика (решение владельца):
#: 0.5с виден, 0.7с скрыт. Общий для идущего вызова и останавливаемого хода.
BLINK_TICK_S = 0.1
BLINK_ON_TICKS = 5
BLINK_PERIOD_TICKS = 12


def blink_on(frame: int) -> bool:
    """Виден ли мигающий глиф в кадре `frame`."""
    return frame % BLINK_PERIOD_TICKS < BLINK_ON_TICKS
