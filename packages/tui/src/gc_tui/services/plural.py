"""Русские склонения числительных для подписей UI — один источник форм.

Копии этой таблицы разъезжались: подпись плашки вставки, хвост свёрнутого
диффа, счётчик файлов в шапке экрана изменений, сводка правок в статусной
строке и счётчик обновлений MCP считали склонение каждая по-своему. Кто-то
забывал про десятки — «… ещё 2 строк» ловили на живой приёмке волны 2.

Готовых слов здесь ровно столько, сколько нужно двум и более местам; своё
редкое слово берёт `plural_form` и передаёт три формы сама — заводить под
каждую подпись отдельную функцию значило бы разводить тот же словарь заново.

Модуль сознательно пустой по зависимостям: его тянут и виджеты, и экраны, и
сервисы, и любой импорт отсюда обязан оставаться дешёвым.
"""

from __future__ import annotations


def plural_form(n: int, one: str, few: str, many: str) -> str:
    """Форма по числу: 11–14 (и любые …11–…14) — всегда `many`, дальше решает
    последняя цифра. Знак числа на форму не влияет.

    Публичная: своё слово («обновление/обновления/обновлений») зовёт её
    напрямую, и второй реализации самого правила в кодовой базе быть не должно.
    """
    tail = abs(n) % 100
    if 11 <= tail <= 14:
        return many
    last = tail % 10
    if last == 1:
        return one
    if 2 <= last <= 4:
        return few
    return many


def files_word(n: int) -> str:
    """«файл / файла / файлов» под число `n` — счётная форма («3 файла
    изменено»), для числительного САМОГО ПО СЕБЕ, без предлога."""
    return plural_form(n, "файл", "файла", "файлов")


def files_word_genitive(n: int) -> str:
    """«файла / файлов» — форма ПОСЛЕ ПРЕДЛОГА («у 2 файлов», не «у 2
    файла»): предлог требует родительного падежа у всей числительной группы,
    и 2–4 там ведут себя как 5+ (множественное число), а не как счётная форма
    `files_word` — различает только «оканчивается на 1» (кроме 11) и всё
    остальное, поэтому `few`/`many` здесь — одно и то же слово.
    """
    return plural_form(n, "файла", "файлов", "файлов")


def lines_word(n: int) -> str:
    """«строка / строки / строк» под число `n`."""
    return plural_form(n, "строка", "строки", "строк")


def errors_word(n: int) -> str:
    """«ошибка / ошибки / ошибок» под число `n`."""
    return plural_form(n, "ошибка", "ошибки", "ошибок")


def refusals_word(n: int) -> str:
    """«отказ / отказа / отказов» под число `n`."""
    return plural_form(n, "отказ", "отказа", "отказов")
