    def footer_text(self) -> str:
        if self._env_pending is not None:
            return _FOOTER_ENV_CONFIRM
        if self._pending is not None:
            return _FOOTER_CONFIRM
        if self._picker is not None:
            return _FOOTER_PICKER
        if self._form is not None:
            return self._form_footer()
        if self._legacy_open:
            return _FOOTER_EMPTY if self.registry_empty else _FOOTER_RESERVE_FORM
        row = self._row_at_cursor()
        if row is None:
            # Пустое тело бывает у ОБЕИХ ролей (см. `_body` и коммент у
            # `_FOOTER_EMPTY_MAIN`): выбор хвоста — по роли, как у всех пар футеров.
            return _FOOTER_PROFILE_EMPTY if self._is_profile else _FOOTER_EMPTY_MAIN
        if row["kind"] == "reserve":
            return _FOOTER_RESERVE
        if row["kind"] == "slot":
            return _FOOTER_PROFILE_SLOT if self._is_profile else _FOOTER_SLOT
        if row["kind"] == "assign":
            return _FOOTER_PROFILE_ASSIGN if self._is_profile else _FOOTER_ASSIGN
        if row["kind"] == "add":
            # Строка-действие: удалять на ней нечего, и общий футер списка обещал
            # бы Del впустую — в ОБЕИХ ролях (дефект был и у основной секции).
            return _FOOTER_PROFILE_ADD if self._is_profile else _FOOTER_ADD
        # Строка реестра обещает по ПРОИСХОЖДЕНИЮ записи под курсором (§5): на
        # унаследованной не работают ни Del, ни Enter — обещать их там нечем.
        if self._entry_origin(row["alias"]) == "base":
            return _FOOTER_PROFILE_BASE_ENTRY
        return _FOOTER_PROFILE_ENTRY if self._is_profile else _FOOTER_ENTRY

    def _form_footer(self) -> str:
        form = self._form
        if form.presets_open:
            return _list_footer(form.presets_have_selection,
                                form.can_return_shared_pair)
        if form.list_open:
            return _list_footer(form.list_has_selection, form.can_return_shared_pair)
        # Обещание «вернуть наследование» гейтится ТЕМ ЖЕ предикатом, что и сама клавиша
        # (`can_return_shared_pair`): свой гейт витрины разошёлся бы с клавишей на
        # первой правке правила — ложь того же рода, что стережёт `test_footer_contract`.
        if form.on_url_field:
            return (_FOOTER_FORM_URL_PAIR if form.can_return_shared_pair
                    else _FOOTER_FORM_URL)
        if form.on_model_field:
            return _FOOTER_FORM_MODEL
        if form.on_no_auth_row:
            return _FOOTER_FORM_NOAUTH
        # Остались поле токена и поле алиаса. Ни одному из них футер клавишу не
        # обещает: у токена её называет ПОДПИСЬ ПОЛЯ (`_TOKEN_LABEL_INHERIT`, канон
        # `ConnectionEditor._token_label`) — повторять то же обещание в одном кадре
        # значит шуметь, а место в футере секции считанное; у алиаса работает штатный
        # `delete_left_all`, обещать который нечего. Футер о клавише говорит там, где
        # подписи с ней нет, — на адресе (`_FOOTER_FORM_URL_PAIR`) и в футерах
        # раскрытого списка, который поднимают над ним.
        return _FOOTER_FORM_FIELD

    # --- клавиши --------------------------------------------------------------
    def move(self, delta: int) -> None:
        if self._pending is not None or self._env_pending is not None:
            return
        if self._picker is not None:
            rows = self._picker["rows"]
            self._picker["idx"] = (self._picker["idx"] + delta) % len(rows)
            self._refresh_picker_rows()
            return
        if self._form is not None:
            self._form.move(delta)
            return
        if self._legacy_open and self._legacy is not None:
            self._legacy.move(delta)
            return
        rows = self._rows()
        if not rows:
            return
        self._idx = (self._idx + delta) % len(rows)
        self._refresh_rows()

    def enter(self) -> None:
        if self._env_pending is not None:
            # Подтверждение перезаписи ссылки: снимок (алиас, поля) зафиксирован
            # на момент submit, фокус на время вопроса снят — правки под баннером
            # снимку разъехаться не дают.
            alias, fields = self._env_pending
            self._clear_env_confirm()
            self._finish_submit(alias, fields)
            return
        if self._pending is not None:
            self.confirm_pending()
            return
        if self._picker is not None:
            self._pick()
            return
        if self._form is not None:
            if self._form.enter():
                return                      # Enter израсходован списком формы
            self._submit_form()
            return
        if self._legacy_open:
            if self._on_legacy_save is not None:
                self._on_legacy_save()
            return
        row = self._row_at_cursor()
        if row is None:
            return
        if row["kind"] == "reserve":
            self._open_reserve()
        elif row["kind"] == "add":
            self._open_form(None)
        elif row["kind"] in ("slot", "assign"):
            self._open_value_picker(row)
        elif self._entry_origin(row["alias"]) == "base":
            # Унаследованная строка: править в файле цели нечего — запись живёт в
            # основном конфиге. Футер Enter здесь не обещает, но клавиша эта —
            # универсальный вход в строку, и молчание в ответ было бы тупиком:
            # отказ говорит, почему и где эта запись правится (симметрия с Del).
            self._notice(_NOTICE_EDIT_REFUSED_INHERITED.format(alias=row["alias"]),
                         ok=False)
        else:
            self._open_form(row["alias"])

    def escape(self) -> bool:
        """Свернуть СВОЁ под-состояние и съесть клавишу; сворачивать нечего — False,
        и Esc достаётся экрану (тот уводит в меню). Вложенность из Global Constraints."""
        if self._env_pending is not None:
            # Отмена — назад В ФОРМУ, не теряя набранного: ссылка остаётся в
            # файле, черновик — в полях; ввод возвращается форме (приём пикера).
            self._clear_env_confirm()
            if self._form is not None:
                self._form.refocus()
            return True
        if self._pending is not None:
            self.cancel_pending()
            return True
        if self._picker is not None:
            self._close_picker()
            if self._form is not None:
                # Вопрос снят, форма осталась — вернуть ей ввод, отобранный на время
                # вопроса. Только здесь: по выбору значения форма уходит вместе с
                # записью, и фокус на её поле стал бы фокусом на снесённом виджете
                # (та же беда, что лечит `set_focus(None)` перед сносом тела).
                self._form.refocus()
            return True
        if self._form is not None:
            if self._form.escape():
                return True                 # закрыт только список формы
            self._form = None
            self._legacy_open = self._legacy_default()  # назад в СВОЁ состояние, не в меню
            self._rebuild()
            return True
        if self._legacy_open and not self.registry_empty:
            self._legacy_open = False       # под-форма резервной — назад к списку
            self._rebuild()
            return True
        return False

    def new_entry(self) -> bool:
        """`n`/`Alt+N`: новая запись реестра. False — состояние занято, клавиша не наша.

        Занято — это форма, пикер, confirm И под-форма резервной модели: в последней
        лежит несохранённый выбор, а её футер `Alt+N` не обещает. Пустое состояние
        исключение по построению: там вход в реестр и есть смысл клавиши, а «терять»
        нечего — легаси-редактор поднимается из файла заново."""
        if self._form is not None or self._picker is not None or self._pending is not None:
            return False
        if self._legacy_open and not self.registry_empty:
            return False
        self._open_form(None)
        return True

    def alt_down(self) -> bool:
        # Гейт пикера — первым, как у `move`/`enter`/`escape`/`clear_token`: вопрос
        # о слоте висит НАД живой формой, и спрошенная раньше него форма раскрывала
        # под ним второй список (пресетов адреса) — две ленты на один Enter.
        # Вопрос о перезаписи ссылки (L22) висит там же — гейт тот же.
        if self._picker is not None or self._env_pending is not None:
            return False        # список уже раскрыт, а перечитывать в нём нечего
        if self._form is not None:
            return self._form.reload_models() or self._form.reload_presets()
        if self._legacy_open and self._legacy is not None:
            return bool(self._legacy.reload())
        row = self._row_at_cursor()
        if row is not None and row["kind"] in ("slot", "assign"):
            # Канон клавиш: `Alt+↓` — раскрыть список. Список у строки тот же, что и
            # у Enter (решение 9 называет обе клавиши), а не вторая механика.
            self._open_value_picker(row)
            return True
        return False

    def probe(self) -> bool:
        """`Ctrl+Space` — проба соединения; она есть только у формы записи (у списка
        и у легаси-редактора пробы нет, §5.2 спеки клавиш)."""
        if self._picker is not None or self._env_pending is not None:
            return False        # висит вопрос (слот / перезапись ссылки) — клавиши не формы
        if self._form is not None:
            return self._form.probe_connection()
        return False

    def space(self) -> bool:
        if self._picker is not None or self._env_pending is not None:
            return False        # висит вопрос (слот / перезапись ссылки) — клавиши не формы
        if self._form is not None:
            return self._form.toggle_no_auth()
        return False

    def clear_token(self) -> bool:
        """`Ctrl+U` — вернуть записи наследование: снять её адрес, токен и галку
        разом (§5). Клавиша есть только у формы записи и только на полях её пары
        (решает сама форма). False — состояние не наше вовсе (формы нет), и
        клавишу съедать нельзя: в полях легаси-редактора её штатный
        `delete_left_all` работает как обычно.

        Висящий вопрос (пикер слота по умолчанию / баннер перезаписи ссылки) —
        другое дело: форма ЖИВА, только снята с фокуса ради вопроса. Все соседние
        клавиши экрана (`up`/`down`, `alt+down`, `ctrl+space`, `delete`, `space`,
        `n`, `enter`) съедаются экраном безусловно; только `Ctrl+U` решает по
        ЭТОМУ ответу, стопить ли событие (`SettingsScreen.on_key`) — и «не наш
        случай» здесь означало бы «пусть уходит легаси-`delete_left_all`», хотя
        поле формы просто временно не в фокусе. `True` — клавиша съедена, но
        ничего не делает: без гейта Ctrl+U отвечал «наследование возвращено» и
        чистил поле, пока в файл уезжал прежний токен."""
        if self._form is None:
            return False         # состояние не наше — легаси-редактор берёт клавишу как обычно
        if self._picker is not None or self._env_pending is not None:
            return True           # висит вопрос — клавиша съедена, форме она не достаётся
        return self._form.clear_token()

    # --- под-формы ------------------------------------------------------------
    def _open_form(self, alias: str | None) -> None:
        """Форма правит СВОЙ файл, поэтому и поля, и список занятых имён — свои:
        `initial` собирается из `_own_entries`, а не из витринного `_entry`, —
        иначе ключи записи основного конфига приехали бы в поля, стали неотличимы
        от набранных и уехали копией в файл профиля.

        Алиасы тени формa получает отдельно (`base_aliases`): имя, занятое записью
        основного конфига, — не «дубль своей», и отказ у него свой (§5).

        Тень ПОД ИМЕНЕМ записи (`base_entry`) форма получает целиком, но витринно:
        в поля она не кладётся (см. выше), а называет источник наследования — тёзка
        берёт пару, адрес и id у заслонённой записи, не у «Подключения», и туда же
        форма шлёт пробу. Без неё форма звала раздел под чужим хостом (смок)."""
        initial = None
        if alias is not None:
            # Запись едет ЦЕЛИКОМ, а не четырьмя знакомыми ключами: своё подключение
            # пишется и вторым написанием (`backend.completions_url`/`proxy`/
            # `chat_completion_headers.Authorization`), и форма обязана видеть пару так
            # же, как её видит валидатор, — иначе объявит запись общей и откажется
            # сохранить её без единой правки. Правит форма по-прежнему только свои поля.
            initial = {"alias": alias, **self._own_entry(alias)}
        self._form = ModelEntryForm(
            interaction_gate=lambda: (self._picker is not None
                                      or self._env_pending is not None),
            initial=initial, existing_aliases=self._own_aliases, presets=self._presets,
            effective_url=self._effective_url, effective_auth=self._effective_auth,
            verify=self._verify, config_proxy=self._config_proxy,
            base_aliases=frozenset(self._base_entries),
            base_entry=self._base_entry(alias) if alias is not None else {})
        self._legacy_open = False           # форма занимает тело целиком
        self._rebuild()

    def _open_reserve(self) -> None:
        self._legacy_open = True
        self._rebuild()

    # --- запись ---------------------------------------------------------------
    def _submit_form(self) -> None:
        ok, alias, fields = self._form.submit()
        if not ok:
            return                          # ошибка осталась В форме, писать нечего
        # Гейт «ссылка не может стать литералом молча» (L22) — ДО транзакции и до
        # вопроса о слоте: та же дверь, что у плоского `_do_save` экрана, тем же
        # предикатом (`config_raw.env_refs_overwritten`). Судятся token и url —
        # ключи записи, где живут секрет и адрес, — по СЫРОЙ записи файла цели:
        # один Enter поверх `${ENV:…}` иначе клал секрет открытым текстом в файл,
        # который может лежать в репозитории. Затирание ссылки ПУСТЫМ значением
        # (Ctrl+U, галка ●) вопрос не поднимает: это явные действия формы со
        # своими подписями, а не молчаливая подмена.
        from gc_core import config_raw
        prev = self._form.original_alias
        pair = {k: v for k, v in fields.items() if k in ("token", "url")}
        old = self._own_entry(prev) if prev is not None else {}
        written, _erased = config_raw.env_refs_overwritten(pair, old)
        if written:
            self._env_pending = (alias, fields)
            self._ask("В файле — ссылка на переменную окружения: "
                      + ", ".join(written)
                      + " — сохранение запишет введённое значение в файл "
                        "открытым текстом.", _FOOTER_ENV_CONFIRM)
            # Вопрос висит над живой формой — клавиатура его, иначе печать под
            # баннером разводила бы снимок с показанным (приём пикера слота).
            self.screen.set_focus(None)
            return
        self._finish_submit(alias, fields)

    def _finish_submit(self, alias: str, fields: dict) -> None:
        """Хвост submit'а ПОСЛЕ гейта перезаписи ссылки: вопрос о слоте и запись.
        Отдельным шагом, потому что подтверждение (L22) возвращается сюда с тем же
        снимком (алиас, поля) — форма всё это время жива."""
        prev = self._form.original_alias
        renaming = prev is not None and alias != prev
        # Гейт спрашивается и у переименования: у неактивного профиля фаза 2 записи
        # пропущена по дизайну (`validate_profile_text_with_sections` остаётся на
        # фазе 1, пока указатель базы не приводит именно в этот файл), и транзакция,
        # оставляющая реестр без резолвимого `default`, уходила бы на диск молча —
        # старт падал бы только после активации профиля. Ранний `return` до этой
        # проверки был как раз той дырой.
        ops = self._rename_ops(prev, alias, fields) if renaming else [
            ("upsert_model", alias, fields)]
        if self._needs_default_slot(ops):
            # Вторая модель делает реестр неоднозначным (спека §4): валидатор отвергнет
            # такую запись отдельной операцией — и правильно. Спрашиваем слот и уходим
            # ОДНОЙ транзакцией (решение Task 1). Выбор — из ЭФФЕКТИВНОГО реестра:
            # слот профиля законно указывает на запись основного конфига, и прятать
            # её из списка значило бы предлагать неполный набор ответов.
            #
            # `prev` вычитается ТОЛЬКО при переименовании: тогда этот алиас исчезает
            # ЭТОЙ ЖЕ транзакцией, и выбор его отказал бы «slots.default: алиас не
            # найден» — слот целился бы в запись, которой в реестре уже не будет.
            # Правка полей БЕЗ переименования — другой случай: `prev == alias`, и
            # огульное вычитание выкинуло бы из списка алиас, чьи поля как раз правит
            # форма, хотя он никуда не девается (находка ревью).
            aliases = sorted({*self._effective_aliases, alias} - ({prev} if renaming else set()))
            # Строку своей записи описывает то, что уедет в файл ЭТОЙ транзакцией: в
            # файле её ещё нет под этим именем — при переименовании содержимое берётся
            # из СТАРОЙ записи (`prev`), как и у самого `_rename_ops`, иначе витрина
            # потеряла бы нетронутые ключи. Описания собираются здесь и целиком —
            # `_refresh_picker_rows` их только усекает, — поэтому подмена снимается
            # сразу же.
            self._writing_entry = (alias, self._merged_entry(prev if renaming else alias,
                                                              fields))
            try:
                model_w = max(len(self._entry_model(a)) for a in aliases)
                rows = [self._picker_alias_item(a, model_w) for a in aliases]
            finally:
                self._writing_entry = None
            self._open_picker(rows, lambda chosen: self._write(
                ops + [("write_slot", "default", chosen)], alias),
                hint=_PICKER_DEFAULT_HINT)
            return
        self._write(ops, alias)

    def _rename_ops(self, prev: str, alias: str, fields: dict) -> list:
        """Переименование записи — ОДНА транзакция: новая запись с полным содержимым
        старой (merge правок формы здесь, а не у писателя: под новым именем записи
        ещё нет, и писательский merge стартовал бы с пустоты, теряя нетронутые
        ключи), переезд всех ссылок slots/assign, снятие старой записи. Порядок
        важен: к моменту `remove_model` на старое имя уже никто не ссылается.
        Валидация — одна, на итог; занятое имя отвергла форма."""
        ops: list = [("upsert_model", alias, self._merged_entry(prev, fields))]
        for level in LEVELS:
            if self._slot_value(level) == prev:
                ops.append(("write_slot", level, alias))
        for consumer in assign_consumers():
            if self._assign_value(consumer) == prev:
                ops.append(("write_assign", consumer, alias))
        ops.append(("remove_model", prev, True))
        return ops

    def _merged_entry(self, alias: str, fields: dict) -> dict:
        """Запись, какой она станет после правок формы: `fields` поверх своей старой
        по контракту писателя (значение — установить, `None` — снять, ключа нет —
        оставить как было).

        Одна на обоих, кому итог нужен ДО записи: `_rename_ops` собирает им
        переезжающую под новое имя запись, пикер default-слота — описание строки той,
        которой в файле ещё нет. Второй раз выписанное правило merge'а разъехалось бы
        с писателем на первой же правке контракта."""
        merged = dict(self._own_entry(alias))
        for key, value in fields.items():
            if value is None:
                merged.pop(key, None)
            else:
                merged[key] = value
        return merged

    def _needs_default_slot(self, ops: list) -> bool:
        """Спрашивать ли «какая модель по умолчанию»: оставит ли ЭТА транзакция стек
        без резолвимого `default` (§7).

        Спрашивается у слоя записи, а не считается здесь: правило резолвимости одно,
        и своя его редакция в секции разъезжалась с валидатором — считала по своему
        файлу плюс тень, а тень есть только у под-вида профиля."""
        from gc_core.config_modules.registry_write import needs_default_slot
        return needs_default_slot(self._target, ops, self._template,
                                  is_profile=self._is_profile,
                                  stack_base=self._stack_base)

    def _write(self, ops: list, alias: str) -> None:
        from gc_core.config_modules.registry_write import RegistryWriteError, apply_registry_ops
        try:
            apply_registry_ops(self._target, ops, self._template,
                               is_profile=self._is_profile,
                               stack_base=self._stack_base)
        except (RegistryWriteError, OSError) as exc:
            self._notice(f"✗ не сохранено: {exc}", ok=False)
            if self._form is not None:
                # Форма осталась смонтированной — оба пути СЮДА (подтверждение
                # ${ENV:…} и вопрос «какая модель по умолчанию») перед собой снимают
                # фокус ради баннера/пикера (`_submit_form`, `_open_picker`) и никто,
                # кроме Esc (`escape()`), фокус не возвращал. Отказ записи — не Esc:
                # черновик остаётся в полях, и без возврата фокуса клавиатура мертва
                # (L21 ревью MR #80, находка #8).
                #
                # Пикер вопроса о слоте закрывается ПЕРЕД возвратом фокуса (канон
                # `escape()`): `_pick` его не снимает, и refocus поверх живого
                # пикера давал двоевластие — каретка в Input, а ↑/↓/Enter уходят
                # пикеру, состав же транзакции уже заморожен: правки полей молча
                # терялись. Вопрос снят вместе с отказом — повторный submit задаст
                # его заново по свежим полям.
                self._close_picker()
                self._form.refocus()
            return
        self._form = None
        self._close_picker()
        # `_changed()` — ПЕРЕД перечиткой: он сбрасывает снимки экрана, из которых
        # `_reload` тут же и собирает тело (происхождение реестра — первым делом,
        # в `_legacy_default`). Обратный порядок судил бы о слое сверху состоянием
        # ДО этой записи: снятая последняя запись базы под живым реестром слоя
        # выше подняла бы легаси-редактор `agent.model`, который там не действует.
        self._changed()
        self._reload()
        self._cursor_to(alias)
        self._refresh_rows()
        if not self._entry_address(alias):
            # Оба предупреждения (адрес и литеральный токен) едут каналом `ok=None`
            # — ОДНИМ виджетом (`_singleton`), и второй вызов подряд его не
            # дополняет, а замещает. Склеены здесь, а не по два отдельных вызова
            # (L21 ревью MR #80, находка #7).
            self._warn_literal_tokens(f"⚠ запись «{alias}» сохранена в "
                                      f"{Path(self._target).name}, но {_NO_ADDRESS_HINT}")
        else:
            self._notice(_NOTICE_ENTRY_SAVED.format(alias=alias,
                                                    file=Path(self._target).name), ok=True)
            self._warn_literal_tokens()

    def _warn_literal_tokens(self, pending: str | None = None) -> None:
        """Предупреждение секрет-политики — рядом с итогом записи и по ИТОГОВОМУ
        документу цели (перечитан `_reload` строкой выше): судится то, что реально
        легло в файл, тем же `find_literal_tokens`, каким судит загрузчик.
        Реализация загрузчика (`load_profile_document(warn_literal_tokens=…)`)
        срабатывает только при сборке стека и только для АКТИВНОГО профиля — токен
        в неактивном проектном профиле лежал в git без единого слова, и узнавали
        об этом после push.

        `pending` — уже готовый текст, которому идти тем же каналом (`ok=None`):
        предупреждение об отсутствующем адресе. Канал общий с плашкой успеха
        (`ok=True`) не заменяет — они в разных виджетах; а вот с ЭТИМ
        предупреждением он ОДИН И ТОТ ЖЕ виджет (`#set-notice`), и второй вызов
        подряд заместил бы первый целиком. `pending` печатается ПЕРВОЙ строкой
        одним вызовом с находками `find_literal_tokens`, если они есть, — обе
        строки видны разом взаправду, а не только когда докстрока обещала."""
        lines = [pending] if pending else []
        if self._project_profile:
            from gc_core.config_modules.profiles import find_literal_tokens
            lines.extend(_NOTICE_LITERAL_TOKEN.format(path=self._target, alias=alias)
                        for alias in find_literal_tokens(self._document))
        if lines:
            self._notice("\n".join(lines), ok=None)

    def _cursor_to(self, alias: str) -> None:
        """Курсор на строку записи — поиском ПО СТРОКАМ: индекс алиаса в реестре и
        индекс его строки разошлись (унаследованные записи стоят выше своих, а
        свёрнутый блок строк не даёт вовсе). Строки нет — курсор остаётся где был."""
        for i, row in enumerate(self._rows()):
            if row["kind"] == "entry" and row["alias"] == alias:
                self._idx = i
                return

    def _write_binding(self, op: tuple, done: str) -> None:
        """Запись слота/привязки — немедленно по выбору, через тот же слой с
        валидацией результата (решение 2): нерезолвимая комбинация (снятый последний
        слот при двух моделях в реестре) отвергается целиком, файл байт-в-байт не
        тронут, отказ называет причину от валидатора."""
        from gc_core.config_modules.registry_write import RegistryWriteError, apply_registry_ops
        self._close_picker()
        kind, key, chosen = op
        current = (self._slot_value(key) if kind == "write_slot"
                   else self._assign_value(key))
        if chosen == current and not (chosen is None and self._binding_key_present(kind, key)):
            # Выбрано ТЕКУЩЕЕ значение файла (обещание `_open_picker` дословно:
            # «Enter без движения — no-op записи того же значения») — файл не
            # изменится, и `done` рапортовал бы «✓ Слот снят» о ключе, которого
            # в файле не было. Значение файла — теми же аксессорами, какими пикер
            # открывался на нём (`current=` в `_open_value_picker`).
            #
            # Исключение — ключ в файле ЕСТЬ, но мусорный/пустой (`_slot_value`/
            # `_assign_value` нормализуют его в тот же `None`, что и честное
            # отсутствие ключа): снятие такого ключа МЕНЯЕТ файл, и судить no-op
            # надо по факту записи (`_binding_key_present`), а не по значению
            # после нормализации (L21 ревью MR #80, находка #6).
            self._notice(_NOTICE_NO_CHANGE, ok=None)
            return
        try:
            apply_registry_ops(self._target, [op], self._template,
                               is_profile=self._is_profile,
                               stack_base=self._stack_base)
        except (RegistryWriteError, OSError) as exc:
            self._notice(f"✗ не сохранено: {exc}", ok=False)
            return
        self._changed()             # снимки экрана — до перечитки (см. `_write`)
        self._reload()
        self._refresh_rows()        # подводка курсора — как у записи в реестр
        self._notice(f"{done} — {Path(self._target).name}", ok=True)

    @staticmethod
    def _slot_notice(level: str, chosen) -> str:
        if chosen is None:
            return f"Слот «{level}» снят"
        return f"Уровень «{level}» → «{chosen}»"

    @staticmethod
    def _assign_notice(consumer: str, chosen) -> str:
        label = consumer_labels()[consumer]
        if chosen is None:
            return f"Привязка «{label}» снята"
        return f"Привязка «{label}» → «{chosen}»"

    # --- удаление -------------------------------------------------------------
    def request_remove(self) -> bool:
        if self._pending is not None or self._form is not None or self._picker is not None:
            return False
        row = self._row_at_cursor()
        if row is None or row["kind"] != "entry":
            return False                    # резервную модель удалять нечем — она поле
        from gc_core.config_modules.registry_write import (RegistryWriteError,
                                                   alias_survives_removal,
                                                   references_broken_by_removal,
                                                   references_to)
        alias = row["alias"]
        if self._entry_origin(alias) == "base":
            # Отказ СРАЗУ, без confirm-баннера (ревизия владельца по смоку A+B):
            # баннер «точно удалить?» обещал бы удаление, которого не случится ни
            # при каком ответе — вопрос ложен, а не преждевременен. Ветка
            # `removed=False` в `confirm_pending` остаётся страховкой от гонки
            # (запись исчезла из файла между баннером и Enter).
            self._notice(_NOTICE_REMOVE_REFUSED_INHERITED.format(alias=alias), ok=False)
            return False
        try:
            foreign = references_broken_by_removal(self._target, alias,
                                             stack_base=self._stack_base)
        except (RegistryWriteError, OSError):
            foreign = []            # чужой слой нечитаем — своё удаление это не запрещает
        if foreign:
            # Тот же приём, что и с унаследованной записью: вопрос ложен, а не
            # преждевременен — снять запись, на которую смотрит другой файл, нельзя
            # ни при каком ответе.
            self._notice(_NOTICE_REMOVE_REFUSED_CROSS_LAYER.format(
                alias=alias,
                refs=", ".join(f"{name}: {coordinate}" for name, coordinate in foreign)),
                ok=False)
            return False
        if (not self._needs_default_slot([])
                and self._needs_default_slot([("remove_model", alias, True)])):
            # Третий случай того же рода: каскад снимет ссылку и оставит стек без
            # резолвимого `default`. Валидатор такую транзакцию отвергает, и баннер
            # обещал бы снятие, которого не случится ни при каком ответе — удалить
            # запись было нельзя вовсе. Правило спрашивается там же, где его
            # спрашивает форма записи перед своей транзакцией.
            #
            # Спрашиваем ДВАЖДЫ, потому что вопрос — «ухудшит ли транзакция», а не
            # «будет ли плохо после». Реестр, которому слота не хватает и сейчас,
            # удалением записи хуже не станет: запрещать тут значило бы держать
            # человека в конфиге, который он как раз и разбирает.
            self._notice(_NOTICE_REMOVE_REFUSED_NEEDS_DEFAULT.format(alias=alias), ok=False)
            return False
        try:
            references = references_to(self._target, alias)
        except (RegistryWriteError, OSError) as exc:
            # Файл испортили под ногами между кадрами: спрашивать «удалить?» не о чем,
            # но и падать нельзя — говорим причину.
            self._notice(f"✗ не удалено: {exc}", ok=False)
            return False
        # Тёзка базовой записи (профиль перекрыл имя базы своей записью) переживает
        # СВОЁ удаление: `alias_survives_removal` — тот же предикат, что уже решает
        # отказ по чужому слою выше. Обе клаузы баннера обязаны знать про выживание:
        # «реестр станет пустым» — про ЭФФЕКТИВНЫЙ реестр (§5), а `_effective_aliases`
        # совпадает с `[alias]` и тогда, когда база продолжит отдавать ту же запись;
        # «ссылки снимутся» — про СВОИ же слот/привязку на алиас, а каскад их не
        # трогает (`keep_references=True` у `_apply_ops_to_text`) именно потому, что
        # алиас продолжит резолвиться.
        survives = alias_survives_removal(self._target, alias, stack_base=self._stack_base)
        last = self._effective_aliases == [alias] and not survives
        if survives:
            references = []
        self._pending = {"alias": alias, "references": references, "last": last}
        return self._ask(self._confirm_text(alias, references, last), _FOOTER_CONFIRM)

    def _ask(self, question: str, keys: str) -> bool:
        """Смонтировать confirm-баннер: сам вопрос плюс клавиши ЕГО футера — второй
        раз слова клавиш не пишутся, иначе вопрос и футер разошлись бы обещаниями."""
        banner = Static(Text(f"{question} {keys}", style=WARN),
                        classes=f"models-confirm onb-dyn {KEEP_IN_VIEW}", markup=False)
        self.mount(banner)
        # Вопрос монтируется в КОНЕЦ тела секции, а тело длиннее вьюпорта рамки: без
        # подводки футер честно менялся на «Enter — удалить», а самого вопроса на
        # экране не было — Enter приходилось жать вслепую.
        reveal_focus(self)
        return True

    @staticmethod
    def _confirm_text(alias: str, references: list, last: bool) -> str:
        parts = [f"Удалить запись «{alias}» из реестра?"]
        if references:
            parts.append("На неё ссылаются " + ", ".join(references)
                         + " — ссылки снимутся вместе с ней.")
        if last:
            parts.append("Реестр станет пустым — уровни выключатся.")
        return " ".join(parts)

    def confirm_pending(self) -> None:
        pending = self._pending
        self._clear_confirm()
        if pending is None:
            return
        from gc_core.config_modules.registry_write import RegistryWriteError, remove_model
        try:
            report = remove_model(self._target, pending["alias"], force=True,
                                  is_profile=self._is_profile,
                                  stack_base=self._stack_base)
        except (RegistryWriteError, OSError) as exc:
            self._notice(f"✗ не удалено: {exc}", ok=False)
            return
        if not report.removed:
            # Записи нет в ФАЙЛЕ ЦЕЛИ — писатель отвечает отчётом, а не исключением
            # (`RemovalReport(removed=False)`), и рапорт об удалении был бы ложным.
            # Файл менялся под ногами (сюда попадают только гонкой: отказ по тени
            # `request_remove` даёт до баннера) — экран обязан догнать диск, и
            # текст судится по СВЕЖЕМУ состоянию: строка либо продолжает стоять
            # тенью (тёзку унесли из профиля — прежний отказ про запись основного
            # конфига), либо исчезла вовсе, и прежний единственный текст слал
            # «удалите в секции «Модели»» человека, который в ней и стоит.
            self._reload()
            if self._shadowed and pending["alias"] in self._base_entries:
                self._notice(_NOTICE_REMOVE_REFUSED_INHERITED.format(
                    alias=pending["alias"]), ok=False)
            else:
                self._notice(_NOTICE_REMOVE_RACED.format(
                    alias=pending["alias"], file=Path(self._target).name), ok=False)
            return
        self._changed()             # снимки экрана — до перечитки (см. `_write`)
        self._reload()
        self._notice(f"Запись «{pending['alias']}» удалена — {Path(self._target).name}",
                     ok=True)

    def cancel_pending(self) -> None:
        self._clear_confirm()

    def _clear_confirm(self) -> None:
        self._pending = None
        for widget in self.query(".models-confirm"):
            widget.remove()

    def _clear_env_confirm(self) -> None:
        """Снять вопрос о перезаписи ссылки (L22). Класс баннера тот же, что у
        confirm удаления (`_ask` один на оба), а состояния взаимоисключающие —
        снос по классу чужого не заденет."""
        self._env_pending = None
        for widget in self.query(".models-confirm"):
            widget.remove()

    # --- инлайн-пикер значений (решение 9: свой механизм раскрытия) -----------
    def _row_widget(self, idx: int):
        widgets = list(self.query(".models-row"))
        return widgets[idx] if 0 <= idx < len(widgets) else None

    def _picker_alias_item(self, alias: str, model_w: int) -> dict:
        """Позиция-модель: справа ТЕ ЖЕ колонки, что у строки реестра (id + адрес),
        — по одному id модели не различить (две записи на один id, разные endpoint'ы),
        а выбор вслепую и был проблемой плоского списка.

        При активной тени пикер зеркалит реестр и ПРОИСХОЖДЕНИЕМ (ревизия
        владельца по смоку A+B): свои — ярко, унаследованные — приглушённо; иначе
        строка, белая в реестре, серела в списке, и глазу приходилось сверять по
        имени. Без тени (основная секция) — прежний DIM."""
        desc = Text()
        if self._base_entries and self._entry_origin(alias) != "base":
            label_style = INK
            desc.append(self._entry_model(alias).ljust(model_w), style=DIM)
        else:
            label_style = DEEP_DIM if self._base_entries else None
            desc.append(self._entry_model(alias).ljust(model_w),
                        style=DEEP_DIM if self._base_entries else DIM)
        cell = self._address_cell(alias)
        if cell:
            desc.append("  ")
            desc.append(cell, style=DEEP_DIM)
        item = {"value": alias, "label": alias, "desc": desc}
        if label_style is not None:
            item["label_style"] = label_style
        return item

    def _picker_fallback_desc(self, level: str) -> Text:
        """Крашеная версия `_slot_fallback_text` для строк пикера: имя уровня — своим
        цветом (§12.4: уровень выглядит одинаково на всём экране), алиас — DIM как
        прочие алиасы-значения. Ветки без имени уровня остаются ровным DEEP_DIM."""
        candidate, alias = self._slot_fallback(level)
        if candidate is None:
            return Text(self._slot_fallback_text(level), style=DEEP_DIM)
        t = Text("действует ", style=DEEP_DIM)
        t.append(candidate, style=value_style(candidate))
        t.append(" → ", style=DEEP_DIM)
        t.append(alias, style=DIM)
        return t

    def _picker_inherited_desc(self, value: str) -> Text:
        """Описание первой строки, когда снятие своего ключа вернёт значение
        основного конфига: «→ gc» — ровно хвост подписи строки после слова
        «основной» (канон тождества «подпись строки ↔ первый пункт»). Стрелка —
        DEEP_DIM, значение — своим цветом (§12.4: уровень и алиас выглядят
        одинаково на всём экране)."""
        t = Text("→ ", style=DEEP_DIM)
        t.append(value, style=value_style(value))
        return t

    def _picker_unset_row(self, inherited, label: str, desc: Text) -> dict:
        """Первая позиция пикера — снятие СВОЕГО ключа (`value is None`, §7-8).

        Значение основного конфига под ним есть — подпись «основной» и описание
        «→ gc»: пункт отвечает «что будет после снятия», а будет ровно оно. Нет —
        прежние «не задан»/«активная» со своим описанием-фоллбэком."""
        if inherited:
            return {"value": None, "label": _INHERITED_LABEL,
                    "desc": self._picker_inherited_desc(inherited)}
        return {"value": None, "label": label, "desc": desc}

    def _picker_level_desc(self, level: str) -> Text:
        """Позиция-уровень отвечает «что реально произойдёт»: на какую модель уровень
        указывает СЕЙЧАС, — а не описание роли (оно стоит в блоке «уровни» выше).
        Уровень берётся эффективный (§8): не переопределённый профилем слот
        продолжает работать раскладкой основного конфига."""
        alias = self._effective_slot_value(level)
        t = Text()
        if alias:
            # «→» — не `_LEVEL_TAIL_LEAD`: у указателя реестра стрелка смотрит
            # НА запись («← light»), здесь — ОТ уровня к модели.
            t.append("→ ", style=DEEP_DIM)
            t.append(alias, style=DIM)
        else:
            t.append(f"{_SLOT_UNSET} · ", style=DEEP_DIM)
            t.append_text(self._picker_fallback_desc(level))
        return t

    def _picker_active_desc(self) -> Text:
        t = Text(_ACTIVE_DESC_LEAD, style=DEEP_DIM)
        t.append(self._active_level, style=value_style(self._active_level))
        return t

    def _open_value_picker(self, row: dict) -> None:
        """Список значений строки слота/привязки — ПОД ней (решение 9).

        Слот указывает на алиас реестра, привязка — ещё и на уровень (индирекция
        через слоты). Первая позиция обеих — снятие значения: отдельной клавиши
        снятия нет (Global Constraints), а «не задан»/«активная» — не значения, а
        отсутствие ключа в файле. `on_pick` получает `None` именно за неё —
        сентинел опознаётся строкой с `value is None` и до записи доезжает тем же
        `None`, которым снимает ключ слой записи.

        Уровни и алиасы идут сплошным списком, без черт-разделителей: группы и так
        различимы правой колонкой («→ модель» против «id + адрес») и цветом
        подписи (ревизия владельца — черты внутри дропдауна резали список).

        Модели — ЭФФЕКТИВНОГО реестра и в порядке реестра секции (§7): профиль
        законно ссылается на записи основного конфига, а второй порядок одного и
        того же списка читался бы как второй список."""
        anchor = self._row_widget(self._idx)
        model_w = self._model_width()
        alias_items = [self._picker_alias_item(a, model_w)
                       for a in self._effective_aliases]
        if row["kind"] == "slot":
            level = row["level"]
            rows = [self._picker_unset_row(self._base_slot_value(level), _SLOT_UNSET,
                                           self._picker_fallback_desc(level)),
                    *alias_items]
            self._open_picker(rows, lambda chosen: self._write_binding(
                ("write_slot", level, chosen), self._slot_notice(level, chosen)),
                after=anchor, current=self._slot_value(level))
            return
        consumer = row["consumer"]
        rows = ([self._picker_unset_row(self._base_assign_value(consumer),
                                        _ASSIGN_ACTIVE, self._picker_active_desc())]
                + [{"value": lvl, "label": lvl, "desc": self._picker_level_desc(lvl)}
                   for lvl in LEVELS]
                + alias_items)
        self._open_picker(rows, lambda chosen: self._write_binding(
            ("write_assign", consumer, chosen),
            self._assign_notice(consumer, chosen)),
            after=anchor, current=self._assign_value(consumer))

    def _open_picker(self, rows: list, on_pick, *, hint: str | None = None,
                     after=None, current=None) -> None:
        """Строки — словари `{"value", "label", "desc"}`; `value is None` — снятие
        ключа.

        Курсор открывается на ТЕКУЩЕМ значении строки (`current`): выбранное видно
        сразу, Enter без движения — no-op записи того же значения. Ключа в файле
        нет — `current=None` находит первую строку (она и есть «снято»).

        `hint` у пикеров значений НЕ монтируется: каждая позиция объясняет себя
        своей правой колонкой, а общий текст под списком говорил бы только про
        первую строку. Остался он один — вопрос формы «какая модель по умолчанию»,
        там hint и есть сам вопрос."""
        idx = next((i for i, r in enumerate(rows) if r["value"] == current), 0)
        # `width` — ширина рамки, под которую посчитаны колонки списка (сосед
        # `_measured_width` строк секции): часть формы пикера с самого начала, а не
        # ключ, появляющийся после первой отрисовки, — иначе читателям пришлось бы
        # гадать `.get` он или `[...]`. `None` — ещё не измерено.
        self._picker = {"rows": rows, "idx": idx, "on_pick": on_pick, "width": None}
        if self._form is not None:
            # Вопрос формы («какая модель по умолчанию») висит НАД живой формой, и
            # её поля остаются в фокусе. Гейты `probe`/`space`/`clear_token` держат
            # только те клавиши, которые экран ведёт САМ; всё остальное — печать,
            # Backspace, штатный `delete_left_all` у `Ctrl+U` — Textual доставляет
            # прямо в поле, и человек правит текст, уже зафиксированный в
            # транзакции. Снимаем фокус: пока вопрос висит, клавиатура его.
            self.screen.set_focus(None)
        # Строка-якорь на время раскрытия теряет нижний воздух (.set-spaced):
        # список — продолжение строки и обязан стоять к ней вплотную.
        if after is not None:
            after.add_class("models-picker-anchor")
        scroll = VerticalScroll(classes="dropdown-scroll onb-dyn models-picker")
        scroll.can_focus = False
        self.mount(scroll, after=after)
        if not scroll.is_attached:
            return
        scroll.mount(*[Static("", classes="onb-option onb-dyn models-picker-row")
                       for _ in rows])
        if hint is not None:
            self.mount(Static(hint, classes="onb-hint onb-dyn models-picker-hint",
                              markup=False), after=scroll)
        self._refresh_picker_rows()

    def _picker_width(self):
        """Ширина строки пикера внутри её padding (`.onb-option`: `padding: 0 1`).
        `None` — рамки ещё нет (первый кадр, до layout-прохода): усечения нет,
        досчитает `_confirm_picker_width`.

        Сентинелом здесь служит именно `None`, а не 0, как у `_row_width`: у строк
        списка «0 колонок» не бывает (их держит рамка секции), а у строки ПИКЕРА
        бывает — рамка `.dropdown-scroll` со своим бордюром на узком окне отдаёт
        под содержимое ноль колонок. Спутать «не измерено» с «нуль» здесь нельзя:
        трактовка «не измерено» печатает полный текст, тот переносится на десятки
        строк, список перерастает `max-height` и заводит скроллбар — а скроллбар
        отнимает колонку и делает замер снова другим. Замер бы не сошёлся никогда."""
        widgets = list(self.query(".models-picker-row"))
        if not widgets or widgets[-1].region.width <= 0:
            return None
        return max(0, widgets[-1].region.width - 2)

    def _confirm_picker_width(self) -> None:
        """Самоподтверждение замера — близнец `_confirm_width` строк списка: рамка
        `.dropdown-scroll` заводит свой скроллбар уже после раскладки, и первый
        проход считал бы колонки по прежней ширине. Сходимость гарантирована тем,
        что высота строки от ширины не зависит — строка не переносится."""
        if self._picker is not None and self._picker["width"] != self._picker_width():
            self._refresh_picker_rows()

    def _refresh_picker_rows(self) -> None:
        """Строка пикера не переносится НИ НА КАКОЙ ширине — та же дисциплина, что
        у строк списка, и та же лестница жертв: сперва ужимается описание (оно —
        хвост, `Text.truncate` с многоточием сохраняет раскраску начала), потом
        сама подпись (`fit_cell`), в пределе описания нет вовсе вместе с его
        зазором. Усекается КОПИЯ описания: оригинал живёт в `_picker["rows"]` и
        переживает ресайзы — усечённый на узкой рамке, обратно он бы не вырос."""
        if self._picker is None:
            return
        rows = self._picker["rows"]
        widgets = list(self.query(".models-picker-row"))
        width = self._picker_width()
        self._picker["width"] = width
        label_w = max([len(r["label"]) for r in rows] + [0])
        if width is not None:
            label_w = min(label_w, max(0, width - 2))
        for i, (widget, row) in enumerate(zip(widgets, rows)):
            selected = i == self._picker["idx"]
            if width is not None and width < 2:
                # Места нет даже под курсор — строка пустая: перенос двух его
                # колонок на вторую строку ничего не сообщает, а список превращает
                # в лестницу огрызков.
                widget.update(Text())
                widget.set_class(selected, "selected")
                continue
            text = Text()
            text.append("▸ " if selected else "  ", style=ACCENT)
            # Снятие — по `value is None`, не по тексту подписи: алиас с именем
            # «не задан» схемой разрешён.
            unset = row["value"] is None
            if label_w:
                # Цвет — по ПОЛНОЙ подписи: усечение говорит о ширине рамки, а не
                # о том, уровень это или алиас. `label_style` строки (происхождение
                # в профильном пикере) перекрывает словарь значений.
                style = (DEEP_DIM if unset
                         else row.get("label_style") or value_style(row["label"]))
                text.append(fit_cell(row["label"], label_w).ljust(label_w),
                            style=style)
            desc = row.get("desc")
            budget = 0 if width is None else width - 2 - label_w - 2
            if desc is not None and desc.plain and (width is None or budget > 0):
                if width is not None:
                    desc = desc.copy()
                    desc.truncate(budget, overflow="ellipsis")
                text.append("  ")
                text.append_text(desc)
            widget.update(text)
            widget.set_class(selected, "selected")
        if 0 <= self._picker["idx"] < len(widgets):
            # Своя строка в раскрытом списке — тот же приём, что у `field_list`:
            # ↑/↓ крутят ВНУТРЕННИЙ скролл `.dropdown-scroll`, за курсором Textual
            # не следит.
            self.call_after_refresh(widgets[self._picker["idx"]].scroll_visible,
                                    animate=False)
        self.call_after_refresh(self._confirm_picker_width)

    def _pick(self) -> None:
        picker = self._picker
        if picker is None:
            return
        row = picker["rows"][picker["idx"]]
        picker["on_pick"](row["value"])

    def _close_picker(self) -> None:
        self._picker = None
        for widget in self.query(".models-picker, .models-picker-hint"):
            widget.remove()
        for widget in self.query(".models-picker-anchor"):
            widget.remove_class("models-picker-anchor")

    # --- связь с экраном ------------------------------------------------------
    def _notice(self, text: str, *, ok) -> None:
        if self._on_notice is not None:
            self._on_notice(text, ok=ok)

    def _changed(self) -> None:
        if self._on_change is not None:
            self._on_change()
