def _hhmm(ts: float) -> str:
    """Момент как «часы:минуты» локального времени — один формат на весь экран.

    Читают и расшифровка глифа `↺` (`accepted_caption`), и строка потери в
    подтверждении сброса (`reset_loss_line`): третья редакция того же
    `strftime` рано или поздно разъехалась бы с первыми двумя.
    """
    return time.strftime("%H:%M", time.localtime(ts))


def accepted_caption(ts: float) -> str:
    """«счёт от принятого состояния (HH:MM)» — расшифровка глифа `↺` в шапке вьюера."""
    return f"{ACCEPTED_CAPTION_STEM} ({_hhmm(ts)})"


