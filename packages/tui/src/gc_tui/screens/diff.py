"""Экран изменений агента (`/diff`, F3) — список файлов и вьюер одного файла.

Данные приходят готовыми из `tui.services.edits_view`: экран ничего не считает
сам, иначе то же число разъехалось бы со сводкой хода в статусной строке (Р11).
Здесь только представление — сетка строки, шапка, курсор и навигация.

**Сетка строки — общая для всего списка, а не для каждой строки своя.** Ширины
колонок «вид правки», «пометки», «+N», «−M» считаются по максимуму ПО ВСЕМУ
набору до отрисовки: пользователь сверяет счётчики глазом по вертикали, и
колонка, которая едет от строки к строке, эту работу ломает. Пометки при этом
прижаты вправо, а знак `≈` (числа неточные) живёт в собственном слоте перед
`+N` и не жертвуется никогда — он про достоверность самих чисел.

Состояние индекса git на этом экране больше не показывается нигде — ни
колонкой списка (снята раньше), ни строкой шапки вьюера (снята Задачей 14):
Р21 отменена целиком (§13 плана волны 4). Роль забрали глиф `↺` принятой
базы (сразу после счётчиков, только когда действующая ступень `ActiveRow.step`
— `accepted`, — значит, счёт и откат идут не от начала сессии) и группа
«принято» внизу списка.

Группа «принято» (§4.1/§4.2 плана волны 4) — файлы, на которые смотреть уже
нечего (принято и чисто, либо чисто закоммичено), сворачиваются в одну строку
внизу списка вместо того, чтобы теряться среди активных. Курсор ходит по ОДНОМУ
плоскому списку — активные, затем строка группы, затем (раскрыта — Enter/клик)
её файлы, — тот же приём, что у `/sessions`: разбирать «что это за строка»
нужно только в двух местах (`_activate_selected`, открытие вьюера), не на
каждом шаге навигации.

Счётчики красятся смыслом правки: `+N` — `OK`, `−M` — `ERR`, ровно те цвета,
которыми движок правок красит гаттер тела диффа. Тусклым остаётся только `≈`.
Правило одно на весь экран — строки списка, шапка списка, шапка вьюера и
заголовок подтверждения отката: числа в них сверяют глазом, а не читают.
Внутри группы «принято» тот же смысл красит счётчики притушённым вариантом
тех же цветов (С2 смоука волны 4) — строка группы приглушена целиком, и
полная яркость спорила бы с этим, а цвет `+`/`−` обязан остаться значимым,
а не серым.

Пометка — флаг события, а не «кто правил последним»: `командой` и `извне`
независимы и складываются. Правки инструментами агента — норма, их не
подписывают вовсе.

Тело вьюера рисует ТОТ ЖЕ движок `diff_render`, что и блоки правок в трейсе:
цвета, колонка номеров, заливка и внутристрочная подсветка — один в один, своих
стилей у вьюера нет. Иначе один и тот же дифф выглядел бы в двух местах
продукта по-разному. Разница только в порядке: блок ленты просит нарисовать
тело целиком (`render_hunks`), а экраны правок — участками, по мере попадания в
кадр (`HunkBody`, Р23).

Тело собирается ЛЕНИВО (Р23) — и здесь, и в подтверждении отката. Число строк
участка известно из разбора входа, поэтому место под него резервируется до
всякой отрисовки: полоса прокрутки честна с первого кадра, содержимое не
прыгает, а рисуется то, что видно, плюс запас. Механизм общий — `LazyBody`.

Принятие (`a` — файл, `Ctrl+A` — всё представление) объявляет диск новой
точкой отсчёта — `.accepted` := текущее содержимое, затем, в git-проекте,
best-effort `git add` (пересмотр Р9: раньше `a` был голым git add, отдельной
клавиши «только застейджить» не осталось нигде). В отличие от старого git
add принятие МЕНЯЕТ данные экрана — база сдвигается, список перечитывается
целиком, и файл с пустой дельтой от новой базы в тот же миг уезжает в группу
«принято» (Р9 + §4.1). Отмена (`u` — файл, `Ctrl+U` — все принятые вручную)
снимает `.accepted`; подтверждение — полноэкранное, в жанре отката (см.
`RESET_CONFIRM_TITLE` ниже), и просит его только когда хоть один путь теряет
точку отката к принятому состоянию (`EditsView.reset_targets`) — иначе сброс
восстановил бы то же состояние, что и повторное принятие.

Массовые действия (`Ctrl+A`, `Ctrl+U`, `Ctrl+R`) живут ТОЛЬКО в списке, где
виден весь набор (Р20). Вьюер получает те же жесты над одним файлом — тем,
который в нём открыт: `a` принимает его, `u` снимает принятие, `r`
откатывает; любое из трёх меняет данные экрана, поэтому закрывает вьюер и
возвращает к списку, если что-то реально изменилось, — открытый файл мог
уехать из активных. Вьюер, открытый ИЗ ГРУППЫ разобранных, `a`/`r` не видит
вовсе (дельта от ступени пуста — зачитывать и откатывать нечего), `u` там
жив только у файлов, принятых вручную.

Итоги действий живут в канонной плашке (`.set-flash-ok`/`.set-flash-warn`,
§16), а отказы «сейчас нельзя» — во всплывающем уведомлении: плашка
рассказывает про случившееся и переживает перечитывание списка, а отказ
случается и из вьюера, где плашки списка не видно. Свою плашку вьюер поэтому
монтирует У СЕБЯ (`_ActionFlash`): экран списка лежит под ним и не виден.

Откат (`r` — файл, `Ctrl+R` — всё представление) живёт здесь только проводкой:
подтверждение — соседний экран `diff_revert_confirm`, запись на диск — сервис
`edits_view.revert`. Экран отвечает за три вещи, которые ниже сделать нельзя:
гасит откат на время живого прогона, отсеивает пути без достоверной базы до
показа подтверждения и собирает пользовательские тексты из машинных кодов
отказа.
"""

