class DiffScreen(_ActionFlash, Screen):
    """Изменения агента за сессию или за последний ход.

    Идентичность треда неполна (`/diff` до первой сессии) — экран открывается
    с объяснением, а не падает: `EditsView` требует все три части непустыми, и
    проверка идёт ДО его конструирования.
    """

    def __init__(
        self,
        *,
        launch_root: str,
        settings: Any = None,
        threads_dir: Optional[str] = None,
        system_id: Optional[str] = None,
        thread_id: Optional[str] = None,
        source: str = SOURCE_SESSION,
        on_undo_feedback: Optional[UndoFeedbackFn] = None,
        on_ui_ack: Optional[UiAckFn] = None,
    ) -> None:
        super().__init__()
        self._settings = settings
        self._on_undo_feedback = on_undo_feedback
        self._on_ui_ack = on_ui_ack
        self._source = source
        self._view = SessionView(source, None, [], [], 0, 0)
        self._entries: List[FileEntry] = []
        self._settled: List[SettledRow] = []
        self._group_expanded = False
        self._rows: List[Static] = []
        # Строка про урезанные команды, если показана: `x` снимает её одну, не
        # пересобирая список, — а список под ней почти всегда огромный.
        self._cut_note: Optional[Static] = None
        # Текст, который сейчас показан в каждой строке, — `_repaint_rows` трогает
        # только разошедшиеся.
        self._shown_texts: list = []
        self._selected_idx = 0
        # `Tab` — переключатель областей (С4 смоука волны 4): последняя строка
        # активной части, запомненная на момент ухода в группу. По умолчанию
        # первая строка — «Tab» назад без предшествующего «Tab» туда обязан
        # приземлиться на неё, а не оставаться на месте.
        self._active_cursor_memory = 0
        # Симметричная память группы (Д3 второго смоука) — ПУТЬ файла, а не
        # индекс: между двумя нажатиями список перечитывается, и голый индекс
        # указал бы на соседа. `None` — ушли с самой строки группы, возвращаться
        # надо туда же.
        self._group_cursor_memory: Optional[str] = None
        self._width = 0
        self._viewer: Optional[DiffFileViewer] = None
        # Вьюер, открытый из группы, листает файлы группы, а не активные (§4.3):
        # `on_screen_resume` обязан вернуть курсор в тот же список, откуда ушли.
        self._viewer_is_group = False
        self._edits: Optional[EditsView] = None
        self._thread_ident = (str(system_id), str(thread_id))
        if all((threads_dir, system_id, thread_id)):
            self._edits = EditsView(
                str(threads_dir),
                str(system_id),
                str(thread_id),
                str(launch_root),
                self._settings,
            )

    @property
    def source(self) -> str:
        return self._source

    @property
    def mode(self) -> str:
        return self._edits.mode if self._edits is not None else "cache-mode"

    # ---- каркас --------------------------------------------------------

    def compose(self) -> ComposeResult:
        with Vertical(id="root"):
            with Horizontal(id="header"):
                yield Static("", id="header-left", markup=False)
                yield Static("", id="header-right", markup=False)
            yield VerticalScroll(id="trace")
            yield Static("", id="footer", markup=False)

    def on_mount(self) -> None:
        self._reload()

    def on_resize(self, event: events.Resize) -> None:
        # Высота меняется тоже — но сетка строки зависит ТОЛЬКО от ширины;
        # пересборка списка на каждый Resize была бы работой впустую.
        if event.size.width == self._width:
            return
        self._width = event.size.width
        if self._edits is not None:
            self._render_screen()

    # ---- данные --------------------------------------------------------

    def _reload(self) -> None:
        """Перечитать источник и отрисовать экран целиком.

        Прочитанное остаётся в `self._view`: и шапка, и строки обязаны идти из
        ОДНОГО чтения, иначе «N файлов» и сам список могут разъехаться (Р11).
        Перерисовка курсора и смена ширины журнала уже не читают.
        """
        if self._edits is None:
            self._render_no_thread()
            return
        self._view = self._current_view()
        self._entries = [row.entry for row in self._view.active]
        self._settled = self._view.settled
        self._selected_idx = min(
            max(self._selected_idx, 0), max(0, self._row_count() - 1)
        )
        self._render_screen()

    def _current_view(self) -> SessionView:
        try:
            return self._edits.session_view(self._source)
        except Exception as exc:  # битый журнал не должен ронять весь TUI
            _logger.warning("изменения не прочитаны: %r", exc)
            return SessionView(self._source, None, [], [], 0, 0)

    # ---- плоский список: активные → группа → её файлы (§4.2) -----------

    def _row_count(self) -> int:
        """Число строк экрана, включая строку группы и, если раскрыта, её файлы."""
        n = len(self._entries)
        if self._settled:
            n += 1 + (len(self._settled) if self._group_expanded else 0)
        return n

    def _is_group_row(self, idx: int) -> bool:
        return bool(self._settled) and idx == len(self._entries)

    def _settled_index(self, idx: int) -> Optional[int]:
        """Индекс внутри `self._settled` для строки `idx` — либо `None`.

        `None`, когда `idx` не settled-строка (активная, строка группы) или
        группа сейчас свёрнута — тогда settled-строк на экране нет вовсе.
        """
        if not (self._settled and self._group_expanded):
            return None
        offset = idx - len(self._entries) - 1
        return offset if 0 <= offset < len(self._settled) else None

    # ---- рендер --------------------------------------------------------
    # Имя `_render` занято: `Widget._render` отдаёт Textual визуал виджета, и
    # свой метод с таким именем гасит отрисовку самого экрана.

    def _render_no_thread(self) -> None:
        self.query_one(_SEL_HEADER_LEFT, Static).update("")
        self.query_one("#header-right", Static).update("")
        self.query_one(_SEL_FOOTER, Static).update("Esc")
        trace = self.query_one(_SEL_TRACE, VerticalScroll)
        trace.remove_children()
        self._rows = []
        trace.mount(Static(NO_THREAD, classes="line-meta", markup=False))

    def _render_screen(self) -> None:
        left, right = build_header(
            self._source,
            files=len(self._entries),
            add=self._view.total_add,
            del_=self._view.total_del,
            mode=self.mode,
            width=self._header_width(),
            has_group=bool(self._settled),
            # Легенда — только про то, что реально видно на этом экране.
            legend_accepted=any(
                _step_is_accepted(row.step) for row in self._view.active
            ),
            legend_commit=any(
                _commit_hash(row.step) for row in self._view.active
            ),
            legend_external=any(
                row.entry.external for row in self._view.active
            ),
        )
        self.query_one(_SEL_HEADER_LEFT, Static).update(paint_counters(left))
        self.query_one("#header-right", Static).update(right)
        self._update_footer()

        trace = self.query_one(_SEL_TRACE, VerticalScroll)
        trace.remove_children()
        self._rows = []
        # Всё тело — ОДНИМ монтированием: Textual на каждом перебирает уже
        # смонтированных детей, и строки по одной давали квадрат (10 000
        # файлов открывались 96 секунд).
        widgets: List[Static] = []
        self._cut_note = None
        cut = self._shown_cut_commands()
        if cut:
            # Не строка списка: курсор на неё не встаёт, жесты её не касаются.
            widest = max(paths for _, paths in cut)
            self._cut_note = meta_line(
                Text.assemble(
                    (overflow_note(widest), WARN),
                    "  ",
                    (CUT_NOTE_HIDE, MUTED),
                )
            )
            widgets.append(self._cut_note)
        # Пустое состояние — только когда нет НИ активных, НИ группы (§4.2):
        # непустая группа при нуле активных — валидный экран, а не пустой.
        if not self._entries and not self._settled:
            empty = EMPTY_SESSION
            if self._source == SOURCE_TURN:
                empty = EMPTY_TURN_UNDONE if self._view.turn_id else EMPTY_TURN
            widgets.append(Static(empty, classes="line-meta", markup=False))
            trace.mount(*widgets)
            return
        texts = self._row_texts()
        for idx, text in enumerate(texts):
            classes = "diff-row"
            if self._is_group_row(idx):
                classes += " diff-group-row"
            if idx == self._selected_idx:
                classes += " selected"
            self._rows.append(Static(text, classes=classes, markup=False))
        self._shown_texts = list(texts)
        trace.mount(*widgets, *self._rows)
        self._scroll_to_cursor()

    def _dismissed_cut_commands(self) -> set:
        """Скрытые урезанные команды — в UI-состоянии приложения, до выхода.

        Экран живёт одно открытие F3, а прочитанное должно оставаться скрытым
        и при следующем. Строка построена по истории журнала, погаснуть сама
        не может, и после перезапуска напомнит о себе снова — не соврав:
        файлы сверх потолка так и остались изменёнными.
        """
        return self.app.tui_state.dismissed_cut_commands

    def _shown_cut_commands(self) -> List[Tuple[str, int]]:
        dismissed = self._dismissed_cut_commands()
        return [
            cmd
            for cmd in self._view.cut_commands
            if (*self._thread_ident, *cmd) not in dismissed
        ]

    def _hide_cut_note(self) -> None:
        """`x`: скрыть строку про урезанные команды — все, о которых она сейчас."""
        cut = self._shown_cut_commands()
        if not cut:
            return
        self._dismissed_cut_commands().update(
            (*self._thread_ident, *cmd) for cmd in cut
        )
        if self._cut_note is not None:
            self._cut_note.remove()
            self._cut_note = None

    def _update_footer(self) -> None:
        """Вторая строка футера — по строке под курсором (§13 плана волны 4).

        Вызывается и полной пересборкой (`_render_screen`), и точечной
        перерисовкой курсора (`_repaint_rows`): футер обязан поспевать за
        курсором так же, как строки списка.
        """
        active = self._selected_active()
        step = active.step if active is not None else None
        self.query_one(_SEL_FOOTER, Static).update(
            footer_text(
                row=self._footer_row(),
                empty=not self._entries and not self._settled,
                source=self._source,
                # Сегмент `Tab` — только когда переключать есть куда: с пустой
                # активной частью клавиша молчит (Д3), и реклама соврала бы.
                has_group=bool(self._settled and self._entries),
                # Реклама `u` и её исполнение — ОДИН расчёт (Ж4 батча 4):
                # раньше гейт брался только с активной строки, и на заголовке
                # группы, где `_reset_target` отдаёт `None`, футер обещал
                # клавишу, которой там нет.
                can_reset=self._reset_target(self._selected_idx) is not None,
                can_revert=active is not None and active.entry.revertable,
                step=step.kind if step is not None else None,
                # Заголовок группы называет `Enter` по текущему развороту (Ж3).
                group_expanded=self._group_expanded,
                # Массовые клавиши — решение ПРЕДСТАВЛЕНИЯ (Е4), не строки под
                # курсором: хвост одинаков независимо от `row`.
                mass_accept=bool(self._entries),
                mass_revert=any(entry.revertable for entry in self._entries),
                mass_reset=(
                    any(row.has_accepted_base for row in self._view.active)
                    or self._manual_accepted_count() > 0
                ),
            )
        )

    def _footer_row(self) -> str:
        """Состояние строки под курсором (`ROW_PLAIN`/`_ACCEPTED`/`_GROUP`/`_GROUP_FILE`).

        Заголовок группы и файл ВНУТРИ неё разведены (Ж3/Ж4 батча 4): `Enter`
        там делает разное (`_toggle_group` против `_open_group_viewer`), а `u`
        на самом заголовке мёртв — `_reset_target` отдаёт по нему `None`.
        """
        if self._is_group_row(self._selected_idx):
            return ROW_GROUP
        if self._settled_index(self._selected_idx) is not None:
            return ROW_GROUP_FILE
        if 0 <= self._selected_idx < len(
            self._entries
        ) and self._counts_from_accepted(
            self._entries[self._selected_idx].path
        ):
            return ROW_ACCEPTED
        return ROW_PLAIN

    def _cursor_in_group(self) -> bool:
        """Курсор сейчас на строке группы или внутри неё (§4.2) — вопрос
        переключателя областей `Tab` (`_toggle_group_focus`, С4 смоука волны
        4): ему нужна ОБЛАСТЬ целиком. Футер сюда больше не ходит — ему обе
        половины нужны врозь (Ж3/Ж4 батча 4, см. `_footer_row`)."""
        return self._is_group_row(self._selected_idx) or (
            self._settled_index(self._selected_idx) is not None
        )

    def _counts_from_accepted(self, path_key: str) -> bool:
        """Файл СЕЙЧАС считается от принятой ступени — не «у него есть `.accepted`».

        Футер этого состояния обещает «r откат — вернуть к принятому», и
        обещание правдиво, только когда действующая ступень «Сессии» — та
        самая `.accepted`. Наличия принятой базы для этого мало: тай-брейк
        Р28 мог отдать ступень HEAD (`r` вернёт к коммиту), а источник «Ход»
        ступеней не видит вовсе (`r` вернёт к началу хода) — глиф `↺` там
        стоит по факту принятия, но цель отката другая. Тот же гейт, что у
        подписи в шапке вьюера (`_open_viewer`).
        """
        return (
            self._edits is not None
            and self._source == SOURCE_SESSION
            and self._edits.accepted_step_ts(path_key) is not None
        )

    def _selected_active(self) -> Optional[ActiveRow]:
        """Активная строка под курсором — либо `None` (курсор в группе).

        Один ответ на два вопроса футера: есть ли достоверная база отката
        (гейт `r`, Д10) и какая ступень действует (цель `r`, Д4). Гейт `u`
        сюда больше не ходит — его считает `_reset_target` (Ж4 батча 4).
        Индекс держит тот же контракт, что `_reset_target`.
        """
        if not (0 <= self._selected_idx < len(self._entries)):
            return None
        return self._view.active[self._selected_idx]

    def _manual_accepted_count(self) -> int:
        """Сколько в группе принято ВРУЧНУЮ — гейт сегмента `Ctrl+U` (Р35)."""
        return sum(1 for row in self._settled if row.reason == SETTLED_MANUAL)

    def _row_texts(self) -> List[Text]:
        """Все строки экрана одним списком: активные → группа → её файлы (§4.2).

        Один плоский список — курсор (`self._selected_idx`) и монтаж
        (`_render_screen`/`_repaint_rows`) ходят по нему единообразно, без
        разбора «какая это строка» (курсор /sessions).
        """
        texts = self._active_texts()
        if self._settled:
            texts.append(self._group_text())
            if self._group_expanded:
                texts.extend(self._settled_texts())
        return texts

    def _active_texts(self) -> List[Text]:
        width = self._row_width()
        sel = (
            self._selected_idx
            if self._selected_idx < len(self._entries)
            else -1
        )
        return build_rows(
            self._entries,
            selected=sel,
            width=width,
            steps=[row.step for row in self._view.active],
            accepted=[row.accepted_now for row in self._view.active],
        )

    def _group_text(self) -> Text:
        return build_group_row(self._settled, expanded=self._group_expanded)

    def _settled_texts(self) -> List[Text]:
        base = len(self._entries) + 1
        sel = self._selected_idx - base if self._selected_idx >= base else -1
        return build_settled_rows(
            self._settled, selected=sel, width=self._row_width()
        )

    def _scroll_to_cursor(self) -> None:
        if 0 <= self._selected_idx < len(self._rows):
            self.call_after_refresh(
                self._rows[self._selected_idx].scroll_visible, animate=False
            )

    def _header_width(self) -> int:
        # Паддинг шапки плюс padding-right правого сегмента (`styles.tcss`).
        width = self.size.width - CHROME_PADDING - HEADER_RIGHT_PADDING
        return width if width > 0 else FALLBACK_WIDTH

    def _row_width(self) -> int:
        """Тело `#trace` минус паддинг строки и колонка скроллбара.

        Скроллбар резервируется ВСЕГДА, хотя появляется только у длинного
        списка: считать по факту нельзя — он рождается от самих строк, тело
        сужается на колонку, строка перестаёт влезать и уезжает во вторую,
        ломая и сетку колонок, и шаг страницы.

        Рамка тела (Р16) отдельного вычитания не требует: `size` — это уже
        content-region, из неё Textual рамку с паддингом вычел сам.
        """
        try:
            width = (
                self.query_one(_SEL_TRACE, VerticalScroll).size.width
                - ROW_PADDING
                - SCROLLBAR_COLUMN
            )
        except Exception:
            width = 0
        return width if width >= _PATH_MIN else FALLBACK_WIDTH

    # ---- навигация -----------------------------------------------------

    def _move(self, idx: int) -> None:
        # Кламп обязателен: индекс приходит и снаружи — из вьюера, который мог
        # закрыться на файле, уже исчезнувшем из перечитанного списка. Без
        # клампа курсор ушёл бы за диапазон и не подсветилась бы ни одна строка.
        total = self._row_count()
        idx = max(0, min(idx, total - 1))
        if not total or idx == self._selected_idx:
            return
        self._selected_idx = idx
        self._repaint_rows()

    def _repaint_rows(self) -> None:
        """Курсор переехал — строки обновляются НА МЕСТЕ (§16).

        Пересоздавать виджеты на каждый шаг курсора нельзя: между двумя
        кликами двойного клика список успевал смениться, и второй клик
        приходил уже по снятой строке — открытие файла мышью не срабатывало.
        Смена набора (источник, ширина, перечитывание) по-прежнему идёт полной
        пересборкой: там меняются и сами строки.
        """
        #
        # Трогаются только строки, которые действительно изменились: каждое
        # обновление просит Textual переложить весь список, и перерисовка всех
        # строк на шаг курсора стоила 1,3 с на нажатие при 10 000 файлов.
        texts = self._row_texts()
        for idx, (row, text) in enumerate(zip(self._rows, texts)):
            if self._shown_texts[idx] != text:
                row.update(text)
                self._shown_texts[idx] = text
            selected = idx == self._selected_idx
            if row.has_class("selected") != selected:
                row.set_class(selected, "selected")
        self._update_footer()  # строка действий зависит от курсора (§13)
        self._scroll_to_cursor()

    def _page(self) -> int:
        try:
            height = self.query_one(
                _SEL_TRACE, VerticalScroll
            ).content_size.height
        except Exception:
            height = 0
        return max(1, height - 1)

    def _toggle_source(self) -> None:
        # Плашка снимается ТОЛЬКО здесь: смена источника — единственная
        # пересборка, которую затеял сам пользователь, и «принято: 2 файла —
        # новая точка отсчёта» над списком другого набора говорило бы не про
        # него. После отката плашка обязана пережить перечитывание — там она
        # про него и есть.
        self._clear_flash()
        self._source = (
            SOURCE_TURN if self._source == SOURCE_SESSION else SOURCE_SESSION
        )
        self._selected_idx = 0
        self._reload()

    def _toggle_group_focus(self) -> None:
        """`Tab` — переключатель областей: активная часть ↔ группа (С4 смоука
        волны 4), с памятью В ОБЕИХ (Д3 второго смоука).

        Уход запоминает, откуда ушли: из активной части — индекс строки
        (`self._active_cursor_memory`, по умолчанию первая — «Tab» назад без
        предшествующего «Tab» туда обязан приземлиться на неё), из группы —
        ПУТЬ файла под курсором либо `None`, если стояли на самой строке
        группы. Возврат идёт на запомненное, а недостижимое запомненное
        деградирует к строке группы (`_group_focus_target`).

        Запомненный индекс активной части намеренно клампится к ТЕКУЩЕЙ её
        длине: перечитывание списка между двумя `Tab` могло её сократить, и
        непроверенный индекс увёл бы «назад» в саму группу вместо активных.

        Обе области обязаны быть непусты: без группы переключать нечего, с
        пустой активной частью — тоже, и клавиша молчит (в футере её тогда
        нет вовсе — `_update_footer`).
        """
        if not (self._settled and self._entries):
            return
        if self._cursor_in_group():
            settled_idx = self._settled_index(self._selected_idx)
            self._group_cursor_memory = (
                self._settled[settled_idx].path
                if settled_idx is not None
                else None
            )
            self._move(min(self._active_cursor_memory, len(self._entries) - 1))
        else:
            self._active_cursor_memory = self._selected_idx
            self._move(self._group_focus_target())

    def _group_focus_target(self) -> int:
        """Куда `Tab` приземляется в группе: запомненная строка, если группа
        по-прежнему раскрыта и путь всё ещё в ней, иначе — строка группы."""
        group_row = len(self._entries)
        if not self._group_expanded or self._group_cursor_memory is None:
            return group_row
        paths = [row.path for row in self._settled]
        if self._group_cursor_memory not in paths:
            return group_row
        return group_row + 1 + paths.index(self._group_cursor_memory)

    def on_key(self, event: events.Key) -> None:
        key = norm_key(event.key)
        last = self._row_count() - 1
        if key == "shift+tab":
            # Tab в Textual — перемещение фокуса; своя семантика обязана снять
            # и всплытие, и штатное действие клавиши.
            event.stop()
            event.prevent_default()
            if self._edits is not None:
                self._toggle_source()
        elif key == "tab":
            event.stop()
            event.prevent_default()
            self._toggle_group_focus()
        elif key == "up":
            event.stop()
            if last >= 0:
                self._move((self._selected_idx - 1) % (last + 1))
        elif key == "down":
            event.stop()
            if last >= 0:
                self._move((self._selected_idx + 1) % (last + 1))
        elif key in ("home", "end"):
            event.stop()
            if last >= 0:
                self._move(0 if key == "home" else last)
        elif key in ("pageup", "pagedown"):
            # Страница — не круг: на краях курсор упирается.
            event.stop()
            if last >= 0:
                step = self._page() if key == "pagedown" else -self._page()
                self._move(max(0, min(last, self._selected_idx + step)))
        elif key == "enter":
            event.stop()
            self._activate_selected()
        elif key == "a":
            event.stop()
            self._accept_selected()
        elif key == _KEY_CTRL_A:
            event.stop()
            self._accept_all()
        elif key == "u":
            event.stop()
            self._reset_selected()
        elif key == _KEY_CTRL_U:
            event.stop()
            self._reset_all()
        elif key == "r":
            event.stop()
            self._revert_selected()
        elif key == _KEY_CTRL_R:
            event.stop()
            self._revert_all()
        elif key == "x":
            event.stop()
            self._hide_cut_note()
        elif key == "escape":
            event.stop()
            event.prevent_default()
            self.app.pop_screen()

    def on_click(self, event: events.Click) -> None:
        """Клик выделяет строку; на строке группы раскрывает её (§4.2), на
        остальных двойной клик открывает файл (клик-модель §16).
        """
        widget = event.widget
        while widget is not None:
            if widget in self._rows:
                event.stop()
                idx = self._rows.index(widget)
                self._move(idx)
                if self._is_group_row(idx):
                    # Поглощает клик при любом chain, переключает только по
                    # первому — второй клик двойного иначе вернул бы свёртку
                    # (тот же приём, что у `DiffBlock.on_click`).
                    if event.chain == 1:
                        self._toggle_group()
                    return
                if event.chain == 2:
                    self._activate_selected()
                return
            widget = widget.parent

    # ---- вьюер ---------------------------------------------------------

    def _activate_selected(self) -> None:
        """Enter/двойной клик — по смыслу строки под курсором (§4.2/§4.3).

        Строка группы — только toggle разворота; settled-строка — вьюер
        кумулятива сессии; активная — обычный вьюер файла.
        """
        if self._is_group_row(self._selected_idx):
            self._toggle_group()
            return
        settled_idx = self._settled_index(self._selected_idx)
        if settled_idx is not None:
            self._open_group_viewer(settled_idx)
            return
        self._open_viewer()

    def _toggle_group(self) -> None:
        """Развернуть/свернуть группу «принято» — курсор остаётся на её строке.

        Полная пересборка (не `_repaint_rows`): число строк меняется — settled
        появляются или исчезают, а не просто перекрашиваются на месте.
        """
        self._group_expanded = not self._group_expanded
        self._selected_idx = min(self._selected_idx, self._row_count() - 1)
        self._render_screen()

    @_survives_unreadable_edits
    def _open_viewer(self) -> None:
        if self._edits is None or not self._entries:
            return
        self._viewer_is_group = False
        # Ступень «Сессии» — её понятие (Р27): «Ход» лестницу не видит
        # вовсе, а `self._session_ladder` мог остаться от ПРЕДЫДУЩЕГО
        # переключения в «Сессию» — спрашивать его в «Ходе» вслепую нельзя.
        accepted_ts = (
            [
                self._edits.accepted_step_ts(entry.path)
                for entry in self._entries
            ]
            if self._source == SOURCE_SESSION
            else None
        )
        # Симметричный параллельный список для ступени HEAD (С8) — тем же
        # путём, что и `accepted_ts`: из уже посчитанной `self._view.active`
        # (задача 1), без нового обращения к сервису.
        head_refs = (
            [_head_ref(row.step) for row in self._view.active]
            if self._source == SOURCE_SESSION
            else None
        )
        self._viewer = DiffFileViewer(
            view=self._edits,
            source=self._source,
            files=self._entries,
            index=self._selected_idx,
            on_revert=self._revert_one,
            on_accept=self._accept_one,
            on_reset=self._reset_one,
            can_reset=[_has_accepted_base(row) for row in self._view.active],
            can_revert=[row.entry.revertable for row in self._view.active],
            accepted_ts=accepted_ts,
            head_refs=head_refs,
        )
        self.app.push_screen(self._viewer)

    @_survives_unreadable_edits
    def _open_group_viewer(self, settled_idx: int) -> None:
        """Enter на settled-строке — кумулятивный дифф сессии, файлы только
        группы (§4.3): `r`/`a` там мертвы (`on_revert`/`on_accept` — `None`,
        вьюер не зовёт их вовсе), `u` жив только у `вручную` (`can_reset` —
        по причине settled-строки, не по факту принятой базы вообще: файл,
        разобранный «коммитом», принятой базы для `u` не имеет).
        """
        if self._edits is None or not self._settled:
            return
        self._viewer_is_group = True
        self._viewer = DiffFileViewer(
            view=self._edits,
            source=self._source,
            files=[_settled_entry(row) for row in self._settled],
            index=settled_idx,
            on_revert=None,
            on_accept=None,
            on_reset=self._reset_one,
            can_reset=[row.reason == SETTLED_MANUAL for row in self._settled],
            can_revert=[False] * len(self._settled),
        )
        self.app.push_screen(self._viewer)

    def on_screen_resume(self) -> None:
        """Вернулись из вьюера — курсор встаёт на файл, где его закрыли.

        Во вьюере файлы листаются `←`/`→`, и список, оставшийся на прежней
        строке, показывал бы не то, что человек только что читал. Вьюер
        группы листает ТОЛЬКО её файлы (§4.3) — его `index` пересчитывается в
        координаты общего списка, а не подставляется как есть.
        """
        if self._viewer is None:
            return
        index, is_group = self._viewer.index, self._viewer_is_group
        self._viewer = None
        self._move(len(self._entries) + 1 + index if is_group else index)

    # ---- хвост действий, меняющих данные ---------------------------------

    @contextlib.contextmanager
    def _after_the_change(self):
        """Рассказать о случившемся и перечитать список — после того, как данные изменены.

        Сюда граница `_survives_unreadable_edits` не достаёт: отказ здесь — не
        «действие не выполнено, повторите», а «выполнено, но рассказано не до
        конца», и совет повторить увёл бы пользователя на второе изменение.

        Перечитывание — в `finally`: что бы ни случилось в хвосте, и строки, и
        выбор обязаны говорить уже об изменённом состоянии (кэш сервиса
        мутирующие методы сбрасывают сами).
        """
        try:
            yield
        except OSError:  # TimeoutError замка — подкласс OSError
            _logger.warning("о правках рассказано не до конца", exc_info=True)
            self.app.notify(EDITS_CHANGED_UNREPORTED, severity="warning")
        finally:
            self._reload()

    # ---- принятие --------------------------------------------------------

    def _accept_selected(self) -> None:
        """`a` — файл под курсором объявляется новой точкой отсчёта; на
        строке группы клавиша мертва (принимать там нечего — §4.2)."""
        if self._selected_idx < len(self._entries):
            self._accept([self._entries[self._selected_idx].path])

    def _accept_all(self) -> None:
        """`Ctrl+A` — всё представление новой точкой отсчёта."""
        if self._entries:
            self._accept([entry.path for entry in self._entries])

    def _accept_one(self, path_key: str) -> None:
        """`a` во вьюере — читаемый файл (Р20)."""
        self._accept([path_key], from_viewer=True)

    @_survives_unreadable_edits
    def _accept(
        self, path_keys: Sequence[str], *, from_viewer: bool = False
    ) -> None:
        """Принять пути: без подтверждения — обратимо `u` (Р26/Р29, пересмотр Р9).

        В отличие от старого `git add` принятие МЕНЯЕТ данные экрана: база
        сдвигается, и файл с пустой дельтой от новой базы в тот же миг уезжает
        в группу «принято» — список обязан перечитаться целиком (`_reload()`),
        а не перерисоваться на месте, как раньше делал `git add` (Р9 + Р21).
        Успешное принятие ИЗ ВЬЮЕРА поэтому закрывает его, как и откат:
        открытый файл мог уехать из активных, и держать вьюер на устаревшей
        записи значило бы врать о том, что в нём показано.
        """
        if self._edits is None:
            return
        if self._run_is_live():
            self.app.notify(BUSY_ACTION, severity="warning")
            return
        outcome = self._edits.accept(path_keys)
        changed = bool(outcome.accepted)
        is_git = self.mode == "git-mode"
        with self._after_the_change():
            ack = accept_ack(outcome, is_git=is_git, source=self._source)
            self._flash(ack, outcome=accept_tone(outcome, is_git=is_git))
            if from_viewer and not changed:
                # Ничего не изменилось — вьюер остаётся открытым, и плашка
                # списка под ним не видна. Отказ обязан доехать поверх любого
                # экрана.
                self.app.notify(ack, severity="warning")
        if changed and from_viewer:
            self.app.call_later(self._close_viewer)

    # ---- сброс принятия ----------------------------------------------------

    def _reset_target(self, idx: int) -> Optional[str]:
        """Путь, который снимет `u` под курсором строки `idx` — либо `None`,
        если клавиша здесь мертва: активная строка без принятой базы вовсе
        (`ActiveRow.has_accepted_base`, финальный фикс волны 4 — НЕ то же
        самое, что отсутствие глифа `↺`: тай-брейк Р28 и источник «Ход»
        гасят глиф, но не саму базу), сама строка группы, разобранная строка
        с причиной «коммитом»."""
        if idx < len(self._entries):
            row = self._view.active[idx]
            return row.entry.path if _has_accepted_base(row) else None
        settled_idx = self._settled_index(idx)
        if settled_idx is not None:
            row = self._settled[settled_idx]
            return row.path if row.reason == SETTLED_MANUAL else None
        return None

    def _manual_accept_keys(self) -> List[str]:
        """Все пути с принятой базой — цель `Ctrl+U` (Р35): активные (глиф
        `↺` не обязателен — тай-брейк Р28 и источник «Ход» могут его гасить,
        не трогая саму базу, финальный фикс волны 4) и разобранные «вручную»."""
        active = [
            row.entry.path
            for row in self._view.active
            if _has_accepted_base(row)
        ]
        settled = [
            row.path for row in self._settled if row.reason == SETTLED_MANUAL
        ]
        return active + settled

    def _reset_selected(self) -> None:
        """`u` в списке — снять принятие файла под курсором (активного или
        разобранного «вручную»)."""
        key = self._reset_target(self._selected_idx)
        if key is not None:
            self._ask_reset([key], mass=False)

    def _reset_one(self, path_key: str) -> None:
        """`u` во вьюере (в т.ч. открытом из группы) — читаемый файл."""
        self._ask_reset([path_key], mass=False, from_viewer=True)

    def _reset_all(self) -> None:
        """`Ctrl+U` — снять принятие у всех принятых вручную (Р35)."""
        keys = self._manual_accept_keys()
        if keys:
            self._ask_reset(keys, mass=True)

    @_survives_unreadable_edits
    def _ask_reset(
        self,
        path_keys: Sequence[str],
        *,
        mass: bool,
        from_viewer: bool = False,
    ) -> None:
        """Спрашиваем, пока хоть один путь теряет точку отката к принятому
        состоянию (`ResetTarget.loses_point`, §4.3): не теряет НИКТО — сброс
        восстановимый (повторное `a` вернуло бы то же состояние), и вопроса
        нет, действие идёт сразу, с плашкой.

        Полноэкранное, в жанре отката (задача 4 доп., С7) и по ВСЕМУ
        `path_keys` (Д5 второго смоука): раньше в него уходили только
        теряющие, и заголовок «у N файлов» занижал число — принятие-то
        снималось у всех. Кто чем рискует, теперь говорит само тело, а не
        умолчание.
        """
        if self._edits is None:
            return
        if self._run_is_live():
            self.app.notify(BUSY_ACTION, severity="warning")
            return
        targets = self._edits.reset_targets(path_keys)
        if not any(target.loses_point for target in targets):
            self._apply_reset(path_keys, from_viewer=from_viewer)
            return

        # Импорт локальный — тот же приём, что у отката (`_ask_revert`).
        from gc_tui.screens.diff_revert_confirm import RevertConfirmScreen

        def _on_result(confirmed: bool) -> None:
            if confirmed:
                self._apply_reset(path_keys, from_viewer=from_viewer)

        self.app.push_screen(
            RevertConfirmScreen.for_reset(
                paths=path_keys,
                targets=targets,
                mass=mass,
            ),
            _on_result,
        )

    @_survives_unreadable_edits
    def _apply_reset(
        self, path_keys: Sequence[str], *, from_viewer: bool
    ) -> None:
        """Снять принятие и рассказать об этом (§13)."""
        # Проверка ПОВТОРЯЕТСЯ здесь, а не только перед вопросом: окно
        # подтверждения и есть та щель, ради которой она заводилась — пока
        # пользователь читает, ход мог начаться и писать файлы.
        if self._run_is_live():
            self.app.notify(BUSY_ACTION, severity="warning")
            return
        outcome = self._edits.reset_accept(path_keys)
        changed = bool(outcome.reset)
        with self._after_the_change():
            ack = reset_ack(outcome, source=self._source)
            self._flash(ack, outcome=reset_tone(outcome))
            if from_viewer and not changed:
                self.app.notify(ack, severity="warning")
        if changed and from_viewer:
            self.app.call_later(self._close_viewer)

    # ---- откат ---------------------------------------------------------

    def _revert_selected(self) -> None:
        """`r` в списке — откат файла под курсором; в группе не работает ни у
        кого (§4.3): дельта от ступени пуста, а закоммиченное — территория git.
        """
        if self._selected_idx < len(self._entries):
            self._ask_revert([self._entries[self._selected_idx]])

    def _revert_one(self, path_key: str) -> None:
        """`r` во вьюере — откат открытого в нём файла."""
        entry = next((e for e in self._entries if e.path == path_key), None)
        if entry is not None:
            self._ask_revert([entry], from_viewer=True)

    def _revert_all(self) -> None:
        """`Ctrl+R` — откат всего представления; только отсюда, из списка (Р20)."""
        if self._entries:
            self._ask_revert(list(self._entries))

    @_survives_unreadable_edits
    def _ask_revert(
        self, entries: Sequence[FileEntry], *, from_viewer: bool = False
    ) -> None:
        """Подтверждение отката набора; согласие — исполняется, отказ молчит.

        Откатываются только пути с достоверной базой. Остальные из набора не
        выбрасываются: они уходят в подтверждение своими блоками (`skipped`), а
        в `revert_paths` — пропущенными, чтобы итог назвал их и причину.
        """
        if self._edits is None:
            return
        if self._run_is_live():
            self.app.notify(BUSY_REVERT, severity="warning")
            return
        targets = [entry for entry in entries if entry.revertable]
        if not targets:
            # Пустое подтверждение под шапкой «будет отменено» было бы враньём.
            self.app.notify(REVERT_UNAVAILABLE, severity="warning")
            return

        # Импорт локальный: подтверждение говорит словарём этого экрана
        # («превью недоступно», склонение файлов) и импортирует его само.
        from gc_tui.screens.diff_revert_confirm import RevertConfirmScreen

        # Пропущенные и правленные извне уезжают ПУТЯМИ: строку о каждом
        # собирает подтверждение, и собирает её в блоке своего файла (Е3).
        blocked = [entry.path for entry in entries if not entry.revertable]
        external = [entry.path for entry in targets if entry.external]
        path_keys = [entry.path for entry in entries]

        # Состояние отката — ДО расчёта превью: перемена, пришедшая, пока оно
        # считалось, тоже расходится с показанным.
        target_paths = [entry.path for entry in targets]
        shown_state = self._edits.revert_state(target_paths)

        def _on_result(confirmed: bool) -> None:
            if confirmed:
                self._apply_revert(
                    path_keys,
                    from_viewer=from_viewer,
                    shown_state=(target_paths, shown_state),
                )

        # Числа и превью — ИЗ ОДНОГО расчёта, и того самого, которым откат
        # пишет: счётчики строки списка идут от счётной базы и обещали бы
        # другое (см. `EditsView.revert_deltas`). Дельты уезжают в подтверждение
        # ЦЕЛИКОМ: там показывается весь набор (Р22) — с диффом каждого файла,
        # а выше порога компактного вида без тел, — и счётчики каждой дельты
        # становятся заголовком её файла.
        deltas = list(
            zip(
                target_paths,
                self._edits.revert_deltas(self._source, target_paths),
            )
        )
        # Цели — тот же расчёт, что исполнит откат (задача 9): превью не
        # вправе назвать ступень иначе, чем реально вернёт `r`/`Ctrl+R`.
        preview_targets = self._edits.revert_targets(
            self._source, [entry.path for entry in targets]
        )
        counted = [delta for _path, delta in deltas if delta.countable]
        self.app.push_screen(
            RevertConfirmScreen(
                paths=[path for path, _delta in deltas],
                add=sum(delta.add for delta in counted),
                del_=sum(delta.del_ for delta in counted),
                # Несчётный путь из суммы выпал — числа неполные, и это `≈`.
                exact=len(counted) == len(deltas),
                skipped=blocked,
                external=external,
                preview=deltas,
                targets=preview_targets,
            ),
            _on_result,
        )

    @_survives_unreadable_edits
    def _apply_revert(
        self,
        path_keys: Sequence[str],
        *,
        from_viewer: bool,
        shown_state: Optional[Tuple[Sequence[str], Tuple]] = None,
    ) -> None:
        """Откатить пути и рассказать об этом всем, кого это касается.

        ``shown_state`` — пути и всё, от чего зависит их откат, на момент показа
        превью (``EditsView.revert_state``: файлы, принятия, HEAD). Разошлось —
        откат не пишет ничего: он записал бы то, чего в превью не было. Список
        перечитывается, чтобы новое подтверждение показало то, что сейчас.
        """
        # Проверка ПОВТОРЯЕТСЯ здесь, а не только перед вопросом: окно
        # подтверждения и есть та щель, ради которой она заводилась — пока
        # пользователь читает, ход мог начаться и писать файлы.
        if self._run_is_live():
            # Тот же отказ, что и перед вопросом (`_ask_revert`), и слова те
            # же: одно условие не вправе звучать двумя способами в зависимости
            # от того, был ли диалог подтверждения.
            self.app.notify(BUSY_REVERT, severity="warning")
            return
        if shown_state is not None:
            shown_paths, state = shown_state
            if self._edits.revert_state(shown_paths) != state:
                self.app.notify(REVERT_STALE, severity="warning")
                self._reload()
                return
        outcome = self._edits.revert(self._source, path_keys)
        changed = bool(outcome.restored or outcome.deleted)
        with self._after_the_change():
            if changed and self._on_undo_feedback is not None:
                # Модель обязана узнать, что её представление о файлах
                # устарело: иначе следующая правка ляжет поверх выдуманного
                # состояния (§7).
                self._on_undo_feedback(outcome.restored, outcome.deleted)
            ack = revert_ack(outcome)
            # Пропущенное — тоже повод для жёлтого: «часть вернулась, часть не
            # записалась» спокойным тоном читалось бы как полный успех.
            clean = changed and not outcome.skipped
            self._flash(ack, outcome="ok" if clean else "warn")
            if from_viewer and not changed:
                # Ничего не изменилось — вьюер остаётся открытым, и плашка
                # списка под ним не видна. Отказ обязан доехать поверх любого
                # экрана.
                self.app.notify(ack, severity="warning")
            if self._on_ui_ack is not None:
                self._on_ui_ack(ack)
        if changed and from_viewer:
            self.app.call_later(self._close_viewer)

    def _close_viewer(self) -> None:
        """Вернуть пользователя к списку: то, что он читал, только что откачено.

        Отложено на такт: `dismiss` зовёт колбэк ДО снятия подтверждения со
        стека, и снимать вьюер в этот момент было бы снятием не того экрана.
        """
        if self._viewer is not None and self.app.screen is self._viewer:
            self.app.pop_screen()

    def _run_is_live(self) -> bool:
        runner = getattr(self.app, "active_runner", None)
        return runner is not None and bool(runner.is_running())


