# Пара счётчиков «+N −M» в готовой строке шапки (минус — U+2212, как во всём
# экране). Собирают шапку функции ниже: им нужен plain-текст, иначе не посчитать
# ширину и не сравнить с доступной. Цвет поэтому накладывается отдельным шагом —
# одним на все три шапки экрана.
_COUNTERS_RE = re.compile(r"(\+\d+)(\s+)(−\d+)")


def paint_counters(line: str) -> Text:
    """Шапка со счётчиками в цвете: `+N` — `OK`, `−M` — `ERR`.

    Цвета — те же семантические, которыми движок правок красит гаттер тела
    (`palette.DIFF_ADD_GUTTER`/`DIFF_DEL_GUTTER`): один смысл — один цвет во
    всём TUI, и глаз ищет прибавленное и убранное одинаково в списке, во вьюере
    и в подтверждении отката. Ноль не выделяется тусклым: колонка читается
    ЦВЕТОМ, и выпавшее из него `−0` пришлось бы разбирать чтением.

    Красится ПОСЛЕДНЯЯ пара строки: счётчики всегда стоят в хвосте, а путь
    пользователя такую пару содержать может.
    """
    matches = list(_COUNTERS_RE.finditer(line))
    text = Text()
    if not matches:
        text.append(line)
        return text
    match = matches[-1]
    text.append(line[: match.start()])
    text.append(match.group(1), style=OK)
    text.append(match.group(2))
    text.append(match.group(3), style=ERR)
    text.append(line[match.end() :])
    return text


def build_header(
    source: str,
    *,
    files: int,
    add: int,
    del_: int,
    mode: str,
    width: int,
    has_group: bool = False,
    legend_accepted: bool = False,
    legend_commit: bool = False,
    legend_external: bool = False,
) -> Tuple[str, str]:
    """`(текст слева, маркер справа)` шапки под доступную ширину.

    Порядок жертв на узкой ширине — слева направо: маркер `git`, затем слово
    экрана, затем «от начала хода» (только у источника «Ход» — С5 смоука
    волны 4), затем «N файлов». Источник и счётчики уходят последними:
    источник задаёт смысл чисел, а числа — суть экрана. Сегмент
    выбрасывается целиком, полусъеденное «+12 −» врало бы.

    `legend_accepted`/`legend_commit`/`legend_external` — есть ли на экране
    хоть одна строка с таким знаком: легенда объясняет только то, что реально
    видно, пустых сегментов не бывает. В порядке жертв она ПЕРВАЯ — знак без
    расшифровки хуже, чем числа без знака.

    Внутри легенды порядок держится: две расшифровки ступени идут парой, а
    `извне` — последним. Оно про доверие к показанному, а не про базу счёта.

    `has_group` (Д7 второго смоука) — жива ли группа разобранных. Шапка
    считает ТОЛЬКО активные файлы (§4.2), и на нуле активных при живой группе
    честно говорит про НОВЫЕ изменения: «изменений нет» над видимой группой
    было бы неправдой. Без аргумента (старые вызовы) — прежний текст.
    """
    label = _SOURCE_LABELS.get(source, source)
    if files > 0:
        tail = f"+{add} −{del_}"
    else:
        tail = _NO_NEW_COUNTERS if has_group else _NO_COUNTERS
    marker = "git" if mode == "git-mode" else ""
    turn_base = [TURN_BASE_PHRASE] if source == SOURCE_TURN else []
    files_seg = [f"{files} {files_word(files)}"] if files > 0 else []

    legend = (
        ([LEGEND_ACCEPTED] if legend_accepted else [])
        + ([LEGEND_COMMIT] if legend_commit else [])
        + ([LEGEND_EXTERNAL] if legend_external else [])
    )
    full = [SCREEN_WORD, label] + turn_base + files_seg + [tail] + legend

    stages = [(full, marker)] if marker else []
    stages.append((full, ""))
    if legend:
        stages.append(
            ([SCREEN_WORD, label] + turn_base + files_seg + [tail], "")
        )
    stages.append(
        ([label] + turn_base + files_seg + [tail], "")
    )  # без слова экрана
    if turn_base:
        stages.append(
            ([label] + files_seg + [tail], "")
        )  # без «от начала хода»
    if files > 0:
        stages.append(([label, tail], ""))  # без «N файлов»

    for parts, right in stages:
        left = " · ".join(parts)
        need = len(left) + (len(right) + 1 if right else 0)
        if need <= width:
            return left, right
    parts, right = stages[-1]
    return " · ".join(parts), right


def build_viewer_header(
    source: str,
    entry: FileEntry,
    *,
    full: bool,
    width: int,
    edit: int = 0,
    edits: int = 0,
    accepted_ts: Optional[float] = None,
    head_ref: Optional[str] = None,
) -> str:
    """Шапка вьюера: файл, источник его чисел, режим показа и место курсора.

    Порядок жертв: сначала слово экрана, затем источник. Путь не выбрасывается
    никогда — он и отвечает на вопрос «что я смотрю»; при нехватке ширины он
    режется СЛЕВА, имя файла остаётся целым. Знак `≈` живёт рядом с числами,
    как и в строке списка: он про их точность.

    `accepted_ts` (по умолчанию `None`, как и раньше — старые вызовы не
    меняются) вставляет расшифровку глифа `↺` сразу после счётчиков, тем же
    слотом, где раньше стояла снесённая колонка состояния индекса (§13 спеки).
    `head_ref` (С8 смоука волны 4) — симметричная расшифровка ступени HEAD, тот
    же слот. Ступень одна на файл (`RowStep.kind`, задача 1) — оба параметра
    заданными разом не бывают, вызывающий передаёт ровно один из двух либо
    ни одного.

    Счётчик правок (`правка 2/4`) стоит последним и не жертвуется: он —
    единственный ответ на «что сделало нажатие `n`», когда правка и до, и после
    нажатия видна на экране целиком.

    `извне` приезжает сюда той же фразой, что стоит в легенде списка: во вьюере
    на файл смотрят вплотную, и предупреждение обязано быть там, где читают
    содержимое, — иначе оно исчезало ровно в этот момент (смок 2026-09-10).
    Одна строка на оба экрана: расходиться этим двум формулировкам не о чем.
    """
    label = _SOURCE_LABELS.get(source, source)
    counters = (
        "" if entry.exact else APPROX + " "
    ) + f"+{entry.add} −{entry.del_}"
    if accepted_ts is not None:
        caption = [accepted_caption(accepted_ts)]
    elif head_ref is not None:
        caption = [head_caption(head_ref)]
    else:
        caption = []
    counter = [edit_counter(edit, edits)] if edits else []
    suffix = ([FULL_SUFFIX] if full else []) + counter
    tail = [counters] + caption + [LEGEND_EXTERNAL] + suffix
    stages = [(head, tail) for head in ([SCREEN_WORD, label], [label], [])]
    if not entry.external:
        stages = [(head, [counters] + caption + suffix) for head, _ in stages]
    else:
        # Предупреждение жертвуется ПОСЛЕДНИМ: сперва слово экрана и источник
        # уходят ради него, и только когда даже с голым путём оно не влезает —
        # сбрасывается само. Место, которое оно занимало, тут же возвращается
        # слову экрана и источнику: держать шапку урезанной ПОСЛЕ отказа от
        # фразы незачем, потому и стадии перебираются заново.
        stages += [
            (head, [counters] + caption + suffix)
            for head in ([SCREEN_WORD, label], [label], [])
        ]
    for head, parts in stages:
        text = " · ".join(head + [entry.path] + parts)
        if len(text) <= width:
            return text
    fixed = " · ".join([""] + stages[-1][1])  # « · +84 −12 · весь файл»
    room = max(_PATH_MIN, width - len(fixed))
    return truncate_path_left(entry.path, room) + fixed


def build_revert_title(
    path_keys: Sequence[str], *, add: int, del_: int, exact: bool, width: int
) -> str:
    """Шапка подтверждения: что откатываем и сколько строк это отменит.

    Нулевые счётчики не показываются вовсе: у пути, который сравнивать было
    нечем (бинарь, файл сверх капа), `+0 −0` прочитались бы как «отменяется
    ноль строк», хотя откат вернёт целый файл. Знак `≈` живёт рядом с числами,
    как и в строке списка: он про их точность.

    Путь при нехватке ширины режется СЛЕВА — имя файла остаётся целым, как в
    шапке вьюера.
    """
    what = (
        path_keys[0]
        if len(path_keys) == 1
        else f"{len(path_keys)} {files_word(len(path_keys))}"
    )
    tail = ""
    if add or del_:
        approx = "" if exact else APPROX + " "
        tail = f" · {REVERT_UNDONE} {approx}+{add} −{del_}"
    head = f"{REVERT_HEAD} · "
    room = max(_PATH_MIN, width - len(head) - len(tail))
    return head + truncate_path_left(what, room) + tail


def build_reset_title(
    path_keys: Sequence[str], *, mass: bool, width: int
) -> str:
    """Шапка подтверждения сброса (задача 4 доп., С7): `u` называет ЕДИНСТВЕННЫЙ
    файл по имени — тот же жанр, что у одиночного отката; `Ctrl+U` называет
    ЧИСЛО задетых файлов ВСЕГДА, даже когда оно оказалось единственным —
    старый гейт `mass` (см. docstring бывшего `reset_confirm_message`: `u`
    всегда один путь и никогда не считает, `Ctrl+U` даже на одном файле
    считает), сохранённый при переезде в полноэкранный вид. Считает —
    родительным падежом ПОСЛЕ ПРЕДЛОГА («у 3 файлов», не «у 3 файла»,
    `files_word_genitive`) — сама числительная форма не годится, у неё другая
    грамматика (`files_word`, «изменено 3 файла»).

    Нет диффа — нет и счётчиков в хвосте (в отличие от `build_revert_title`):
    сброс не пишет на диск, отменять в строках нечего.
    """
    if not mass:
        head = f"{RESET_CONFIRM_TITLE} · "
        room = max(_PATH_MIN, width - len(head))
        return head + truncate_path_left(path_keys[0], room)
    count = len(path_keys)
    return f"{RESET_CONFIRM_TITLE} у {count} {files_word_genitive(count)}"


# --- цель отката: подпись превью (§4.4/§13 спеки, задача 13) ----------------

# Дательный падеж — решение дизайн-гейта (§13): «вернёт к принятому
# состоянию», не «вернёт к принятое состояние». Факты в скобках (время
# принятия, ref коммита) сюда не пересчитываются — они уже готовы в
# `RevertTarget.label` (задача 9), отсюда берётся только сложившийся «хвост».
# «delete» — само по себе законченное предложение («будет удалён…»), «вернёт
# к» ему грамматически не подходит и отдаётся как есть; «skip» сюда не
# доезжает (см. `_ask_revert` — цели строятся только для путей, которые
# реально откатываются).
REVERT_TARGET_HEAD = "вернёт к"
_TARGET_DATIVE_STEM = {
    "accepted": "принятому состоянию",
    "head": "закоммиченному состоянию",
    "session": "началу сессии",
    "turn": "началу хода",
}


def revert_target_line(target: RevertTarget) -> str:
    """Шапка одиночного превью: «вернёт к <ступень>» (§4.4/§13)."""
    stem = _TARGET_DATIVE_STEM.get(target.kind)
    if stem is None:
        return target.label
    suffix = (
        target.label[target.label.find("(") :] if "(" in target.label else ""
    )
    return f"{REVERT_TARGET_HEAD} {stem}" + (f" {suffix}" if suffix else "")


def revert_target_arrow(target: RevertTarget) -> str:
    """Массовое превью: цель стрелкой у файла — `label` как есть, падеж тут не нужен."""
    return f"→ {target.label}"


# Родительный падеж после предлога «от» — задача 4 доп. (С7): сброс не
# «вернёт к» ступени (диск не меняется — это была бы неправда), а СЧЁТ
# «пойдёт от» неё, и «от» требует другого падежа, чем дательные стемы отката
# выше. Тот же приём переноса скобочного «хвоста» из `RevertTarget.label`,
# что у `revert_target_line` — цель ОДНА (`EditsView.reset_targets`, рядом с
# `revert_targets`), меняется только грамматика обёртки. Сброс достаёт только
# «head»/«session»: принятой ступени после сброса уже нет, а своей лестницы у
# «Хода» нет вовсе (Р27) — `u` из «Хода» тоже возможен (владелец оставил
# клавишу рабочей, финальный фикс волны 4: гейт теперь на факте принятой базы,
# `_has_accepted_base`, а не на действующей ступени), но цель ВСЕГДА про
# лестницу «Сессии».
RESET_TARGET_HEAD = "после сброса счёт пойдёт от"
_RESET_TARGET_GENITIVE_STEM = {
    STEP_HEAD: "закоммиченного состояния",
    "session": "начала сессии",
}


def reset_target_line(target: RevertTarget) -> str:
    """Строка цели в подтверждении сброса: «после сброса счёт пойдёт от
    <ступень>» (задача 4 доп., С7) — у каждого пути набора (Д5)."""
    stem = _RESET_TARGET_GENITIVE_STEM.get(target.kind)
    if stem is None:
        return target.label
    suffix = (
        target.label[target.label.find("(") :] if "(" in target.label else ""
    )
    return f"{RESET_TARGET_HEAD} {stem}" + (f" {suffix}" if suffix else "")


# Цена сброса (Д5 второго смоука). «Куда пойдёт счёт» — это последствие, а
# ВОПРОС подтверждения в другом: принятое состояние — единственная точка, к
# которой файл ещё можно вернуть, и сброс её стирает. Молчавшее об этом тело
# заставляло верить на слово, а заголовок «у N файлов» вдобавок считал одних
# теряющих. Час принятия — тем же форматом, что расшифровка глифа `↺`
# (`accepted_caption`); его может не быть вовсе (принятая база не прочиталась,
# `ResetTarget.accepted_ts`) — тогда строка обходится без скобок, а не
# выдумывает время. Путь, которому терять нечего, тоже назван: он в наборе, у
# него снимется принятие, и молчание о нём читалось бы как «этого файла тут
# нет».
RESET_LOSS_STEM = "точка отката к принятому состоянию"
RESET_LOSS_TAIL = "будет потеряна"
RESET_NOTHING_LOST = "терять нечего"


def reset_loss_line(target: ResetTarget) -> str:
    """Что сброс стоит одному пути: «точка отката к принятому состоянию
    (HH:MM) будет потеряна» либо «терять нечего» (Д5)."""
    if not target.loses_point:
        return RESET_NOTHING_LOST
    stamp = (
        f" ({_hhmm(target.accepted_ts)})"
        if target.accepted_ts is not None
        else ""
    )
    return f"{RESET_LOSS_STEM}{stamp} {RESET_LOSS_TAIL}"


def revert_target_warnings(target: RevertTarget) -> List[str]:
    """`⚠`-строки цели — непусты только у «Хода» (`RevertTarget.warns`, §4.4)."""
    return [f"⚠ {warn}" for warn in target.warns]


def revert_ack(outcome: RevertOutcome) -> str:
    """Итог отката одной строкой: что вернулось, что удалено, что пропущено.

    Пропущенное группируется по ПРИЧИНЕ: «достоверной базы нет» и «файла уже
    нет на диске» — разные события, и общий счётчик их бы склеил.
    """
    parts = []
    if outcome.restored:
        parts.append(_files_phrase("восстановлено", outcome.restored))
    if outcome.deleted:
        parts.append(_files_phrase("удалено", outcome.deleted))
    for reason, keys in _by_reason(outcome.skipped).items():
        parts.append(
            f"{_files_phrase('пропущено', keys)}"
            f" — {_REASON_TEXTS.get(reason, reason)}"
        )
    head = (
        REVERT_HEAD if (outcome.restored or outcome.deleted) else REVERT_FAILED
    )
    return " · ".join([head] + parts)


def _files_phrase(word: str, keys: Sequence[str]) -> str:
    """«восстановлено: a.py» либо «восстановлено: 3 файла».

    У одного файла имя полезнее числа. Безличная форма с двоеточием
    согласуется с любым количеством — «удалено: 1 файл» звучит так же ровно,
    как «удалено: 3 файла».
    """
    if len(keys) == 1:
        return f"{word}: {keys[0]}"
    return f"{word}: {len(keys)} {files_word(len(keys))}"


def _by_reason(skipped: Sequence[Tuple[str, str]]) -> Dict[str, List[str]]:
    """Пропущенные пути по причинам, в порядке первого появления."""
    groups: Dict[str, List[str]] = {}
    for key, reason in skipped:
        groups.setdefault(reason, []).append(key)
    return groups


def _git_error_detail(text: str) -> str:
    """Первая строка ответа git как есть — остальные обычно подсказки «как быть»."""
    lines = (text or "").strip().splitlines()
    return lines[0].strip() if lines else ""


def accept_ack(
    outcome: AcceptOutcome, *, is_git: bool, source: str = SOURCE_SESSION
) -> str:
    """Итог принятия одной строкой (§13): что сдвинулось, что застейджилось,
    что пропущено. Плашка не имеет права соврать: про индекс git молчит вне
    репозитория, а про ручные правки — только когда они реально были
    (``outcome.with_external``).

    `source` (по умолчанию «Сессия», как и раньше — старые вызовы не
    меняются, задача 4 доп.): из «Хода» принятие ТОЖЕ двигает базу «Сессии»
    (Р26), но сам «Ход» её не видит (Р27) — файл в его списке остаётся на
    месте. `ACCEPT_TURN_NOTE` называет, где сдвиг реально виден; в «Сессии»
    текст не меняется.
    """
    parts: List[str] = []
    if outcome.accepted:
        head = _files_phrase(GROUP_LABEL, outcome.accepted)
        if is_git and outcome.stage_error is not None:
            detail = _git_error_detail(outcome.stage_error)
            reason = f" ({detail})" if detail else ""
            parts.append(
                f"{head}, но {ACCEPT_STAGE_FAILED}{reason} — {ACCEPT_STAGE_ACTION}"
            )
        else:
            tail = ""
            if is_git and outcome.staged:
                note = (
                    ACCEPT_STAGE_EXTERNAL
                    if outcome.with_external
                    else ACCEPT_STAGE_PLAIN
                )
                tail = f"; {note}"
            parts.append(f"{head} — {ACCEPT_NEW_BASELINE}{tail}")
        if source == SOURCE_TURN:
            parts.append(ACCEPT_TURN_NOTE)
    else:
        parts.append(ACCEPT_FAILED_HEAD)
    for reason, keys in _by_reason(outcome.skipped).items():
        parts.append(
            f"{_files_phrase('пропущено', keys)}"
            f" — {_ACCEPT_REASON_TEXTS.get(reason, reason)}"
        )
    return " · ".join(parts)


def reset_ack(outcome: ResetOutcome, *, source: str = SOURCE_SESSION) -> str:
    """Итог сброса принятия (`u`/`Ctrl+U`) одной строкой — с условной целью
    счёта (§13, Р29): ближайшая ОСТАВШАЯСЯ ступень, а не всегда «начало
    сессии» (``ResetOutcome.to_head``).

    `source` (по умолчанию «Сессия», как и раньше — старые вызовы не
    меняются, финальный фикс волны 4): из «Хода» сброс ТОЖЕ двигает базу
    «Сессии» (принятая база — глобальный маркер, `EditsView.reset_accept`),
    но сам «Ход» её не видит (Р27) — файл в его списке остаётся на месте.
    `RESET_TURN_NOTE` называет источник, где сдвиг реально виден — тот же
    приём, что у `accept_ack`/`ACCEPT_TURN_NOTE`; в «Сессии» текст не меняется.
    """
    parts: List[str] = []
    if outcome.reset:
        to_head = set(outcome.to_head)
        from_start = [key for key in outcome.reset if key not in to_head]
        from_head = [key for key in outcome.reset if key in to_head]
        if from_start:
            parts.append(
                f"{_files_phrase(RESET_UNDONE, from_start)} — {RESET_FROM_SESSION_START}"
            )
        if from_head:
            parts.append(
                f"{_files_phrase(RESET_UNDONE, from_head)} — {RESET_FROM_HEAD}"
            )
        if source == SOURCE_TURN:
            parts.append(RESET_TURN_NOTE)
    else:
        parts.append(RESET_FAILED_HEAD)
    for reason, keys in _by_reason(outcome.skipped).items():
        parts.append(
            f"{_files_phrase('пропущено', keys)}"
            f" — {_RESET_REASON_TEXTS.get(reason, reason)}"
        )
    return " · ".join(parts)


# Подтверждение сброса (`u`/`Ctrl+U`, задача 4 доп. — С7) — полноэкранное, в
# жанре отката (`RevertConfirmScreen.for_reset`, `diff_revert_confirm.py`), не
# лёгкий `ConfirmScreen`: снятие принятия по опасности сопоставимо с откатом
# — то же полотно, имя файла (или список задетых для `Ctrl+U`), цель сброса
# из сервиса (`EditsView.reset_targets`). Заголовок — слово, общее для `u` и
# `Ctrl+U` (см. `build_reset_title`).
RESET_CONFIRM_TITLE = "Сброс принятия"


# --- строка списка -----------------------------------------------------------


def _marks(entry: FileEntry, *, accepted: bool = False) -> List[str]:
    """Пометки строки в порядке показа. Норму (правку тулом) не подписываем."""
    marks: List[str] = []
    if accepted:
        marks.append(MARK_ACCEPTED)
    if entry.by_shell:
        marks.append(MARK_SHELL)
    if entry.external:
        marks.append(MARK_EXTERNAL)
    return marks


def _shrink(marks: List[str]) -> List[str]:
    """Одна пометка вместо двух: «извне» предупреждает о риске отката."""
    if len(marks) <= 1:
        return marks
    return [MARK_EXTERNAL] if MARK_EXTERNAL in marks else marks[:1]


def _marks_text(marks: List[str], width: int) -> Text:
    """Пометки, прижатые вправо в своей колонке. Жёлтая — только «извне»."""
    plain = _MARK_SEP.join(marks)
    text = Text(" " * max(0, width - len(plain)), no_wrap=True)
    for idx, mark in enumerate(marks):
        if idx:
            text.append(_MARK_SEP, style=DEEP_DIM)
        text.append(mark, style=WARN if mark == MARK_EXTERNAL else DEEP_DIM)
    return text


def _step_is_accepted(step: Optional[RowStep]) -> bool:
    """Ступень `RowStep` — действующая «принято» (не просто «где-то есть
    `.accepted`»): предикат для глифа `↺` (`build_rows`) — один расчёт, а не
    два разных условия на одну и ту же строку списка.
    """
    return step is not None and step.kind == STEP_ACCEPTED


def _head_ref(step: Optional[RowStep]) -> Optional[str]:
    """Готовая подпись ступени HEAD («e5f2c1a · 14:20», собрана батчем в
    `agent_edits.ladder`/`git_ops.head_commit_label`) — общее чтение поля
    для короткого хэша списка (`_commit_hash`, С9) и полной подписи шапки
    вьюера (`head_caption`, С8): один расчёт, здесь ничего не пересчитывается.
    `None` — ступень не HEAD, либо `ref` пуст (редкий сбой сборки подписи).
    """
    if step is None or step.kind != STEP_HEAD or not step.ref:
        return None
    return step.ref


def _commit_hash(step: Optional[RowStep]) -> Optional[str]:
    """Короткий хэш ступени HEAD для слота списка (С9 смоука волны 4) —
    первая часть `_head_ref` (полную подпись, со временем, несёт только шапка
    вьюера, симметрично `accepted_caption`) — слот строки тесен для времени.
    """
    ref = _head_ref(step)
    return ref.split(" ", 1)[0] if ref else None


def build_rows(
    entries: Sequence[FileEntry],
    *,
    selected: int,
    width: int = FALLBACK_WIDTH,
    steps: Optional[Sequence[Optional[RowStep]]] = None,
    accepted: Optional[Sequence[bool]] = None,
) -> List[Text]:
    # `accepted` — параллельный `entries` признак принятой базы. Он идёт в
    # ПОМЕТКИ строки (`_marks`), а не в слот глифа `↺`: глиф говорит «строка
    # считается от принятой базы», и в «Ходе», где счёт всегда от начала хода,
    # это было бы неправдой (Р27). Пометка же говорит про сам файл — рядом с
    # «командой» и «извне», где ей и место.
    """Строки списка одной общей сеткой (см. модульный докстринг).

    `steps` — параллельный `entries` список действующих ступеней отсчёта
    (`ActiveRow.step`): ступень `accepted` рисует глиф `ACCEPTED_GLYPH` сразу
    после счётчиков (§13 волны 4), ступень `head` — приглушённый короткий
    хэш коммита В ТОМ ЖЕ слоте (С9 смоука волны 4). Ставится ровно один из
    двух — `RowStep.kind` одно значение на строку, оба сразу невозможны. Без
    аргумента (старые вызовы) слота нет ни у кого — колонки состояния индекса
    здесь больше нет вовсе (снята вместе с волны-3 словами `в индексе`/
    `частично`, их роль забрали группа и этот слот).
    """
    if not entries:
        return []

    row_steps = [
        steps[idx] if steps and idx < len(steps) else None
        for idx in range(len(entries))
    ]
    marked = [_step_is_accepted(step) for step in row_steps]
    row_accepted = [
        bool(accepted[idx]) if accepted and idx < len(accepted) else False
        for idx in range(len(entries))
    ]
    hashes = [_commit_hash(step) for step in row_steps]
    kinds = [_KIND_LABELS.get(entry.kind, entry.kind) for entry in entries]
    pluses = [f"+{entry.add}" for entry in entries]
    minuses = [f"−{entry.del_}" for entry in entries]
    kind_w = max(len(kind) for kind in kinds)
    plus_w = max(len(plus) for plus in pluses)
    minus_w = max(len(minus) for minus in minuses)
    head_w = _MARKER_W + kind_w + _KIND_GAP
    # Слот `≈` — один символ ВСЕГДА: без него неточная строка сдвигала бы
    # счётчики относительно точных, а именно их и сверяют по вертикали. Слот
    # маркера (глиф/хэш) — по тому же правилу, но только когда он есть хоть у
    # одной строки, и шириной по САМОМУ ШИРОКОМУ из них — короткий глиф в
    # наборе с хэшем получает свою же долю пробелов справа (см. цикл ниже).
    markers_with_hash = [
        ACCEPTED_GLYPH if marked[idx] else hashes[idx]
        for idx in range(len(entries))
    ]
    markers_glyph_only = [
        ACCEPTED_GLYPH if marked[idx] else None for idx in range(len(entries))
    ]
    marker_w = _glyph_column_width(markers_with_hash)
    tail_w = 1 + plus_w + _COUNTER_GAP + minus_w + marker_w

    # Порядок жертв на узком окне (С9 смоука волны 4): хэш уходит ПЕРВЫМ, ещё
    # до второй пометки и колонки пометок целиком — счётчики, `≈` и глиф `↺`
    # не жертвуются никогда.
    free = width - head_w - tail_w
    # Пометка «принят» — только там, где глиф её ещё не сказал: у строки с
    # действующей ступенью «принято» он и есть этот знак, дубль был бы шумом.
    # Остаются два случая, где принятие иначе невидимо: «Ход» (ступеней нет
    # вовсе) и тай-брейк Р28 в «Сессии» (ступень HEAD, слот занят хэшем).
    marks = [
        _marks(entry, accepted=row_accepted[idx] and not marked[idx])
        for idx, entry in enumerate(entries)
    ]
    marks_w, path_w = _fit(marks, free)
    show_hash = True
    if path_w < _PATH_MIN:
        show_hash = False
        marker_w = _glyph_column_width(markers_glyph_only)
        tail_w = 1 + plus_w + _COUNTER_GAP + minus_w + marker_w
        free = width - head_w - tail_w
        marks_w, path_w = _fit(marks, free)
    if path_w < _PATH_MIN:
        marks = [_shrink(row_marks) for row_marks in marks]
        marks_w, path_w = _fit(marks, free)
    if path_w < _PATH_MIN:
        marks = [[] for _ in entries]
        marks_w, path_w = _fit(marks, free)
    path_w = max(path_w, _PATH_MIN)

    rows: List[Text] = []
    for idx, entry in enumerate(entries):
        is_selected = idx == selected
        # `no_wrap`/`overflow` — как у карточек /sessions и /skills, но от
        # переноса строку спасает не он: Textual рендерит Static через свой
        # Content, и решают правила `.diff-row` в styles.tcss.
        text = Text(no_wrap=True, overflow="ellipsis")
        text.append("▸ " if is_selected else "  ", style=ACCENT)
        text.append(kinds[idx].ljust(kind_w) + " " * _KIND_GAP, style=DEEP_DIM)
        text.append(
            truncate_path_left(entry.path, path_w).ljust(path_w),
            style=BRIGHT if is_selected else INK,
        )
        if marks_w:
            text.append(" " * _MARKS_GAP)
            text.append_text(_marks_text(marks[idx], marks_w))
        text.append(" " * _MARKS_GAP)
        # `≈` остаётся тусклым: он про ДОСТОВЕРНОСТЬ чисел, а не про сами
        # прибавленное и убранное, и цвет счётчиков ему не принадлежит.
        text.append(APPROX if not entry.exact else " ", style=DEEP_DIM)
        text.append(pluses[idx].rjust(plus_w), style=OK)
        text.append(" " * _COUNTER_GAP)
        text.append(minuses[idx].rjust(minus_w), style=ERR)
        if marker_w:
            if marked[idx]:
                text.append(" ")
                text.append(ACCEPTED_GLYPH.ljust(marker_w - 1), style=ACCENT)
            elif show_hash and hashes[idx]:
                text.append(" ")
                text.append(hashes[idx].ljust(marker_w - 1), style=DEEP_DIM)
            else:
                text.append(" " * marker_w)
        rows.append(text)
    return rows


def _glyph_column_width(markers: Sequence[Optional[str]]) -> int:
    """Ширина слота глифа/хэша: 1 (зазор перед ним) + длина самой широкой
    метки среди `markers`, либо 0, если ни одна строка её не несёт."""
    lengths = [len(marker) for marker in markers if marker]
    return (1 + max(lengths)) if lengths else 0


def _fit(marks: List[List[str]], free: int) -> Tuple[int, int]:
    """`(ширина колонки пометок, ширина колонки пути)` при данном остатке.

    Зазор перед счётчиками резервируется всегда — даже когда колонки пометок
    нет: путь занимает свою колонку до последнего символа, и без зазора длинный
    путь склеился бы со знаком `≈` (`…/engine.py≈+1284`). Колонка пометок, если
    жива, добавляет свой зазор СЛЕВА — по тому же правилу.
    """
    marks_w = max(len(_MARK_SEP.join(row)) for row in marks)
    gaps = _MARKS_GAP * (1 + bool(marks_w))
    return marks_w, free - marks_w - gaps


# Притушённые зелёный/красный счётчиков группы (С2 смоука волны 4) — тот же
# смысл, что у активных строк (`OK`/`ERR`), но не так ярко: строка группы
# приглушена целиком, а полная яркость спорила бы с этим. Не новый оттенок
# (Global Constraints — цвета только токенами `palette.py`): существующие
# токены с рендер-атрибутом Rich `dim`, тот же приём, что у акцента
# `f"{_ACC} bold"` в `markdown_render.py`.
SETTLED_OK = f"{OK} dim"
SETTLED_ERR = f"{ERR} dim"


def group_summary(settled: Sequence[SettledRow]) -> str:
    """`принято N · закоммичено M` — нулевые сегменты опущены (С3 смоука
    волны 4). Общего слова-зонтика нет: «закоммичено» нельзя подписать тем
    же словом, что и ручное принятие — коммит происходит без участия
    пользователя на этом экране. `settled` непуст всегда, когда строка
    вообще зовётся, поэтому пустая строка (обе категории по нулю) невозможна.
    """
    manual = sum(1 for row in settled if row.reason == SETTLED_MANUAL)
    commit = sum(1 for row in settled if row.reason == SETTLED_COMMIT)
    parts = []
    if manual:
        parts.append(f"{_SETTLED_REASON_GROUP[SETTLED_MANUAL]} {manual}")
    if commit:
        parts.append(f"{_SETTLED_REASON_GROUP[SETTLED_COMMIT]} {commit}")
    return " · ".join(parts)


def build_group_row(settled: Sequence[SettledRow], *, expanded: bool) -> Text:
    """Строка группы: `▸`/`▾` + сводка, приглушена целиком (§4.2, §13).

    Свой глиф (свёрнуто/раскрыто) стоит в маркерной колонке ВМЕСТО курсорного
    `▸ `/`  ` активных строк — курсор на этой строке виден только фоном
    выделения (`.diff-row.selected` в `styles.tcss`), второй глиф здесь был бы
    лишним.
    """
    glyph = _GROUP_EXPANDED if expanded else _GROUP_COLLAPSED
    text = Text(no_wrap=True, overflow="ellipsis")
    text.append(f"{glyph} {group_summary(settled)}", style=DEEP_DIM)
    return text


def build_settled_rows(
    settled: Sequence[SettledRow],
    *,
    selected: int,
    width: int = FALLBACK_WIDTH,
) -> List[Text]:
    """Строки раскрытой группы: та же сетка, что у активных, причина — в
    колонке вида (`принят`/`закоммичен` — С3 смоука волны 4). Марок нет:
    ``SettledRow`` не несёт ``by_shell``/``external`` — колонок для них нет. А
    вот точность у строки СВОЯ (``SettledRow.exact``), и `≈` рисуется по тому
    же правилу, в том же слоте и тем же тусклым токеном, что у активных строк
    (Д6 второго смоука): знак про ДОСТОВЕРНОСТЬ чисел, и слот занят всегда —
    иначе счётчики точных и неточных строк разъехались бы по вертикали. Путь
    и колонка вида остаются приглушёнными (`MUTED`), а счётчики красятся
    притушённым вариантом смысловых цветов (С2): строка группы приглушена
    целиком, но `+`/`−` обязаны нести смысл, не только украшать (не новый
    оттенок — существующие `OK`/`ERR` с рендер-атрибутом Rich `dim`, тот же
    приём, что у акцента `f"{_ACC} bold"` в `markdown_render.py`).
    """
    if not settled:
        return []

    reasons = [_SETTLED_REASON_ROW[row.reason] for row in settled]
    pluses = [f"+{row.add}" for row in settled]
    minuses = [f"−{row.del_}" for row in settled]
    kind_w = max(len(reason) for reason in reasons)
    plus_w = max(len(plus) for plus in pluses)
    minus_w = max(len(minus) for minus in minuses)
    head_w = _MARKER_W + kind_w + _KIND_GAP
    tail_w = 1 + plus_w + _COUNTER_GAP + minus_w  # 1 — слот `≈`
    path_w = max(_PATH_MIN, width - head_w - tail_w - _MARKS_GAP)

    rows: List[Text] = []
    for idx, row in enumerate(settled):
        is_selected = idx == selected
        text = Text(no_wrap=True, overflow="ellipsis")
        text.append("▸ " if is_selected else "  ", style=ACCENT)
        text.append(reasons[idx].ljust(kind_w) + " " * _KIND_GAP, style=MUTED)
        text.append(
            truncate_path_left(row.path, path_w).ljust(path_w), style=MUTED
        )
        text.append(" " * _MARKS_GAP)
        text.append(APPROX if not row.exact else " ", style=DEEP_DIM)
        text.append(pluses[idx].rjust(plus_w), style=SETTLED_OK)
        text.append(" " * _COUNTER_GAP)
        text.append(minuses[idx].rjust(minus_w), style=SETTLED_ERR)
        rows.append(text)
    return rows


def _settled_entry(row: SettledRow) -> FileEntry:
    """`FileEntry`-заглушка для вьюера группы: тело — кумулятив сессии.

    `exact` берётся У СТРОКИ, а не назначается: числа группы посчитаны от базы
    начала сессии (§12), и `EditsView.file_diff` собирает тело оттуда же — но
    у пути, чьей базы в сторе нет вовсе, те же числа пришли из журнала, и
    шапка обязана оставить при них маркер `≈` (`build_viewer_header` выводит
    его из `entry.exact`). Хардкод `True` здесь снимал маркер и обещал
    точность, которой нет (ре-ревью фикс-волны). Если базу сравнить нечем
    (бинарь, кап), `file_diff` честно вернёт `exact=False`, и вьюер падает на
    историю журнала сам (`DiffFileViewer._build_body`).
    """
    return FileEntry(
        path=row.path,
        add=row.add,
        del_=row.del_,
        kind=row.kind,
        exact=row.exact,
        countable=True,
        by_shell=False,
        external=False,
        revertable=False,
        last_ts=0.0,
    )


def _has_accepted_base(row: ActiveRow) -> bool:
    """Есть ли у пути принятая база вообще — гейт `u`/`Ctrl+U` в списке и во
    вьюере (финальный фикс волны 4): НЕ то же самое, что действующая ступень
    (`row.step`/`_step_is_accepted` — гейт глифа `↺`; `accepted_step_ts`/
    `_counts_from_accepted` — гейт футерного `ROW_ACCEPTED`). Владелец на
    смоуке решил явно — `u` остаётся рабочим и в «Ходе»
    (`ActiveRow.has_accepted_base` там читается независимо от того, что
    `row.step` всегда `None`, Р27; эффект виден в «Сессии»,
    `ACCEPT_TURN_NOTE`/`RESET_TURN_NOTE`), и в «Сессии» при тай-брейке Р28
    (ступень разрешилась в HEAD, а принятая база всё ещё жива) — тоже.
    """
    return row.has_accepted_base


# --- плашка результата --------------------------------------------------------

# Тон плашки: успех, отказ и спокойное «так не получится» (Р24). Глифа у
# спокойной нет вовсе — ✓ обещал бы сделанное, ⚠ пугал бы поломкой.
_FLASH_GLYPHS = {"ok": "✓ ", "warn": "⚠ ", "note": ""}
_FLASH_CLASSES = {
    "ok": "set-flash-ok",
    "warn": "set-flash-warn",
    "note": "set-flash-note",
}


def accept_tone(outcome: AcceptOutcome, *, is_git: bool) -> str:
    """Тон плашки принятия: `ok` только когда всё прошло дочиста — без
    пропусков и без отказа стейджинга."""
    if not outcome.accepted or outcome.skipped:
        return "warn"
    if is_git and outcome.stage_error is not None:
        return "warn"
    return "ok"


def reset_tone(outcome: ResetOutcome) -> str:
    """Тон плашки сброса принятия — та же логика, что у `accept_tone`."""
    if not outcome.reset or outcome.skipped:
        return "warn"
    return "ok"


class _ActionFlash:
    """Плашка результата действия — канон §16 (`.set-flash-ok`/`-warn`).

    Общая обоим экранам правок: акк обязан появиться там, где пользователь
    нажал клавишу. Мутирующие действия вьюера (`a`/`u`/`r`) идут через
    колбэки в `DiffScreen` и потому всегда флешатся ТАМ (`self` внутри
    `_accept`/`_apply_reset`/`_apply_revert` — экран-список, не вьюер): плашка
    списка лежит ПОД вьюером и не видна, пока действие не закрыло его, —
    отказ, оставляющий вьюер открытым, доходит до пользователя всплывающим
    уведомлением (тот же промах уже ловило ревью отката из вьюера).
    """

    def _flash(self, text: str, *, outcome: str = "ok") -> None:
        """Плашка под телом экрана: `ok` (✓), `warn` (⚠) либо `note` (без глифа).

        Живёт в `#root`, а не в `#trace`: тело пересобирается на каждое
        перечитывание, и плашка исчезала бы ровно тогда, когда рассказывает про
        только что случившееся (`_apply_revert` перечитывает сразу за акком).

        Замена — `update` существующего виджета, а не `remove()+mount()`: снятие
        в Textual асинхронно, и повторное нажатие роняло бы `DuplicateIds`.
        """
        glyph = _FLASH_GLYPHS.get(outcome, "⚠ ")
        cls = _FLASH_CLASSES.get(outcome, "set-flash-warn")
        try:
            flash = self.query_one("#diff-flash", Static)
        except NoMatches:
            self.query_one("#root", Vertical).mount(
                Static(
                    glyph + text, id="diff-flash", classes=cls, markup=False
                ),
                before=self.query_one(_SEL_FOOTER, Static),
            )
            return
        flash.update(glyph + text)
        flash.set_classes(cls)
        flash.display = True

    def _clear_flash(self) -> None:
        """Снять плашку: сказанное относилось к прошлому набору.

        Виджет прячется, а не удаляется: `remove()` в Textual асинхронен, и
        следующее нажатие успело бы смонтировать второй `#diff-flash` до того,
        как исчезнет первый (та же ловушка, из-за которой плашка идемпотентна).
        """
        for flash in self.query("#diff-flash"):
            flash.display = False


