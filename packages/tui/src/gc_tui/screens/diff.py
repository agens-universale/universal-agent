def edit_caption(number: int, record: EditRecord) -> str:
    """Подпись одной правки в теле без точной базы: «— правка 2 (14:05) —».

    Канал называется только у команды (`call_id is None`): правка инструментом
    агента — норма, и подписывают её не больше, чем строку списка.
    """
    stamp = time.strftime("%H:%M", time.localtime(record.ts))
    channel = f", {EDIT_BY_COMMAND}" if record.call_id is None else ""
    return f"— правка {number} ({stamp}{channel}) —"


def inexact_note(records: Sequence[EditRecord]) -> str:
    """Нота над телом без точной базы — по тому, чем файл на самом деле правили.

    «Командами» дописывается, только если все записи пути шелловые. Точную
    базу теряет и правка инструментом (снимок вытеснила живая эвикция), и в
    этом случае нота с «командами» приписывала бы правку не тому автору.
    """
    if any(record.call_id is not None for record in records):
        return VIEWER_NOTE_INEXACT
    return VIEWER_NOTE_INEXACT_SHELL


# Метрики хрома (выше, в «метриках сетки») и служебная строка ниже —
# ПУБЛИЧНЫЕ: их берёт соседний экран подтверждения отката
# (`diff_revert_confirm`). Он часть того же экрана изменений, только вынесенная
# в свой файл, и второй копии этих чисел у него быть не должно — разъехались бы
# заливка и обрезка на одной и той же ширине.
#
# Ширина, на которую собрано тело, ещё не мерилась. Отдельное значение нужно:
# `None` — законная ширина «раскладки ещё нет», и совпадение с ней означало бы
# «тело актуально», хотя тела нет вовсе.
BODY_UNBUILT = -1

# Потолок строк в участке. Ради него всё и режется: один `Static` на файл в
# 4 тыс. строк раскладывается ~0.8 с (замер — Ревизия 8), а участки полотно
# рисует по мере попадания в кадр. Режется и правка длиной в файл — куски
# несут один её номер, и курсор метит их разом (Р23).
CONTEXT_CHUNK = 100


class _BodyPart(NamedTuple):
    """Часть тела вьюера: служебная строка ИЛИ участок диффа.

    Кэшируется вместо готовых виджетов: снятый с экрана `Static` обратно не
    монтируется, а разбор тела переживает пересборку и стоит дорого.

    `edit` — номер правки, к которой часть относится (курсор `n`/`p` метит
    ВСЕ части одной правки разом); `None` — часть не правка: контекст, подпись
    рода тела, объяснение вместо тела.
    """

    meta: Optional[str]  # текст служебной строки; None — это участок тела
    lines: int  # высота участка в строках — известна ДО рендера
    edit: Optional[int]  # номер правки или None
    render: Optional[Callable[[], Text]] = None  # содержимое по требованию

    @property
    def text(self) -> Optional[Text]:
        """Содержимое участка. Обращение к нему И ЕСТЬ требование собрать его.

        Служебная строка отдаёт `None` — рисовать движком в ней нечего.
        Экраны сюда не ходят: им нужно место участка, а не его текст, и
        наполняет виджеты полотно (`LazyBody`), когда участок доезжает до
        кадра.
        """
        return None if self.render is None else self.render()


def meta_line(text: Union[str, Text], extra: str = "") -> Static:
    """Служебная строка тела: в мышиное выделение не попадает (§16).

    `Text` принимается ради строк с цветными кусками — заголовок файла в
    превью отката несёт счётчики, и красит их общий `paint_counters`.
    """
    classes = "line-meta" + (f" {extra}" if extra else "")
    return NoSelectStatic(text, classes=classes, markup=False)


def split_body(
    hunks: str, *, path: str, fill_width: Optional[int], by_edits: bool = True
) -> List[_BodyPart]:
    """Тело файла участками «контекст — правка — контекст», СОБИРАЕМЫМИ ЛЕНИВО.

    Правка — подряд идущие добавленные и удалённые строки: именно её метит
    курсор и по ней прыгают `n`/`p`. Контекст между правками режется на куски
    по `CONTEXT_CHUNK` строк — в режиме «весь файл» его бывает тысячи; так же
    режется и правка длиной в файл (переписан целиком), только куски её несут
    ОДИН номер, и кромка курсора остаётся непрерывной.

    `by_edits=False` — резать РОВНЫМИ кусками, не глядя на правки: так просит
    подтверждение отката, где курсора по правкам нет и выравнивать участки не
    на что. Границы по правкам там не бесплатны: на файле с сотней мелких
    правок они дают сотни участков вместо десятка.

    **Высота участка известна отсюда, из РАЗБОРА входа, а картинка — нет**
    (Р23): `HunkBody` отдаёт виды строк тела, то есть их число, за доли той
    цены, которой стоит рисование (8 мс против 540 на теле в 8 тыс. строк).
    Полотно резервирует место по высотам сразу, а рисуются те участки, что
    доехали до кадра, — до файла, до которого не долистали, дело не доходит
    вовсе.

    Решения, общие для всего тела (ширина колонки номеров, порог подсветки
    синтаксиса, границы пар для внутристрочных акцентов), движок принимает
    один раз на файл — участки не могут разъехаться гаттером и раскраской.
    """
    body = HunkBody(hunks, path=path, fill_width=fill_width)
    if not body.shown_lines:  # рисовать нечего
        return []
    kinds = body.kinds
    bounds = _part_bounds(kinds) if by_edits else _even_bounds(len(kinds))
    return [
        _BodyPart(
            None,
            end - begin,
            edit,
            lambda first=begin, last=end: body.render(first, last),
        )
        for begin, end, edit in bounds
    ]


def _part_bounds(kinds: Sequence[str]) -> List[Tuple[int, int, Optional[int]]]:
    """Границы участков `(первая строка, за последней, номер правки)`.

    Правка — подряд идущие `add`/`del`; всё остальное контекст. И то и другое
    режется на куски по `CONTEXT_CHUNK`: файл, переписанный целиком, — это ОДНА
    правка в тысячи строк, и неразрезанной она давала бы один `Static` на всё
    тело, тот самый фриз, ради которого тело и режется. Куски одной правки
    несут ОДИН её номер: курсор метит их разом, и кромка остаётся непрерывной.
    """
    bounds: List[Tuple[int, int, Optional[int]]] = []
    edits = 0
    start = 0
    for index in range(1, len(kinds) + 1):
        if index < len(kinds) and _is_edit(kinds[index]) == _is_edit(
            kinds[start]
        ):
            continue
        if _is_edit(kinds[start]):
            for pos in range(start, index, CONTEXT_CHUNK):
                bounds.append((pos, min(pos + CONTEXT_CHUNK, index), edits))
            edits += 1
        else:
            for pos in range(start, index, CONTEXT_CHUNK):
                bounds.append((pos, min(pos + CONTEXT_CHUNK, index), None))
        start = index
    return bounds


def _even_bounds(rows: int) -> List[Tuple[int, int, Optional[int]]]:
    """Границы ровных кусков по `CONTEXT_CHUNK` строк — тело без курсора.

    Номера правки у кусков нет: метить курсором на таком теле нечего, а по
    файлам подтверждение ходит своими заголовками.
    """
    return [
        (pos, min(pos + CONTEXT_CHUNK, rows), None)
        for pos in range(0, rows, CONTEXT_CHUNK)
    ]


def _is_edit(kind: str) -> bool:
    """Строка правки — добавленная или удалённая; контекст и `⋮` — нет."""
    return kind in ("add", "del")


def edit_counter(index: int, total: int) -> str:
    """«правка 2/4» — где мы среди правок файла (Р18).

    Показывается и при единственной правке (`правка 1/1`): счётчик отвечает на
    вопрос «сколько их всего», и молчание при одной читалось бы как «счётчик
    сломался», а не как «правка одна».
    """
    return f"правка {index + 1}/{total}"


class DiffFileViewer(_ActionFlash, Screen):
    """Изменения одного файла: тело правок, навигация по ним и по файлам.

    Тела бывает три рода, и различает их САМ экран — по флагам записи:

    * точная база есть — кумулятив «база → диск», разрезанный на участки
      «контекст — правка — контекст»;
    * точной базы нет (Р12) — записи журнала подряд в хронологии, каждая со
      своей подписью: время и канал;
    * считать было нечем (`countable=False`) — строка-объяснение вместо тела.

    От рода зависит и `f`: полного файла в записях журнала нет, поэтому без
    точной базы режим неприменим — клавиша не значится в футере и ничего не
    делает. Переключённая шапка при неизменившемся теле была бы враньём.

    `n`/`p` двигают КУРСОР по правкам, а не прокрутку (Р18): текущая правка
    помечена акцентной кромкой слева всегда, даже когда файл целиком помещается
    на экране, — иначе на коротком диффе клавиша выглядела бы мёртвой. Ход
    круговой, как `↑`/`↓` в списке файлов; кадр едет за курсором только когда
    правка вне его. В шапке при этом стоит «правка 2/4»: где мы и сколько их.

    Действий у вьюера ровно три, и все — над ОТКРЫТЫМ файлом (Р20, пересмотр
    Р9): `a` принимает его, `u` снимает принятие, `r` откатывает. Все три идут
    колбэками в `DiffScreen` (`on_accept`/`on_reset`/`on_revert`) — экран сам
    мутирует, флешит и, если что-то реально изменилось, закрывает вьюер;
    здесь — только жест и гейт применимости (`can_reset`/колбэк не `None`).
    Массовых (`Ctrl+A`, `Ctrl+U`, `Ctrl+R`) здесь нет: они живут в списке, где
    виден весь набор, а не на экране одного файла.
    """

    # `←`/`→` у `VerticalScroll` заняты своей прокруткой, а фокус на старте
    # уезжает именно в него: без priority экран этих клавиш не увидит вовсе.
    BINDINGS = [
        Binding(
            "left", "prev_file", "предыдущий файл", show=False, priority=True
        ),
        Binding(
            "right", "next_file", "следующий файл", show=False, priority=True
        ),
        # Ctrl+стрелка = «двигать кадр» — та же идиома, что у Ctrl+вверх/вниз в
        # экранах форм. Простые стрелки заняты переключением файла, а строка
        # тела здесь не переносится (иначе рассыплется ленивая сборка), поэтому
        # хвост длинной строки достаётся прокруткой вбок.
        Binding(
            "ctrl+left", "scroll_body_left", "влево", show=False, priority=True
        ),
        Binding(
            "ctrl+right",
            "scroll_body_right",
            "вправо",
            show=False,
            priority=True,
        ),
    ]

    def _body_scroll(self) -> LazyBody | None:
        try:
            return self.query_one(_SEL_TRACE, LazyBody)
        except NoMatches:
            return None

    def action_scroll_body_left(self) -> None:
        body = self._body_scroll()
        if body is not None:
            body.scroll_left(animate=False)

    def action_scroll_body_right(self) -> None:
        body = self._body_scroll()
        if body is not None:
            body.scroll_right(animate=False)

    def __init__(
        self,
        *,
        view: EditsView,
        source: str,
        files: Sequence[FileEntry],
        index: int,
        on_revert: Optional[Callable[[str], None]] = None,
        on_accept: Optional[Callable[[str], None]] = None,
        on_reset: Optional[Callable[[str], None]] = None,
        can_reset: Optional[Sequence[bool]] = None,
        can_revert: Sequence[bool] = (),
        accepted_ts: Optional[Sequence[Optional[float]]] = None,
        head_refs: Optional[Sequence[Optional[str]]] = None,
    ) -> None:
        super().__init__()
        self._view = view
        self._source = source
        self._files = list(files)
        self._index = min(max(index, 0), max(0, len(self._files) - 1))
        self._on_revert = on_revert
        self._on_accept = on_accept
        self._on_reset = on_reset
        # Параллельный `files` список (образец — `accepted` в `build_rows`):
        # `True` — у файла этого индекса есть принятая база, `u` применим.
        self._reset_flags = (
            list(can_reset)
            if can_reset is not None
            else [False] * len(self._files)
        )
        # Тот же приём для `r` (Е5, задача 5 фикса волны 4): `True` — у файла
        # этого индекса есть достоверная база отката. Раньше вьюер спрашивал
        # только колбэк (`can_revert=self._on_revert is not None`) и
        # рекламировал `r` даже у файла, которому список уже отказал.
        self._can_revert_flags = list(can_revert)
        # Тот же приём: `None` у файла, чья ступень «Сессии» сейчас не
        # `.accepted` (обычный файл, ступень HEAD, либо вьюер группы, где
        # звонящий этот параметр вовсе не передаёт) — шапка тогда без подписи.
        self._accepted_ts = (
            list(accepted_ts)
            if accepted_ts is not None
            else [None] * len(self._files)
        )
        # Симметричный параллельный список для ступени HEAD (С8 смоука
        # волны 4) — тот же приём: `None` у файла, чья ступень сейчас не
        # `head`, либо у вьюера группы, который этот параметр не передаёт.
        self._head_refs = (
            list(head_refs)
            if head_refs is not None
            else [None] * len(self._files)
        )
        self._full = False
        self._fill = BODY_UNBUILT  # ширина, на которую собрано тело
        # Виджеты каждой правки: подпись и тело одной правки метятся курсором
        # разом, поэтому список списков, а не плоский.
        self._edits: List[List[Static]] = []
        self._edit_idx = 0
        # Кэш готового тела по (путь, режим, ширина) — образец `DiffBlock._cache`.
        # Тело «весь файл» на крупном файле считается заметно, а возвращаются к
        # нему постоянно: тогл `f`, соседний файл и обратно, прежняя ширина.
        self._cache: Dict[
            Tuple[str, bool, Optional[int]], List[_BodyPart]
        ] = {}

    @property
    def index(self) -> int:
        return self._index

    @property
    def entry(self) -> FileEntry:
        return self._files[self._index]

    @property
    def full(self) -> bool:
        """Режим «весь файл» (контекст ∞) вместо одних изменений."""
        return self._full

    def clipboard_source_cite(self) -> Optional[Tuple[str, str]]:
        """Источник для суффикса буфера: `("diff", путь)`."""
        return ("diff", self.entry.path)

    # ---- каркас --------------------------------------------------------

    def compose(self) -> ComposeResult:
        with Vertical(id="root"):
            with Horizontal(id="header"):
                yield Static("", id="header-left", markup=False)
            yield LazyBody(id="trace")
            yield Static("", id="footer", markup=False)

    def on_mount(self) -> None:
        """Шапка и футер сразу, тело — первым же `Resize` (он придёт тем же тактом).

        Собирать тело здесь рано: раскладка ещё не назвала `#trace` ширину, а
        собранное вслепую пришлось бы собирать заново — и дельта, и участки, и
        виджеты считались бы по второму разу (замер на файле в 4 тыс. строк:
        ровно половина времени открытия).

        Второй заход — ПОСЛЕ раскладки: размах прокрутки вбок до неё не измерен,
        и подсказка про `Ctrl+←/→` без него не появилась бы никогда.
        """
        self._render_chrome()
        self.call_after_refresh(self._render_chrome)

    def on_resize(self, event: events.Resize) -> None:
        """Ширина сменилась — заливка строк тянется до нового края.

        Сверка идёт по ширине ЗАЛИВКИ: `Resize` приходит и на смену высоты, а
        от неё тело не зависит вовсе; `BODY_UNBUILT` отличает «ширина та же»
        от «тела ещё не собирали».
        """
        if self._fill_width(event.size.width) == self._fill:
            return
        self._render_screen(screen_width=event.size.width)

    # ---- рендер --------------------------------------------------------
    # Имя `_render` занято Textual (`Widget._render`) — свой метод с таким
    # именем гасит отрисовку экрана целиком.

    def _render_screen(self, *, screen_width: Optional[int] = None) -> None:
        """Перерисовать экран. `screen_width` — ширина из события `Resize`.

        Тело — ПЕРВЫМ: счётчик правок в шапке берётся из него, и при обратном
        порядке соседний файл получал бы шапку с числом правок предыдущего.

        Тело собирает первый же `Resize` (см. `on_mount`), а не монтаж экрана.
        """
        self._render_body(self._fill_width(screen_width))
        self._render_chrome(screen_width)

    def _render_chrome(self, screen_width: Optional[int] = None) -> None:
        """Шапка и футер: от содержимого тела зависит только счётчик правок.

        Счётчик берётся из уже собранного тела (`self._edits`), а не считается
        заново: «правка 2/4» обязана говорить ровно о тех участках, по которым
        ходит курсор.
        """
        self.query_one(_SEL_HEADER_LEFT, Static).update(
            paint_counters(
                build_viewer_header(
                    self._source,
                    self.entry,
                    full=self._full,
                    width=self._header_width(screen_width),
                    edit=self._edit_idx,
                    edits=len(self._edits),
                    accepted_ts=self._accepted_caption_ts(),
                    head_ref=self._head_caption_ref(),
                )
            )
        )
        self.query_one(_SEL_FOOTER, Static).update(
            viewer_footer(
                full=self._full,
                can_full=self._can_full(),
                can_switch=len(self._files) > 1,
                can_step=len(self._edits) > 1,
                can_add=self._can_add(),
                can_reset=self._can_reset(),
                can_revert=self._can_revert(),
                can_sideways=self._can_sideways(),
            )
        )

    def _can_sideways(self) -> bool:
        """Есть ли куда прокручивать вбок — от этого зависит подсказка."""
        body = self._body_scroll()
        return bool(body is not None and body.max_scroll_x)

    def _render_body(self, fill: Optional[int]) -> None:
        """Пересобрать тело участками и вернуть курсор на прежнюю правку.

        Курсор переживает и смену ширины, и переключение `f`: правки в обоих
        режимах одни и те же — меняется только контекст вокруг них, — и
        сбрасывать курсор в начало значило бы терять место чтения.

        Собирается не всё тело, а то, что попадает в кадр (Р23): участки уходят
        в полотно МЕСТАМИ — с высотой, но пока без содержимого, — и наполняются
        по мере прокрутки. Виджет у каждого участка при этом свой и живёт
        столько же, сколько тело, поэтому и курсор, и заливка, и доводка кадра
        работают ровно так же, как на собранном теле.
        """
        entry = self.entry
        body = self.query_one(_SEL_TRACE, LazyBody)
        self._edits = []
        self._fill = fill
        slots: List[BodySlot] = []
        for part in self._body_parts(entry, fill):
            if part.render is None:
                widget = meta_line(part.meta, "diff-part")
                slots.append(BodySlot(widget))
            else:
                widget = Static(
                    "", classes="diff-hunk diff-part", markup=False
                )
                slots.append(BodySlot(widget, part.lines, part.render))
            if part.edit is not None:
                while len(self._edits) <= part.edit:
                    self._edits.append([])
                self._edits[part.edit].append(widget)
        body.set_slots(slots)
        self._edit_idx = min(self._edit_idx, max(0, len(self._edits) - 1))
        self._paint_cursor()

    def _body_parts(
        self, entry: FileEntry, width: Optional[int]
    ) -> List[_BodyPart]:
        """Тело под текущий режим; повтор берётся из кэша виджета."""
        key = (entry.path, self._full, width)
        cached = self._cache.get(key)
        if cached is None:
            # Записи прошлых ширин выбрасываем: протяжка рамки иначе копила бы
            # по полному телу на каждый свой шаг (приём `DiffBlock._cache`).
            self._cache = {
                k: v for k, v in self._cache.items() if k[2] == width
            }
            try:
                cached = self._build_body(entry, width)
            except OSError:  # TimeoutError замка — подкласс OSError
                # Тело строится лениво, при отрисовке, — до границы действий
                # (`_survives_unreadable_edits`) отказ отсюда не доходит. Строка
                # вместо тела и без кэша: следующая отрисовка попробует снова.
                _logger.warning(
                    "тело файла не прочитано: %s", entry.path, exc_info=True
                )
                return [_BodyPart(EDITS_UNREADABLE, 0, None)]
            self._cache[key] = cached
        return cached

    def _build_body(
        self, entry: FileEntry, width: Optional[int]
    ) -> List[_BodyPart]:
        if not entry.countable:
            return [_BodyPart(VIEWER_NO_PREVIEW, 0, None)]
        if not entry.exact:
            return self._journal_body(entry, width)

        hunks, exact = self._view.file_diff(
            self._source, entry.path, full=self._full
        )
        if not exact:
            # Сервис не смог посчитать дельту от базы (бинарь, кап у пути
            # группы — `SettledRow` признака не несёт, и `entry.exact` знать
            # этого не мог): тело собирается из записей журнала, с честной
            # пометкой о неточности.
            return self._journal_body(entry, width)
        parts = split_body(hunks, path=entry.path, fill_width=width)
        if not parts:
            # База есть, а различий нет: файл вернули к исходному виду руками.
            return [_BodyPart(_NO_COUNTERS, 0, None)]
        return parts

    def _journal_body(
        self, entry: FileEntry, width: Optional[int]
    ) -> List[_BodyPart]:
        """Тело без точной базы: правки подряд, каждая со своей подписью.

        Правка здесь — запись журнала целиком: и подпись, и тело метятся
        курсором вместе, потому что читается такая правка с заголовка. Тело
        одной записи режется РОВНЫМИ кусками: границы по правкам внутри неё не
        нужны — курсор ходит по записям, — а длинная команда (`sed` по всему
        файлу) без нарезки снова стала бы одним `Static` на тысячи строк.
        """
        records = self._view.file_records(self._source, entry.path)
        parts = [_BodyPart(inexact_note(records), 0, None)]
        for number, record in enumerate(records, start=1):
            parts.append(
                _BodyPart(edit_caption(number, record), 0, number - 1)
            )
            parts.extend(
                part._replace(edit=number - 1)
                for part in split_body(
                    record.hunks,
                    path=entry.path,
                    fill_width=width,
                    by_edits=False,
                )
            )
        return parts

    def _can_full(self) -> bool:
        """Применим ли режим «весь файл».

        `exact` тут достаточно: он поднимается ровно тогда, когда дельта
        посчиталась от базы, то есть вместе с `countable`.
        """
        return self.entry.exact

    def _can_add(self) -> bool:
        """Есть ли что принимать: вьюер, открытый ИЗ ГРУППЫ (`on_accept is
        None`, §4.3 плана волны 4), нечего принимать — дельта от ступени
        пуста (ревью Задачи 10). Git больше не требуется (Р9-пересмотр):
        принятие сдвигает базу и без репозитория, стейджинг — best-effort.
        """
        return self._on_accept is not None

    def _can_reset(self) -> bool:
        """Есть ли у ОТКРЫТОГО файла принятая база — гейт `u` (§4.2/§4.3):
        активный (глиф `↺` не обязателен — тай-брейк Р28 и источник «Ход»
        могут его гасить, не трогая саму базу, финальный фикс волны 4), либо
        разобранный «вручную» (в группе — не «коммитом»).

        Индекс сверяется с длиной `_reset_flags` (приём `build_rows`,
        `marked`): список параллелен `files` по построению у обоих вызовов
        `DiffFileViewer(...)`, но чужой конструктор мог передать короче.
        """
        return (
            self._on_reset is not None
            and self._index < len(self._reset_flags)
            and self._reset_flags[self._index]
        )

    def _can_revert(self) -> bool:
        """`r` во вьюере жив только у файла с достоверной базой (Е5) — тот же
        признак, что гасит `r` в списке; подключённый обработчик — необходимое,
        не достаточное условие.

        Индекс сверяется с длиной `_can_revert_flags`, тем же приёмом, что и
        `_can_reset` про `_reset_flags`: список параллелен `files` по
        построению у обоих вызовов `DiffFileViewer(...)`, но чужой конструктор
        мог передать короче. Default-значение параметра конструктора
        (`can_revert: Sequence[bool] = ()`) даёт этому методу тот же исход, что
        и пустому списку — если звонящий передал `on_revert`, но забыл
        `can_revert`, `r` окажется молча выключен, а не упадёт: молчаливая
        смена поведения, а не ошибка сборки.
        """
        return (
            self._on_revert is not None
            and self._index < len(self._can_revert_flags)
            and self._can_revert_flags[self._index]
        )

    def _accepted_caption_ts(self) -> Optional[float]:
        """Момент принятия для шапки ОТКРЫТОГО файла — `None`, если ступень
        «Сессии» сейчас не `.accepted` (см. `_can_reset` про параллельность
        списка `files`)."""
        if self._index < len(self._accepted_ts):
            return self._accepted_ts[self._index]
        return None

    def _head_caption_ref(self) -> Optional[str]:
        """Подпись коммит-ступени для шапки ОТКРЫТОГО файла — симметрично
        `_accepted_caption_ts` (С8 смоука волны 4)."""
        if self._index < len(self._head_refs):
            return self._head_refs[self._index]
        return None

    def _header_width(self, screen_width: Optional[int] = None) -> int:
        width = (screen_width or self.size.width) - CHROME_PADDING
        return width if width > 0 else FALLBACK_WIDTH

    def _fill_width(self, screen_width: Optional[int] = None) -> Optional[int]:
        """Ширина заливки строки: тело `#trace` минус колонка скроллбара.

        На `Resize` ширина берётся ИЗ СОБЫТИЯ: экран получает его раньше, чем
        `#trace` примет новый размер, и замер контейнера отдал бы предыдущую
        ширину — заливка отставала бы от края на шаг. Разница между экраном и
        телом — рамка `#trace` (Р16); паддинга у тела в рамке нет. Замером же
        рамку вычитать не надо: `size` — это content-region.

        Скроллбар резервируется всегда: `size.width` его колонку не вычитает
        (та же ловушка, что у сетки списка), а у диффа он есть почти наверняка.
        Кромка курсора (`EDIT_EDGE`) — две колонки у каждого участка тела, и
        заливка обязана считать их своими: иначе она уехала бы под скроллбар.
        `None` — ширины ещё нет: движок зальёт по содержимому, первый же
        `Resize` пересоберёт.
        """
        if screen_width is None:
            try:
                width = self.query_one(_SEL_TRACE, VerticalScroll).size.width
            except Exception:
                width = 0
        else:
            width = screen_width - TRACE_FRAME
        width -= SCROLLBAR_COLUMN + EDIT_EDGE
        return width if width > 0 else None

    # ---- навигация -----------------------------------------------------

    def _go_edit(self, index: int) -> None:
        """Курсор на следующую/предыдущую правку файла — ПО КРУГУ (Р18).

        Круг тот же, что у `↑`/`↓` в списке файлов: у экрана один ритм
        навигации, и на последней правке клавиша не обязана выглядеть мёртвой.
        """
        if not self._edits:
            return
        self._edit_idx = index % len(self._edits)
        self._paint_cursor()
        self._render_chrome()  # «правка 2/4» переехала
        self._reveal_cursor()

    def _paint_cursor(self) -> None:
        """Кромка курсора — НА МЕСТЕ, сменой класса (§16).

        Пересобирать тело на каждый шаг курсора нельзя: на файле в тысячи строк
        это те самые доли секунды, ради которых тело и разрезано на участки.
        """
        for index, widgets in enumerate(self._edits):
            paint = index == self._edit_idx
            for widget in widgets:
                (widget.add_class if paint else widget.remove_class)("cursor")

    def _reveal_cursor(self) -> None:
        """Довести кадр до курсора — ТОЛЬКО если правка вне его.

        Прокрутка здесь следствие, а не смысл жеста: `scroll_visible` без
        `top` сам ничего не делает, когда правка уже видна целиком.

        Участок под курсором собирается ДО того, как кадр к нему поедет (Р23):
        прокрутка наполнила бы его лишь следующим тактом, и прыжок к далёкой
        правке показал бы пустое место.
        """
        if (
            0 <= self._edit_idx < len(self._edits)
            and self._edits[self._edit_idx]
        ):
            target = self._edits[self._edit_idx][0]
            self.query_one(_SEL_TRACE, LazyBody).ensure(target)
            self.call_after_refresh(target.scroll_visible, animate=False)

    def _go_file(self, step: int) -> None:
        """Соседний файл источника — тот же экран, без push нового.

        Круговая, как `↑`/`↓` в списке: у экрана один ритм навигации.
        """
        if len(self._files) < 2:
            return
        # Плашка говорила про прошлый файл — над диффом соседнего она врала бы
        # (то же правило, что у смены источника в списке).
        self._clear_flash()
        self._index = (self._index + step) % len(self._files)
        if not self._can_full():
            self._full = False  # у нового файла режима «весь файл» нет
        self._edit_idx = 0  # новый файл читают с первой его правки
        self._render_screen()
        # Новый файл читают с начала. Textual сам ужимает прокрутку только под
        # размер нового тела: с длинного файла на длинный она осталась бы
        # посреди чужого диффа.
        self.query_one(_SEL_TRACE, VerticalScroll).scroll_home(animate=False)

    def action_prev_file(self) -> None:
        self._go_file(-1)

    def action_next_file(self) -> None:
        self._go_file(1)

    # ---- принятие и сброс ------------------------------------------------

    def _accept(self) -> None:
        """`a` — открытый файл новой точкой отсчёта (пересмотр Р9, Р20).

        Мёртво во вьюере, открытом из группы (`on_accept is None`): туда
        нечего принимать (§4.3). Мутация и её акк — в `DiffScreen` (колбэк):
        экран сам решает, флешить ли на списке и закрывать ли вьюер, — здесь
        только жест над файлом, который сейчас читают.
        """
        if self._on_accept is not None:
            self._on_accept(self.entry.path)

    def _reset(self) -> None:
        """`u` — снять принятие открытого файла; применимо только когда у
        него есть принятая база (`_can_reset`, §4.2/§4.3)."""
        if self._on_reset is not None and self._can_reset():
            self._on_reset(self.entry.path)

    def on_key(self, event: events.Key) -> None:
        key = norm_key(event.key)
        if key == "n":
            event.stop()
            self._go_edit(self._edit_idx + 1)
        elif key == "p":
            event.stop()
            self._go_edit(self._edit_idx - 1)
        elif key == "f":
            event.stop()
            if self._can_full():
                self._full = not self._full
                self._render_screen()
        elif key == "a":
            event.stop()
            self._accept()
        elif key == "u":
            event.stop()
            self._reset()
        elif key == "r":
            event.stop()
            if self._on_revert is not None:
                self._on_revert(self.entry.path)
