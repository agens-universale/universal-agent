def footer_text(
    *,
    row: str = ROW_PLAIN,
    empty: bool = False,
    source: str = SOURCE_SESSION,
    has_group: bool = False,
    can_reset: bool = False,
    can_revert: bool = True,
    step: Optional[str] = None,
    mass_accept: bool = False,
    mass_revert: bool = False,
    mass_reset: bool = False,
    group_expanded: bool = False,
) -> str:
    """Двухстрочный футер v3 (§13): навигация + действия под строку курсора.

    Правило экрана (Ж3 батча 4): что меняется от КУРСОРА — в строке действий,
    что от СОСТОЯНИЯ экрана — в строке навигации. Поэтому `Enter` живёт внизу
    и называется по строке (`дифф` / `развернуть` / `свернуть` / «что агент
    сделал с файлом за сессию»), а `Tab` остаётся наверху: он зависит от
    наличия группы, а не от того, где стоит курсор. `group_expanded` читает
    одна строка `ROW_GROUP` — она называет `Enter` по текущему развороту.

    Строка навигации одна на все состояния — источник и git/cache-режим её не
    меняют: `a`/`u`/`r` работают одинаково в обоих (Р26). Строку действий
    решает `row` — обычный активный файл, файл, который СЧИТАЕТСЯ от принятой
    ступени (глиф `↺` + действующая ступень `.accepted`), заголовок группы
    «принято» или файл ВНУТРИ неё. `has_group` (С4 смоука волны 4) — жив ли
    переключатель областей `Tab`: сегмент в навигации появляется, только когда
    переключать реально есть куда, то есть НЕПУСТЫ обе области (Д3 второго
    смоука — с пустой активной частью `Tab` молчит, и реклама соврала бы).
    Без аргумента (старые вызовы) сегмента нет, как и раньше.

    `source` и `step` (`RowStep.kind` строки под курсором) подставляют цель
    `r` обычной строке: у «Хода» она своя (начало хода), у коммит-ступени —
    закоммиченное состояние (Д4). Состояние `ROW_ACCEPTED` ни тем, ни другим
    не параметризуется — оно возможно только в «Сессии» (Р27: ступеней «Ход»
    не видит) и называет свою цель само.

    `can_reset` (финальный фикс волны 4, по умолчанию выключен — старые
    вызовы не меняются) — жив ли `u` на строке под курсором. У обычной строки
    это «принятая база есть, но действующая не она»: тай-брейк Р28 отдал
    ступень HEAD, либо источник — «Ход» (Р27-ревью: владелец оставил `u`
    рабочим и там, эффект просто виден в «Сессии»). У файла внутри группы
    (`ROW_GROUP_FILE`, Ж4 батча 4) — «принят вручную, а не коммитом»: там
    параметр читается тоже, и звонящий обязан считать его тем же вызовом,
    который клавишу и исполняет (`_reset_target`). `ROW_ACCEPTED` называет
    `u` сама и параметр игнорирует, `ROW_GROUP` не называет его вовсе —
    снимать на самом заголовке нечего.

    `can_revert` (Д10, по умолчанию включён — старые вызовы не меняются) —
    есть ли у файла достоверная база отката (`FileEntry.revertable`): без неё
    `r` неприменим, и сегмент уходит по общему канону экрана.

    `mass_accept`/`mass_revert`/`mass_reset` (Е4, задача 5 фикса волны 4,
    по умолчанию выключены — старые вызовы не рекламируют ничего) — живы ли
    `Ctrl+A`/`Ctrl+R`/`Ctrl+U` СЕЙЧАС, во всём представлении, а не в строке
    под курсором: массовые клавиши это решение звонящего (`DiffScreen`), а не
    строки, и хвост (`mass_tail`) поэтому ОДИН на любую строку, включая
    `ROW_GROUP`. Раньше `Ctrl+U` рекламировался только со строки группы и
    только при наличии принятых ВРУЧНУЮ — курсор на активном файле о рабочей
    клавише не узнавал ничего (сцена смоука 3).
    """
    if empty:
        return _FOOTER_EMPTY
    nav = _FOOTER_NAV_WITH_GROUP if has_group else _FOOTER_NAV
    if row == ROW_GROUP:
        parts = [_ENTER_COLLAPSE if group_expanded else _ENTER_EXPAND]
    elif row == ROW_GROUP_FILE:
        parts = [_ENTER_GROUP_FILE]
        if can_reset:
            parts.append(_GROUP_FILE_RESET)
    else:
        accepted = row == ROW_ACCEPTED
        words = _FOOTER_ACTIONS_ACCEPTED if accepted else _FOOTER_ACTIONS_PLAIN
        parts = [_ENTER_DIFF, words.accept]
        if accepted or can_reset:
            parts.append(words.reset)
        if can_revert:
            parts.append(
                words.revert.format(target=_revert_target(source, step))
            )
    tail = mass_tail(accept=mass_accept, revert=mass_revert, reset=mass_reset)
    if tail:
        parts.append(tail)
    actions = " · ".join(parts)
    return f"{nav}\n{actions}"


def _revert_target(source: str, step: Optional[str]) -> str:
    """Куда `r` вернёт файл — словами футера (Д4).

    Ступень старше источника: коммит-ступень действует только в «Сессии»
    (Р27), и там она и решает цель; у остальных строк её задаёт источник.
    """
    if step == STEP_HEAD:
        return _FOOTER_TARGET_HEAD
    return _FOOTER_TARGET_BY_SOURCE.get(
        source, _FOOTER_TARGET_BY_SOURCE[SOURCE_SESSION]
    )


def viewer_footer(
    *,
    full: bool,
    can_full: bool,
    can_switch: bool = True,
    can_step: bool = True,
    can_add: bool = True,
    can_reset: bool = False,
    can_revert: bool = True,
    can_sideways: bool = False,
) -> str:
    """Футер вьюера. Мёртвые клавиши не рекламируются — как и везде на экране.

    Полного файла в записях журнала нет, поэтому без точной базы переключать
    нечего (`can_full`); когда в источнике один файл, листать его некуда
    (`can_switch`); когда в файле одна правка, ходить курсору не по чему
    (`can_step`). Вьюер, открытый ИЗ ГРУППЫ разобранных (`can_add=False`,
    `can_revert=False`, §4.3 плана волны 4), не рекламирует ни `a`, ни `r`:
    дельта от ступени пуста — принимать и откатывать там нечего (ревью
    Задачи 10). `can_reset` (по умолчанию выключен — старые вызовы ничего не
    меняют) — только у файла с принятой базой: активного (глиф `↺` не
    обязателен — тай-брейк Р28 и источник «Ход» могут его гасить, не трогая
    саму базу, финальный фикс волны 4) либо разобранного «вручную».
    """
    parts = [_VIEWER_HEAD] if can_step else []
    if can_switch:
        parts.append(_VIEWER_FILES)
    if can_full:
        parts.append(_VIEWER_F_DIFF if full else _VIEWER_F_FULL)
    if can_add:
        parts.append(_VIEWER_ADD)
    if can_reset:
        parts.append(_VIEWER_RESET)
    if can_revert:
        parts.append(_VIEWER_REVERT)
    if can_sideways:
        parts.append(_VIEWER_SIDEWAYS)
    parts.append(_VIEWER_SCROLL_TAIL)
    return " · ".join(parts)


