def _survives_unreadable_edits(action):
    """Действие экрана над правками переживает отказ чтения — предупреждает, не падает.

    Индекс снимков читает почти каждое действие (превью и применение отката,
    принятие, снятие принятия, открытие вьюера), а замок индекса держит
    конкурирующий писатель — второе окно, CLI, субагенты. Граница — здесь, на
    действиях экрана, а не в точках чтения: читателей десятки, и закрывать их
    поштучно значило бы гоняться за трассами. Хранилище при этом не врёт:
    «принятое» не превращается в «не принято» — действие просто не выполняется,
    и повтор обычно проходит.

    Граница кончается там, где данные изменились: после мутации «не выполнено,
    повторите» — ложь, а молчание оставило бы список со старыми дельтами и
    модель с устаревшим представлением (§7). Хвост меняющих действий живёт под
    своей защитой — `DiffScreen._after_the_change`.
    """

    @functools.wraps(action)
    def guarded(self, *args, **kwargs):
        try:
            return action(self, *args, **kwargs)
        except OSError:  # TimeoutError замка — подкласс OSError
            _logger.warning(
                "действие над правками не выполнено", exc_info=True
            )
            self.app.notify(EDITS_UNREADABLE, severity="warning")
            return None

    return guarded


