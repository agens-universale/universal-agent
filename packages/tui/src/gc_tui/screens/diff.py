def overflow_note(paths: int) -> str:
    """Признание неполноты списка: команда тронула больше путей, чем пишет журнал.

    «Одна из команд этой сессии», а не «команда»: строка держится, пока жива
    сессия, и над списком из позднейших правок голое «команда» читалось бы как
    сказанное про них.

    Пути сверх потолка записи шелл-канала (``shell_delta.MAX_PATHS_PER_COMMAND``)
    не записаны — их нет в списке, и откатить их отсюда нельзя. Без этой строки
    список выглядел бы полным, и «откатить всё» молча оставило бы остальное
    изменённым. Числа потолка в тексте нет: сколько файлов в списке, и так
    говорит шапка.
    """
    return (
        f"⚠ Одна из команд этой сессии изменила {paths} {files_word(paths)} — "
        "в список попали не все: остальные здесь не видны, откатить их "
        "отсюда нельзя."
    )


