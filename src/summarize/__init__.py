"""Пакет суммаризации диалога.

Спецификация общего флоу (целевое поведение)
============================================

1. Контроллер (до вызова суммаризации)
   - Быстрая, дешёвая проверка объёма: **как сообщения есть в истории**, без
     форматирования под промпт (без обёрток, склейки в текст и т.п.).
   - Если порог по длине **превышен** — триггер суммаризации считается сработавшим
     (идём в суммаризацию). Детали порога и точки вызова — в контроллере/конфиге.

2. Внутри суммаризации (когда уже решили суммаризировать)
   а) **Форматирование всей истории**: приведение к единому текстовому виду для
      модели, с обрезкой отдельных сообщений по ``max_message_chars`` (чтобы
      один гигантский хвост не раздувал контекст).
   б) **Глобальный лимит диалога** (например ``summary_params.max_dialogue_chars``
      в ``config.yml``): после форматирования обрезаем **с конца** истории:
      сохраняем **хвост** — столько сообщений/текста, сколько укладывается в лимит.
      Если общий объем сообщений после шага (а) всё ещё очень длинный, суммарный
      размер может быть велик; тогда срабатывает следующий уровень.
   в) **Лимит на батч** (инкрементальная суммаризация): уже отформатированную и
      усечённую по (б) историю режем **на батчи** по второму лимиту (размер батча
      в символах/оценке длины), чтобы не слать один огромный запрос.

3. Такты (turns) и батчи
   - Историю в формате для суммаризации представляем как последовательность **тактов
     диалога**: пользователь–ответ ассистента, вызов инструмента–вывод инструмента
     (и совместимые варианты типов), без разрыва связанных пар.
   - **Батчи** строим **по тактам**: накапливаем такты с начала отобранного хвоста,
     пока оценка размера батча не упирается в лимит батча; следующий такт — в новый
     батч.

4. Сколько шагов LLM и память
   - **Один батч** (вся оставшаяся история одним куском):
     - шаг 1: получить структурированное сводное резюме диалога;
     - шаг 2: отдельный вызов — предложить/извлечь апдейт долговременной памяти
       (memory suggestions).
   - **Несколько батчей**:
     - **кумулятивно**: батч 1 → черновик сводки; батч 2 подмешывается к предыдущей
       сводке; …; итоговая сводка накапливается по батчам;
     - шаг обновления памяти **не выполняется** (только сводка по батчам).


Подмодули (текущая раскладка кода)
----------------------------------
- ``compaction`` — порог в контроллере, вызов оркестратора, ``apply_summary_state_patch``;
- ``thread_summarizer`` — сценарий батчей LLM и сборка результата;
- ``dialog_history`` — такты, батчи, текст истории для промпта;
- ``summary_validation`` — эвристики пригодности сводки;
- ``summary_serialization`` — текст сообщений для промпта/метрик, признак dialog summary в истории;
- ``summary_message_body`` — тело сообщения-резюме;
- ``summary_llm_steps`` — сжатие и починка сводки (отдельные вызовы LLM);
- ``memory_suggestions`` — шаг предложений для долговременной памяти;
- ``llm_chat`` — chat completions и логирование;
- ``prompt_loading`` — загрузка шаблона промпта;
- ``config`` — параметры порогов (в корне пакета рядом).
"""
