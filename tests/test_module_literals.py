"""Сетка против тихих поломок строковых ссылок на модули.

Раньше это был скрипт `tools_dev/check_module_literals.py`, который надо было
не забыть запустить руками. Теперь гоняется набором — 1.3 с на весь репозиторий.

Тест живёт в корневом наборе, а не в пакете: он сканирует ВЕСЬ репозиторий,
включая meta/, scripts/ и рецепты MCP, — как и контракт упаковки, он не
принадлежит ни одному дистрибутиву.

ГРАНИЦА ПРИМЕНИМОСТИ, проверена экспериментом 18.08.2026. Сетка ловит только
ТОЧЕЧНЫЕ ссылки — те, где имя модуля стоит в позиции резолва и потому отличимо
от обычной строки: monkeypatch.setattr("mod.attr"), sys.modules["mod"],
startswith("mod."), types.ModuleType, importlib.import_module, f-строки,
имена логгеров, uvicorn.run("mod:app").

Одиночное имя в множестве она НЕ поймает: в `_TUI_NAMES = {"tui", "textual"}`
строка "tui" неотличима от любой другой строки, и попытка её ловить дала бы
поток ложных срабатываний (ровно поэтому `_top_level_names()` уже сужен —
иначе `f"fs{i:04d}"` попадал под подозрение). Подложил туда старое имя и
убедился: сетка молчит.

Этот класс закрывает ПОВЕДЕНЧЕСКИЙ тест — packages/core/tests/test_missing_profile_guards.py,
который на той же подмене падает. Две сетки дополняют друг друга, ни одна из
них не полна сама по себе.
"""

from __future__ import annotations

from gc_testkit.module_literals import scan


def test_no_broken_module_literals():
    """Каждый строковый литерал, похожий на путь к модулю, обязан резолвиться.

    Класс, который ловится: кодмод импортов правит только узлы Import/ImportFrom,
    а имена модулей, записанные строкой, остаются со старым значением и молча
    перестают срабатывать — цикл выселения становится пустым, заглушки текут
    между тестами, набор при этом остаётся зелёным.
    """
    refs, problems = scan()
    assert refs, "сканер не нашёл ни одной ссылки — похоже, он смотрит не туда"

    assert not problems, "битые строковые ссылки на модули:\n" + "\n".join(
        f"  {r.file}:{r.line}  {r.literal!r} — {msg}" for r, msg in problems
    )
